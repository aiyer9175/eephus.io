  // ---- keeper calculator ----------------------------------------------------
  function keeperVerdict(d) {
    var pick = costPick(), be = breakEvenRound(d.rank);
    var edge = pick - d.rank;
    return { pick: pick, be: be, edge: edge, keep: edge >= 0 };
  }
  function renderKeeper() {
    var k = keeper();
    var list = sections().dynasty || [];
    var season = (S.data && S.data.season) || null;
    var form =
      '<div class="dyn-form">' +
      field("dyn-k-teams", "Teams in your league", k.teams, 2, 40) +
      field("dyn-k-slot", "Your first-round pick slot", k.slot, 1, k.teams) +
      field("dyn-k-round", "Round the keeper costs you", k.round, 1, 60) +
      field("dyn-k-window", "Your contention window, in years", k.window, 1, 12) +
      '<button type="button" class="dyn-btn" id="dyn-k-reset">Reset</button>' +
      "</div>";
    var explain =
      '<div class="dyn-note">Keeping a prospect costs a pick. This compares the pick you spend against where the ' +
      "dynasty board ranks him, in rank space, which is the only space we can be honest in: we have never fit a " +
      "dynasty dollar curve, so we do not print one. With " + k.teams + " teams and pick " + k.slot +
      ", a round " + k.round + " keeper costs pick <b>" + costPick() + "</b> overall. Everything you enter stays " +
      "in this browser.</div>";
    if (!list.length) {
      return explain + form + '<div class="dyn-note">The board has no rows yet, so there is nothing to price. ' +
        "The calculator still works: the pick math above updates as you type.</div>";
    }
    var shown = capRows(list.slice(0, 150));
    var rows = shown.map(function (d) {
      var v = keeperVerdict(d);
      var inWindow = (d.eta && season) ? ((Number(d.eta) - Number(season)) <= k.window) : null;
      return "<tr>" +
        '<td class="dyn-rk">' + esc(d.rank) + "</td>" +
        '<td class="dyn-nm">' + teamLogo(d.org) + " " + nameLink(d.mlbam, d.name) + "</td>" +
        "<td>" + esc(d.pos || "") + "</td>" +
        "<td>" + f0(d.efv) + "</td>" +
        "<td>" + esc(d.eta || "-") +
        (inWindow == null ? "" : ' <span class="dyn-win ' + (inWindow ? "dyn-win-in" : "dyn-win-out") +
          '">' + (inWindow ? "in window" : "after window") + "</span>") + "</td>" +
        "<td>R" + esc(v.be) + "</td>" +
        '<td class="dyn-sc ' + (v.keep ? "dyn-pos" : "dyn-neg") + '">' +
        (v.keep ? "keep" : "let go") + " (" + (v.edge >= 0 ? "+" : "") + esc(v.edge) + ")</td>" +
        "</tr>";
    }).join("");
    return explain + form +
      '<div class="dyn-note">Edge is the pick you spend minus his board rank. Positive means the board ranks him ' +
      "ahead of what the keeper costs. Keep by is the earliest round where that flips positive.</div>" +
      '<table class="dyn-table"><thead><tr><th>#</th><th>Prospect</th><th>Pos</th><th>eFV</th><th>ETA</th>' +
      "<th>Keep by</th><th>Verdict at R" + esc(k.round) + "</th></tr></thead><tbody>" + rows + "</tbody></table>" +
      gateNote(list.length, shown.length);
  }
