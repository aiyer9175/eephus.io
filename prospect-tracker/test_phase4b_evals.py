def test_eta_bases_match_km_artifact():
    """eta.BASE_YEARS is the GATED table the committed artifact scored, and
    it stays anchored to the KM basis it was derived from.

    This used to assert exact equality with art["km_base_years_full_window"],
    which is the wrong invariant and it broke on 2026-08-04. That key is a RAW
    refit regenerated by every nightly run_monthly; BASE_YEARS is a table that
    only moves when it WINS the v39 gate (forward-chained debuted MAE and
    within-1y must both beat the incumbent on identical rows, overdue shift
    disclosed). Equating the two makes an ungated nightly refit the arbiter of
    a shipped constant, which is backwards.

    It is also a knife-edge. _km_table quantizes to 0.25, so a median that
    wobbles a hundredth of a year across a boundary flips the whole cell. That
    is exactly what happened: the 2026-08-04 refit read A+ 3.19 (boundary
    3.125) and CPX 4.40 (boundary 4.375), tripping A+ 3.0 -> 3.25 and CPX 4.25
    -> 4.5 with no new debut information behind it (debuted 4,138 -> 4,143;
    censored_active 2,171 -> 2,315). Re-gated on the v39 criterion, the refit
    LOSES both legs: MAE 1.440 -> 1.490 and within-1y 0.579 -> 0.561 on 3,454
    identical debuted rows (paired bootstrap dMAE CI95 [+0.041, +0.059],
    dWithin-1y CI95 [-0.024, -0.014], P(refit better) = 0.000 both). So the
    table correctly did not move. See the RE-GATED block in eta.py.

    What is asserted instead is the pair of things that were actually meant:

      1. SYNC. BASE_YEARS equals the artifact's live_base_years. That field is
         read off eta.BASE_YEARS when eta_backtest runs, so this fires the
         moment someone edits the constants without re-running the gate that
         justifies them. This is strictly the failure mode the original test
         was reaching for, and it does NOT fire on refit drift.
      2. ANCHORING. Every shipped base stays within ONE KM quantization step
         (0.25 yr) of the current refit. Inside one step the constant and the
         raw median are indistinguishable at the resolution the fitter emits;
         beyond it the KM basis has genuinely moved and the ship must be
         re-argued through eta_backtest, not silently absorbed. This is a
         different assertion, not a widened tolerance: it is paired with (1),
         which admits no tolerance at all.

    Plus the structural pins: KM coverage, the monotone ladder, DSL hand-set,
    MLB zero.
    """
    from eta import BASE_YEARS
    art = _load("eta_eval.json")
    km = art["km_base_years_full_window"]

    # (1) SYNC - zero tolerance. The artifact must have scored THIS table.
    live = art["live_base_years"]
    assert {k: v for k, v in BASE_YEARS.items() if k != "MLB"} == \
        pytest.approx(live), \
        (f"eta.BASE_YEARS {BASE_YEARS} is not the table eta_eval.json scored "
         f"({live}); re-run eta_backtest.py and re-argue the ship")

    # (2) ANCHORING - within one 0.25 KM quantization step of the live refit.
    for lvl, val in km.items():
        assert lvl in BASE_YEARS, f"KM level {lvl} has no shipped base"
        drift = abs(BASE_YEARS[lvl] - val)
        assert drift <= 0.25 + 1e-9, (
            f"BASE_YEARS[{lvl}]={BASE_YEARS[lvl]} has drifted {drift:.2f}y "
            f"from the KM median {val} (>1 quantization step); the KM basis "
            f"moved, so re-gate through eta_backtest.py")

    # Monotone ladder: further from MLB is never a shorter trip (v18 spacing).
    ladder = ["MLB", "AAA", "AA", "A+", "A", "CPX", "DSL"]
    seq = [BASE_YEARS[lv] for lv in ladder]
    assert seq == sorted(seq), f"base-years ladder not monotone: {seq}"

    assert BASE_YEARS["DSL"] == 7.5      # cure fraction, hand-set survives
    assert "DSL" not in km               # KM median undefined there
    assert BASE_YEARS["MLB"] == 0.0


