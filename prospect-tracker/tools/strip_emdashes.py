"""Site-wide em-dash and en-dash removal (Open Beta copy pass).

Replaces every em-dash in user-facing sources with plain punctuation:
  "word — word"  ->  "word - word"     (clause break)
  "— word" at a line/string start -> "- word"   (bullet)
  "word—word"    ->  "word - word"     (unspaced break)
The en-dash (U+2013) is banned too - it is almost always a numeric or
alpha range, so it collapses to a plain hyphen with no added spaces:
  "20–80"  ->  "20-80"   "$200K–$500K" -> "$200K-$500K"   "A–Z" -> "A-Z"
A spaced en-dash used as a clause break ("a – b") becomes " - ".
Anything left over collapses to "-". Double spaces introduced by the
swap collapse back to one.

The list below targets SOURCES (generators, app HTML, JS, CSS, README,
article markdown) plus the hand-committed data files the frontend
renders. Generated outputs (root HTML pages, data/glossary.json) are
rebuilt by their generators after this runs, so the fix sticks.

Run: python tools/strip_emdashes.py [--check]
  --check: report files that still contain em-dashes, exit 1 if any
           (used by the copy-audit test).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent

TARGETS: list[str] = [
    "README.md",
    "build_site.py",
    "build_glossary_data.py",
    "prospx/index.html",
    "content/articles/*.md",
    "content/team.json",
    "assets/*.js",
    "assets/*.css",
    "collegesavant/*.js",
    "assets/team/README.md",
    # generated outputs fixed in place too (regenerated by their builders,
    # but the repo copy should never ship an em-dash either way)
    "index.html",
    "articles/index.html",
    "articles/*/index.html",
    "forums/index.html",
    "fa/index.html",
    "projections/index.html",
    "mlbstats/index.html",
    "pal/index.html",
    "glossary/index.html",
    "team/index.html",
    # coverage-gap fix (copy audit 2026-07-16): pages users load that the
    # gate never scanned - clean today, guarded from here on
    "trademachine/index.html",
    "news/index.html",
    "sources/index.html",
    "teams/index.html",
    "report/index.html",
    "collegesavant/index.html",
    "404.html",
    "data/glossary.json",
    # hand-committed data the frontend renders
    "data/model_registry.json",
    "data/cba_rules.json",
    "data/state_demographics.json",
    "data/country_demographics.json",
    "data/draft_timeseries.json",
    "data/ifa_timeseries.json",
    "data/overseas_timeseries.json",
    # exporter-emitted copy (labels/notes that land in frontend JSON)
    "draft_export.py",
    "ifa_export.py",
    "overseas_export.py",
    "proj_export.py",
    "fa_export.py",
    "spotlights.py",
]

EM = "—"
EN = "–"  # U+2013 en-dash - banned like the em-dash (usually a range)


def _strip_line(line: str) -> str:
    # bullet at line start: "— item" -> "- item"
    line = re.sub(r"^(\s*)—\s*", r"\1- ", line)
    # spaced clause break: "a — b" -> "a - b"
    line = line.replace(f" {EM} ", " - ")
    # half-spaced variants
    line = line.replace(f"{EM} ", " - ").replace(f" {EM}", " - ")
    # unspaced break between words: "a—b" -> "a - b"
    line = re.sub(r"(?<=\S)—(?=\S)", " - ", line)
    # anything left
    line = line.replace(EM, "-")
    # en-dash: spaced use is a clause break -> " - "; an unspaced range
    # ("20–80") collapses to a plain hyphen with NO added spaces.
    line = line.replace(f" {EN} ", " - ")
    line = line.replace(f"{EN} ", " - ").replace(f" {EN}", " - ")
    line = re.sub(r"(?<=\S)–(?=\S)", "-", line)
    return line.replace(EN, "-")


def strip_emdashes(text: str) -> str:
    """Line-scoped: lines without an em/en-dash pass through UNTOUCHED (no
    collateral re-spacing of aligned code/comments); lines with one get
    the swap plus a collapse of any doubled interior spaces it produced."""
    out = []
    for line in text.split("\n"):
        if EM in line or EN in line:
            line = _strip_line(line)
            line = re.sub(r"(?<=\S)  +(?=\S)", " ", line)
        out.append(line)
    return "\n".join(out)


def _files() -> list[Path]:
    out: list[Path] = []
    for pat in TARGETS:
        out.extend(p for p in ROOT.glob(pat) if p.is_file())
    return sorted(set(out))


def main() -> int:
    check = "--check" in sys.argv
    dirty: list[str] = []
    changed = 0
    for p in _files():
        try:
            text = p.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if EM not in text and EN not in text:
            continue
        if check:
            dirty.append(str(p.relative_to(ROOT)))
            continue
        p.write_text(strip_emdashes(text), encoding="utf-8")
        changed += 1
        print(f"cleaned: {p.relative_to(ROOT)}")
    if check:
        if dirty:
            print("em/en-dashes remain in:", *dirty, sep="\n  ")
            return 1
        print("clean: no em/en-dashes in targeted sources")
        return 0
    print(f"{changed} files cleaned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
