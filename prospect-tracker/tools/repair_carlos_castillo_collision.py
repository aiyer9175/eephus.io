"""
repair_carlos_castillo_collision.py - one-off repair for the carlos_castillo
name-slug key collision.

THE BUG (found by test_identity_collisions 2026-07-29): two different humans
normalize to the slug "carlos_castillo".

  INCUMBENT  mlbam 807962, b. 2006-02-04, RHP, Pirates org.
             Owns: FanGraphs snapshots 2024-02-14 (SP/PIT rank 29 FV40) and
             2024-08-01 (SP/PIT rank 28 FV40); the career_stats line
             (2026 A+ South Atlantic, PIT, era 6.00, ip 27.0, k_per_9 9.0);
             the 2026 statline (embedded mlbam_id 807962); the milb headshot.

  NEWCOMER   mlbam 837825, b. 2008-09-15, OF, Angels org.
             Arrived on the 2026-07-23 FanGraphs trade-deadline board
             (OF/LAA rank 37 FV35) and landed on the incumbent's key.
             He ALSO already had a separate unresolved-id key,
             "carlos_castillo__noid", from the 2026-02-12 board
             (OF/LAA rank 35 FV35).

Consequences on the served board: the active row (overall_rank 1506) is a
chimera. It is labelled OF/LAA from the newcomer's snapshot while carrying the
incumbent pitcher's mlbam id, statline and career line, so the C4 side check
reads claimed_side=H against fielded_side=P over 126 fielded games. The
players row is itself a Frankenstein: the newcomer's position/org (OF/LAA)
paired with the incumbent's birth_date (2006-02-04), and is_pitcher forced to 0
which mis-frames the pitcher's own statline as a hitter line.

THE REPAIR (follows the jose_a_valdez precedent exactly):
  (a) the INCUMBENT is never re-keyed. "carlos_castillo" stays the pitcher:
      players row restored to SP / PIT / is_pitcher=1 / b. 2006-02-04.
  (b) the NEWCOMER's rows move to "carlos_castillo_laa", the discriminated key
      registered in scrapers._SPLIT_KEYS[("carlos_castillo", 837825)]:
        - the 2026-07-23 trade-deadline snapshot (OF/LAA), and
        - every row still parked on the interim "carlos_castillo__noid" key
          (snapshot 2026-02-12, players, acquisitions, roster_status), so the
          outfielder ends up with ONE key instead of two.
  (c) rows that cannot be attributed with confidence are LISTED and left
      alone. metric_snapshots and trade_value_history accumulated under the
      merged entity and stay with the incumbent by incumbency; they are
      reported, not moved.

The 2026 statline payload carries is_pitcher=false with hitter-shaped fields
because players.is_pitcher had been overwritten to 0. That payload is
regenerated by the next stats refresh once is_pitcher is correct, so it is
reported and left alone rather than hand-edited.

Idempotent: re-running after --apply reports "already repaired" and changes
nothing.

Usage:
    python tools/repair_carlos_castillo_collision.py            # dry run
    python tools/repair_carlos_castillo_collision.py --apply    # write
    python tools/repair_carlos_castillo_collision.py --db PATH  # other DB
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

OLD_KEY = "carlos_castillo"          # stays with the INCUMBENT pitcher
NOID_KEY = "carlos_castillo__noid"   # interim newcomer key, folded in
NEW_KEY = "carlos_castillo_laa"      # discriminated key for the NEWCOMER

INCUMBENT_MLBAM = 807962
INCUMBENT_POS = "SP"
INCUMBENT_ORG = "PIT"
INCUMBENT_BIRTH = "2006-02-04"

KID_MLBAM = 837825
KID_POS = "OF"
KID_ORG = "LAA"
KID_BIRTH = "2008-09-15"

# The newcomer's snapshots, identified by (date, position, org). The pitcher
# never appears as an OF, so position+org is a sufficient discriminator here.
KID_SNAPSHOT_DATES = ("2026-02-12", "2026-07-23")

DEFAULT_DB = Path(__file__).resolve().parent.parent / "prospects.db"


def _p(action: str, *detail):
    print(f"  [{action}] " + " ".join(str(d) for d in detail))


def repair(db_path: Path, apply: bool) -> int:
    mode = "APPLY" if apply else "DRY-RUN"
    print(f"=== repair_carlos_castillo_collision [{mode}] db={db_path} ===")
    if not db_path.exists():
        print(f"FATAL: db not found: {db_path}")
        return 2

    con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    changes = 0
    ambiguous: list[str] = []

    # ------------------------------------------------------------------
    # 1. snapshots - move the newcomer's OF/LAA rows onto the split key.
    # ------------------------------------------------------------------
    print("\n-- snapshots --")
    rows = con.execute(
        "SELECT id, snapshot_date, interval_label, player_key, position, org "
        "FROM snapshots WHERE player_key IN (?, ?, ?) ORDER BY snapshot_date",
        (OLD_KEY, NOID_KEY, NEW_KEY),
    ).fetchall()
    for r in rows:
        if r["player_key"] == NEW_KEY:
            _p("ok", f"already on {NEW_KEY}: {r['snapshot_date']} "
               f"{r['position']}/{r['org']}")
            continue
        is_kid = (r["position"] == KID_POS and r["org"] == KID_ORG
                  and r["snapshot_date"] in KID_SNAPSHOT_DATES)
        if not is_kid:
            _p("keep", f"incumbent snapshot {r['snapshot_date']} "
               f"{r['position']}/{r['org']} stays on {OLD_KEY}")
            continue
        _p("rekey", f"snapshot id={r['id']} {r['snapshot_date']} "
           f"({r['interval_label']}) {r['position']}/{r['org']}: "
           f"{r['player_key']} -> {NEW_KEY}")
        con.execute("UPDATE snapshots SET player_key = ? WHERE id = ?",
                    (NEW_KEY, r["id"]))
        changes += 1

    # ------------------------------------------------------------------
    # 2. players - restore the incumbent, create/repair the newcomer.
    # ------------------------------------------------------------------
    print("\n-- players --")
    inc = con.execute("SELECT * FROM players WHERE player_key = ?",
                      (OLD_KEY,)).fetchone()
    if inc is None:
        ambiguous.append(f"players[{OLD_KEY}]: row missing - NOT created")
    elif (inc["position"] == INCUMBENT_POS and inc["org"] == INCUMBENT_ORG
          and inc["is_pitcher"] == 1):
        _p("ok", f"already repaired: {OLD_KEY} is {INCUMBENT_POS}/"
           f"{INCUMBENT_ORG} is_pitcher=1")
    else:
        _p("restore", f"players[{OLD_KEY}]: "
           f"{inc['position']}/{inc['org']} is_pitcher={inc['is_pitcher']} "
           f"b.{inc['birth_date']} -> {INCUMBENT_POS}/{INCUMBENT_ORG} "
           f"is_pitcher=1 b.{INCUMBENT_BIRTH} (the Pirates RHP)")
        con.execute(
            "UPDATE players SET position = ?, org = ?, is_pitcher = 1, "
            "birth_date = ? WHERE player_key = ?",
            (INCUMBENT_POS, INCUMBENT_ORG, INCUMBENT_BIRTH, OLD_KEY))
        changes += 1

    kid = con.execute("SELECT * FROM players WHERE player_key = ?",
                      (NEW_KEY,)).fetchone()
    if kid is not None:
        _p("ok", f"already repaired: {NEW_KEY} players row exists")
    else:
        _p("create", f"players[{NEW_KEY}]: Carlos Castillo / {KID_POS} / "
           f"{KID_ORG} / is_pitcher=0 / b.{KID_BIRTH} (the Angels OF)")
        con.execute(
            "INSERT INTO players (player_key, player_name, position, org, "
            "is_pitcher, birth_date) VALUES (?, ?, ?, ?, 0, ?)",
            (NEW_KEY, "Carlos Castillo", KID_POS, KID_ORG, KID_BIRTH))
        changes += 1

    # ------------------------------------------------------------------
    # 3. fold the interim __noid key into the split key.
    # ------------------------------------------------------------------
    print(f"\n-- fold {NOID_KEY} -> {NEW_KEY} --")
    tables = [r[0] for r in con.execute(
        "SELECT name FROM sqlite_master WHERE type='table'").fetchall()]
    for t in sorted(tables):
        cols = [c[1] for c in con.execute(f"PRAGMA table_info({t})").fetchall()]
        if "player_key" not in cols:
            continue
        n = con.execute(
            f"SELECT COUNT(*) FROM {t} WHERE player_key = ?",
            (NOID_KEY,)).fetchone()[0]
        if not n:
            continue
        if t == "players":
            # the split key already carries the authoritative row
            _p("drop", f"players[{NOID_KEY}]: interim duplicate of the "
               f"same human, superseded by {NEW_KEY}")
            con.execute("DELETE FROM players WHERE player_key = ?", (NOID_KEY,))
            changes += 1
            continue
        clash = con.execute(
            f"SELECT COUNT(*) FROM {t} WHERE player_key = ?",
            (NEW_KEY,)).fetchone()[0]
        if clash:
            ambiguous.append(
                f"{t}: both {NOID_KEY} ({n}) and {NEW_KEY} ({clash}) rows "
                "exist - NOT merged, resolve manually")
            continue
        _p("rekey", f"{t}: {n} row(s) {NOID_KEY} -> {NEW_KEY}")
        con.execute(f"UPDATE {t} SET player_key = ? WHERE player_key = ?",
                    (NEW_KEY, NOID_KEY))
        changes += n

    # ------------------------------------------------------------------
    # 4. report (do not move) the merged-entity history + the statline.
    # ------------------------------------------------------------------
    print("\n-- reported, NOT touched --")
    for t in ("metric_snapshots", "trade_value_history"):
        if t not in tables:
            continue
        n = con.execute(f"SELECT COUNT(*) FROM {t} WHERE player_key = ?",
                        (OLD_KEY,)).fetchone()[0]
        if n:
            _p("keep", f"{t}: {n} row(s) accumulated under the merged entity "
               f"stay with the incumbent {OLD_KEY} by incumbency")

    st = con.execute("SELECT season, payload_json FROM statlines "
                     "WHERE player_key = ?", (OLD_KEY,)).fetchone()
    if st is not None:
        try:
            payload = json.loads(st["payload_json"])
        except ValueError:
            payload = {}
        mid = payload.get("mlbam_id")
        if mid == INCUMBENT_MLBAM:
            _p("keep", f"statlines[{OLD_KEY}] season={st['season']} carries "
               f"the incumbent mlbam {mid}; is_pitcher="
               f"{payload.get('is_pitcher')!r} is stale and regenerates on "
               "the next stats refresh now that players.is_pitcher=1")
        else:
            ambiguous.append(
                f"statlines[{OLD_KEY}]: payload mlbam_id={mid!r} is neither "
                f"{INCUMBENT_MLBAM} nor {KID_MLBAM} - NOT touched")

    photo = con.execute("SELECT mlbam_id FROM player_photos "
                        "WHERE player_key = ?", (OLD_KEY,)).fetchone()
    if photo is not None:
        if photo["mlbam_id"] == INCUMBENT_MLBAM:
            _p("keep", f"player_photos[{OLD_KEY}] mlbam {photo['mlbam_id']} "
               "is the incumbent's headshot; correct as-is")
        else:
            ambiguous.append(
                f"player_photos[{OLD_KEY}]: mlbam {photo['mlbam_id']} is not "
                f"the incumbent {INCUMBENT_MLBAM} - NOT touched")

    cache_file = db_path.parent / ".cache" / "mlbam_ids.json"
    if cache_file.exists():
        try:
            idc = json.loads(cache_file.read_text(encoding="utf-8"))
            if idc.get(OLD_KEY) == KID_MLBAM:
                _p("advisory", f".cache/mlbam_ids.json still binds {OLD_KEY} "
                   f"-> {KID_MLBAM}; the resolver's collision guard "
                   "(stats._apply_collision_guard) heals this stale binding "
                   "on the next resolve, no manual edit needed")
            else:
                _p("ok", f".cache/mlbam_ids.json[{OLD_KEY}] = "
                   f"{idc.get(OLD_KEY)!r} (no stale newcomer binding)")
        except ValueError:
            pass

    if ambiguous:
        print("\n-- AMBIGUOUS rows (listed, NOT touched) --")
        for a in ambiguous:
            _p("ambiguous", a)

    if apply:
        con.commit()
        print(f"\n=== APPLIED: {changes} write(s) committed ===")
    else:
        con.rollback()
        print(f"\n=== DRY-RUN: {changes} write(s) planned; re-run with "
              "--apply to execute ===")
    con.close()
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Repair the carlos_castillo name-slug key collision "
                    "(Angels OF vs Pirates RHP).")
    ap.add_argument("--apply", action="store_true",
                    help="write the changes (default is a dry run)")
    ap.add_argument("--db", type=Path, default=DEFAULT_DB,
                    help=f"path to prospects.db (default: {DEFAULT_DB})")
    args = ap.parse_args()
    return repair(args.db, apply=args.apply)


if __name__ == "__main__":
    sys.exit(main())
