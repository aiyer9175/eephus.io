"""SCRATCH (read-only feasibility check) - convexity / Jensen gap in FA rational value.

Does NOT import or mutate any fa_* module state beyond reading exported JSON +
value_framework's pure kernel. Writes nothing.

Question: served `rational` = sum_t PV( tiered_war_value(E[W_t]) ).
Because tiered_war_value is convex (floored at 0, rising per-win rate),
E[ value(W_t) ] > value( E[W_t] ). How big is the gap in dollars, per member?
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from value_framework import tiered_war_value_usd, _config  # noqa: E402

cfg = _config()
R = float(cfg["discount_rate"])
INFL = float(cfg.get("dollars_per_war_inflation", 0.0))
FLAT = float(cfg["dollars_per_war"]["flat"])

cls = json.loads((ROOT / "data" / "fa_class.json").read_text(encoding="utf-8"))
DPW = float(cls["dpw_usd"])
LEVEL = DPW / FLAT


def rational(path, n):
    tot = 0.0
    for t, w in enumerate(path[:n]):
        tot += (tiered_war_value_usd(w) * LEVEL * ((1 + INFL) ** t)) / ((1 + R) ** t)
    return tot


# Gauss-Hermite nodes/weights for E[f(Z)], Z~N(0,1)  (probabilists', 9-point)
import numpy as np  # noqa: E402
x, w = np.polynomial.hermite_e.hermegauss(15)
w = w / w.sum()

Z10 = -1.2815515655446004

rows = []
for m in cls["members"]:
    p10 = m.get("warPathP10")
    p90 = m.get("warPathP90")
    mid = m.get("warPath")
    yrs = m.get("projYears")
    if not (p10 and p90 and mid and yrs):
        continue
    n = min(yrs, len(mid), len(p10), len(p90))
    if n < 1:
        continue
    base = rational(mid, n)
    # The three paths are generated by ONE year-1 shock decayed along the same
    # curves, so the path is (approximately) affine in the shock:
    #   W_t(z) ~= mid_t + s_t * z   with  s_t from the P90 side (z=+1.2816)
    #   and s_t^lo from the P10 side (two-piece / skewed).
    s_hi = [(p90[t] - mid[t]) / abs(Z10) for t in range(n)]
    s_lo = [(mid[t] - p10[t]) / abs(Z10) for t in range(n)]
    # two-piece normal integration (mode at the point path, different scale
    # either side) - matches the measured left-skew of the Gate-1 residuals.
    exp_val = 0.0
    for zi, wi in zip(x, w):
        s = s_hi if zi >= 0 else s_lo
        path_z = [max(0.0, mid[t] + s[t] * zi) for t in range(n)]
        exp_val += wi * rational(path_z, n)
    # symmetric-normal variant (scale = average of the two sides) for a range
    s_sym = [(s_hi[t] + s_lo[t]) / 2 for t in range(n)]
    exp_sym = 0.0
    for zi, wi in zip(x, w):
        path_z = [max(0.0, mid[t] + s_sym[t] * zi) for t in range(n)]
        exp_sym += wi * rational(path_z, n)
    rows.append({
        "name": m["name"], "pos": m.get("pos"), "yrs": yrs,
        "served_rational": base, "E_rational_2p": exp_val, "E_rational_sym": exp_sym,
        "guar": m.get("projGuar"), "served_surplus": m.get("surplus"),
        "warY1": m.get("warY1"),
    })

print(f"n = {len(rows)} members with full bands")
gap2 = [(r["E_rational_2p"] - r["served_rational"]) for r in rows]
gapS = [(r["E_rational_sym"] - r["served_rational"]) for r in rows]
rel2 = [g / max(r["served_rational"], 1) for g, r in zip(gap2, rows)]


def pct(v, q):
    v = sorted(v)
    return v[int(q * (len(v) - 1))]


print(f"two-piece  gap $M: median {pct(gap2,.5)/1e6:8.1f}  mean {sum(gap2)/len(gap2)/1e6:8.1f}"
      f"  p10 {pct(gap2,.1)/1e6:8.1f}  p90 {pct(gap2,.9)/1e6:8.1f}")
print(f"symmetric  gap $M: median {pct(gapS,.5)/1e6:8.1f}  mean {sum(gapS)/len(gapS)/1e6:8.1f}")
print(f"relative gap (two-piece): median {pct(rel2,.5):.3f}  p10 {pct(rel2,.1):.3f}  p90 {pct(rel2,.9):.3f}")
print(f"class total served rational  ${sum(r['served_rational'] for r in rows)/1e9:.2f}B")
print(f"class total E[rational] 2p   ${sum(r['E_rational_2p'] for r in rows)/1e9:.2f}B")

# how many members would flip verdict sign on surplus?
flips = sum(1 for r, g in zip(rows, gap2)
            if r["served_surplus"] is not None
            and (r["served_surplus"] < 0) != ((r["served_surplus"] + g) < 0))
print(f"members whose SURPLUS SIGN flips under E[value]: {flips} / {len(rows)}")

rows.sort(key=lambda r: -(r["E_rational_2p"] - r["served_rational"]))
print("\nlargest absolute gaps:")
for r in rows[:8]:
    g = r["E_rational_2p"] - r["served_rational"]
    print(f"  {r['name']:24s} {r['pos']:4s} y{r['yrs']}  served ${r['served_rational']/1e6:7.1f}M"
          f"  E ${r['E_rational_2p']/1e6:7.1f}M  gap ${g/1e6:6.1f}M")
print("\nlargest RELATIVE gaps (low-WAR / high-vol):")
rows.sort(key=lambda r: -((r["E_rational_2p"] - r["served_rational"]) / max(r["served_rational"], 1)))
for r in rows[:8]:
    g = (r["E_rational_2p"] - r["served_rational"]) / max(r["served_rational"], 1)
    print(f"  {r['name']:24s} {r['pos']:4s} warY1 {r['warY1']:5.2f}  served ${r['served_rational']/1e6:7.1f}M  rel +{g:.2%}")
