"""W3 PAL-XRV gate lab -> data/pal_stuff_xrv_eval.json.

Registration: docs/wills-2026-07-23/GATES.md section "W3 PAL-XRV" (frozen
before any arm ran; one attempt; marginal = FAIL; COVERAGE-STARVED is a
recorded verdict, not a retry ticket).

REGISTERED THRESHOLDS (hard-coded, never retuned):
  COVERED_MIN     = 12        covered conversions per direction; below this the
                              verdict is COVERAGE-STARVED (ARM-1 stays OFF, the
                              per-type sidecar + ARM-2 ship display-only)
  COVERAGE        = >= 100 recent AAA pitches (sidecar season == pre-year or
                              pre-year - 1; pal_conversion.PAL_XRV_MIN_PITCHES)
  BLEND_W         = 0.5       est_woba read vs usage-weighted per-type aStuff+
                              (pal_conversion.PAL_XRV_W)
  P1              rho(FIT_blend, war_delta) >= rho(FIT_incumbent, war_delta)
                              on the IDENTICAL conversion set, per direction
  P2              bootstrap gap (rho_blend - rho_incumbent) lo95 > -0.01,
                              2000 reps, seed 20260714 (the PAL harness
                              convention), per direction
  P3              pitchers WITHOUT AAA coverage produce byte-identical FIT
                              scores with the blend armed (0 mismatches)
  SEED = 20260714   BOOT = 2000   GATE_LO95 = -0.01

Machinery: reuses tools/pal_backtest_lab.run() (the T1-6 repaired harness) for
the event set, feature assembly, baselines and the war_delta target; the blend
arm attaches sidecar coverage to the SAME arms and rescores. Also verifies the
STEP-1 sidecar invariance (pooled stuff_plus / n_pitches / season byte-equal to
the pre-change snapshot in .cache/pal_xrv/) and emits 3 ARM-2 before/after
recommend_pitch examples for the consolidator's eyeball pass.

Run:  python tools/pal_xrv_lab.py          (writes data/pal_stuff_xrv_eval.json
                                            + .cache/pal_xrv/w3_detail.json)
"""
from __future__ import annotations

import json
import os
import sys
from datetime import date
from pathlib import Path

_HERE = Path(__file__).resolve().parent
ROOT = Path(os.environ.get("EEPHUS_ROOT") or _HERE.parent)
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import bullpen_export as be                     # noqa: E402
import pal_conversion as pc                     # noqa: E402
import pal_export as pe                         # noqa: E402
import pal_backtest_lab as pbl                  # noqa: E402

SEED = 20260714
BOOT = 2000
GATE_LO95 = -0.01
COVERED_MIN = 12
DIRECTIONS = ("RP->SP", "SP->RP")

EVAL_PATH = ROOT / "data" / "pal_stuff_xrv_eval.json"
SIDECAR_PATH = ROOT / "data" / "stuff_plus_aaa.json"
PRE_SNAPSHOT = ROOT / ".cache" / "pal_xrv" / "stuff_plus_aaa_pre_w3.json"
DETAIL_PATH = ROOT / ".cache" / "pal_xrv" / "w3_detail.json"


def sidecar_invariance() -> dict:
    """STEP-1 clause: every pre-change player's pooled stuff_plus / n_pitches /
    season byte-identical in the regenerated by_type sidecar."""
    old = json.loads(PRE_SNAPSHOT.read_text(encoding="utf-8"))
    new = json.loads(SIDECAR_PATH.read_text(encoding="utf-8"))
    po, pn = old["players"], new["players"]
    diffs = []
    for k, ro in po.items():
        rn = pn.get(k)
        if rn is None:
            diffs.append(k)
            continue
        for f in ("stuff_plus", "n_pitches", "season"):
            if json.dumps(ro.get(f)) != json.dumps(rn.get(f)):
                diffs.append(f"{k}:{f}")
    lg = (new.get("meta") or {}).get("league_xrv_by_type") or {}
    return {
        "rule": "pooled fields byte-identical for every pre-change player",
        "n_players_pre": len(po), "n_players_post": len(pn),
        "same_key_set": set(po) == set(pn),
        "n_pooled_field_diffs": len(diffs), "diffs_sample": diffs[:10],
        "n_rows_with_by_type": sum(1 for r in pn.values() if r.get("by_type")),
        "n_league_xrv_types": len(lg),
        "pass": (set(po) == set(pn) and not diffs),
    }


def _coverage(players: dict, mlbam: int, py: int):
    """The registered coverage gate at the event's TRUE pre-year (delegates to
    the production gate in pal_export so the lab tests the shipped code)."""
    return pe.aaa_coverage(players, mlbam, py)


def _blend_fits(ctx, aaa_players) -> list:
    """Rescore every event with the blend ARMED (coverage attached to the same
    arms run() built). Returns rows aligned 1:1 with ctx['recs']:
    {fit_blend, covered}."""
    out = []
    for e, rec in zip(ctx["events"], ctx["recs"]):
        assert e["mlbam"] == rec["mlbam"] and e["year"] == rec["year"]
        py = e["pre"]["season"]
        byyr = ctx["by_pid"].get(e["mlbam"], {})
        pre_row = byyr.get(py)
        fit = None
        cov = _coverage(aaa_players, e["mlbam"], py)
        if pre_row and pre_row.get("mlbam") in ctx["arsenal_by_year"].get(py, {}):
            arm = pe.build_arm(pre_row, ctx["arsenal_by_year"].get(py, {}),
                               ctx["velo_by_year"].get(py, {}), ctx["platoon"], py)
            arm.p_throws = ctx["hand"].get(arm.mlbam)
            arm.was_starter = pe._was_starter(ctx["by_pid"], arm.mlbam, py)
            arm.aaa_by_type = cov                 # the ONLY delta vs incumbent
            f = pc.rp_sp_fit(arm) if e["direction"] == "RP->SP" else pc.sp_rp_fit(arm)
            if arm.arsenal:
                fit = f["fit"]
        out.append({"fit_blend": fit, "covered": cov is not None})
    return out


def _arm2_examples(ctx, league_xrv, cap=3) -> list:
    """Before/after recommend_pitch on current-season RP candidates; the first
    `cap` arms whose recommendation CHANGES under the xRV ranking."""
    season = pbl.HISTORY_YEARS[-1]
    changed, sampled = [], 0
    for r in ctx["rows_by_year"].get(season) or []:
        if be.ip_to_float(r.get("IP")) < pe.CAND_MIN_IP:
            continue
        if pc.role_of(r.get("G"), r.get("GS"), r.get("IP")) != "RP":
            continue
        if r["mlbam"] not in ctx["arsenal_by_year"].get(season, {}):
            continue
        arm = pe.build_arm(r, ctx["arsenal_by_year"][season],
                           ctx["velo_by_year"][season], ctx["platoon"], season)
        before = pc.recommend_pitch(arm)
        after = pc.recommend_pitch(arm, league_xrv)
        sampled += 1
        if json.dumps(before, sort_keys=True) != json.dumps(after, sort_keys=True):
            changed.append({"mlbam": arm.mlbam, "name": arm.name, "team": arm.team,
                            "families_present": sorted(pc._families(arm)),
                            "before": before, "after": after})
        if len(changed) >= cap:
            break
    return [{"n_candidates_walked": sampled}] + changed


def run() -> dict:
    inv = sidecar_invariance()
    print(f"w3: sidecar invariance pass={inv['pass']} "
          f"(diffs={inv['n_pooled_field_diffs']}, by_type rows="
          f"{inv['n_rows_with_by_type']}/{inv['n_players_post']})")

    sidecar = json.loads(SIDECAR_PATH.read_text(encoding="utf-8"))
    aaa_players = sidecar["players"]
    league_xrv = (sidecar.get("meta") or {}).get("league_xrv_by_type") or {}

    # ---- incumbent harness (T1-6 repaired), one run, shared ctx -------------
    ctx: dict = {}
    doc0 = pbl.run(log=print, _ctx=ctx)

    # ---- blend arm on the SAME arms -----------------------------------------
    blend = _blend_fits(ctx, aaa_players)

    # ---- P3: uncovered arms byte-identical ----------------------------------
    p3_checked = p3_mis = 0
    for rec, b in zip(ctx["recs"], blend):
        if b["covered"]:
            continue
        p3_checked += 1
        if rec["fit"] != b["fit_blend"]:
            p3_mis += 1
    p3 = {"rule": "uncovered pitchers byte-identical FIT with the blend armed",
          "n_uncovered_checked": p3_checked, "n_mismatches": p3_mis,
          "pass": p3_mis == 0}
    print(f"w3: P3 uncovered-invariance mismatches={p3_mis}/{p3_checked}")

    # ---- coverage join + per-direction gate ---------------------------------
    per_dir = {}
    for d in DIRECTIONS:
        rows = [(rec, b) for rec, b in zip(ctx["recs"], blend)
                if rec["direction"] == d]
        prim = [(rec, b) for rec, b in rows
                if rec["post_closed"] and rec["fit"] is not None
                and b["fit_blend"] is not None and rec["war_delta"] is not None
                and all(rec[k] is not None for k in ("b_kbb", "b_neg_era", "b_index"))]
        cov_all = sum(1 for rec, b in rows if b["covered"])
        cov_gate = sum(1 for rec, b in prim if b["covered"])
        covered_events = [{"mlbam": rec["mlbam"], "name": rec["name"],
                           "year": rec["year"], "pre_season": rec["pre_season"],
                           "in_gate_set": (rec, b) in prim}
                          for rec, b in rows if b["covered"]]
        entry = {
            "n_events": len(rows), "n_gate_set": len(prim),
            "n_covered_all_events": cov_all,
            "n_covered_in_gate_set": cov_gate,
            "covered_min_bar": COVERED_MIN,
            "covered_events": covered_events,
        }
        if cov_gate < COVERED_MIN:
            entry["gate"] = {"run": False,
                             "verdict": "COVERAGE-STARVED",
                             "reason": f"covered-in-gate {cov_gate} < {COVERED_MIN}"}
        else:
            fit_i = [rec["fit"] for rec, _ in prim]
            fit_b = [b["fit_blend"] for _, b in prim]
            tgt = [rec["war_delta"] for rec, _ in prim]
            rho_i = pbl._rho(fit_i, tgt)
            rho_b = pbl._rho(fit_b, tgt)
            gap = pbl._boot_gap(fit_b, fit_i, tgt, seed=SEED, reps=BOOT)
            p1 = rho_b is not None and rho_i is not None and rho_b >= rho_i
            p2 = gap is not None and gap["lo95"] > GATE_LO95
            entry["gate"] = {
                "run": True, "seed": SEED, "boot": BOOT,
                "rho_incumbent": rho_i, "rho_blend": rho_b,
                "gap_ci_blend_minus_incumbent": gap,
                "P1_rho_blend_ge_incumbent": bool(p1),
                "P2_gap_lo95_gt_-0.01": bool(p2),
                "verdict": "PASS" if (p1 and p2) else "FAIL",
            }
        per_dir[d] = entry
        print(f"w3: {d}: events={len(rows)} gate_set={len(prim)} "
              f"covered_all={cov_all} covered_gate={cov_gate} -> "
              f"{entry['gate'].get('verdict')}")

    # ---- ARM-2 examples ------------------------------------------------------
    arm2 = _arm2_examples(ctx, league_xrv)

    # ---- overall verdict -----------------------------------------------------
    if not (inv["pass"] and p3["pass"]):
        overall = "FAIL"
    elif any(per_dir[d]["gate"]["verdict"] == "COVERAGE-STARVED" for d in DIRECTIONS):
        overall = "COVERAGE-STARVED"
    elif all(per_dir[d]["gate"]["verdict"] == "PASS" for d in DIRECTIONS):
        overall = "PASS"
    else:
        overall = "FAIL"

    starved = [d for d in DIRECTIONS if per_dir[d]["gate"].get("verdict") == "COVERAGE-STARVED"]
    reading = (
        "Mechanism story: the per-type AAA aStuff+ sidecar reads cleanly (pooled "
        "scores byte-identical; by_type on every scored pitcher) and the blend "
        "machinery is inert without coverage (P3 clean). The conversion event set "
        "is MLB veterans flipping roles, and AAA pitch tracking only begins in "
        "2023, so a conversion can only be covered when its TRUE pre-year is "
        "2023+ AND the pitcher threw >= 100 AAA pitches that year or the prior "
        "one - the a-priori expected starvation recorded in the registration. "
        f"Starved directions: {starved or 'none'}. ARM-1 stays OFF; the per-type "
        "sidecar + the xRV-ranked pitch-add recommender (ARM-2, flag "
        "EEPHUS_PAL_XRV_RECO) are the shippable display product. Revival key: "
        "re-gate when enough post-2023 AAA graduates accumulate conversion "
        "events (each season adds pre-years with tracking; ~2028 before "
        f"{COVERED_MIN} covered events per direction is plausible)."
    )

    doc = {
        "generated_at": "2026-07-23",
        "model": "pal_stuff_xrv (W3 PAL-XRV: per-pitch-type AAA aStuff+ into "
                 "PAL conversion inputs)",
        "lab": "tools/pal_xrv_lab.py",
        "experiment": {
            "registration": "docs/wills-2026-07-23/GATES.md section W3 PAL-XRV",
            "seed": SEED, "bootstrap_reps": BOOT,
            "flags": {"EEPHUS_PAL_XRV": "ARM-1 stuff-read blend (default OFF)",
                      "EEPHUS_PAL_XRV_RECO": "ARM-2 xRV-ranked pitch-add "
                                             "(default OFF, display only)"},
            "registered_bars": {
                "coverage_floor_pitches": pc.PAL_XRV_MIN_PITCHES,
                "coverage_window": "sidecar season == pre-year or pre-year - 1",
                "covered_min_per_direction": COVERED_MIN,
                "blend_w": pc.PAL_XRV_W,
                "P1": "rho(FIT_blend, war_delta) >= rho(FIT_incumbent, war_delta), identical set, per direction",
                "P2": f"bootstrap gap lo95 > {GATE_LO95} (seed {SEED}, {BOOT} reps), per direction",
                "P3": "uncovered pitchers byte-identical FIT with the blend armed",
            },
        },
        "sidecar_invariance": inv,
        "clause_P3_invariance": p3,
        "per_direction": per_dir,
        "arm2_recommend_pitch": {
            "league_xrv_candidates": {pt: league_xrv.get(pt) for fam in
                                      pc.XRV_FAMILY_CANDIDATES.values() for pt in fam},
            "examples_before_after": arm2,
        },
        "incumbent_harness": {
            "source": "tools/pal_backtest_lab.py run() (T1-6 repaired harness)",
            "n_conversions": doc0["n_conversions"],
            "per_direction_incumbent": {d: {
                "n_gate": doc0["per_direction"][d]["n_gate"],
                "rho_fit_war_delta": doc0["per_direction"][d]["rho_fit_war_delta"],
            } for d in DIRECTIONS},
        },
        "verdict": {
            "status": overall,
            "per_clause": {
                "sidecar_invariance": "PASS" if inv["pass"] else "FAIL",
                "P3": "PASS" if p3["pass"] else "FAIL",
                **{f"P1+P2 {d}": per_dir[d]["gate"].get("verdict")
                   for d in DIRECTIONS},
            },
            "consequence": ("ARM-1 (EEPHUS_PAL_XRV) stays OFF; per-type sidecar "
                            "+ ARM-2 ship display-only"
                            if overall != "PASS" else
                            "central flip of EEPHUS_PAL_XRV + PAL export regen"),
        },
        "reading": reading,
    }
    EVAL_PATH.write_text(json.dumps(doc, indent=1), encoding="utf-8")
    print(f"w3: wrote {EVAL_PATH}")
    DETAIL_PATH.parent.mkdir(parents=True, exist_ok=True)
    DETAIL_PATH.write_text(json.dumps(
        {"blend_rows": blend, "recs": ctx["recs"]}, indent=1), encoding="utf-8")
    print(f"w3: wrote {DETAIL_PATH}")
    print("W3 VERDICT:", overall)
    return doc


if __name__ == "__main__":
    run()
