"""generate_brand_assets.py - a shim kept so the old command still works.

Every brand image is generated by tools/pixel_brand.py from the hand decisions
in tools/pixel_brand_src.py (PB-09, owner ask 2): the letters are PixelMplus12
Bold's own bitmap sampled from the vendored TTF, with no system font, no RNG
and no anti-aliasing, so every box writes the same pixels. This file runs that
generator and keeps the two jobs the generator does not do:

    the served favicon set: favicon.ico (root; crawlers request /favicon.ico
    unconditionally), assets/favicon.svg, assets/favicon-32.png and
    assets/favicon-16.png (the footer mark), PX-23's copies of the
    generator's ball strikes, served until build_site.py's PIXEL_BRAND flag
    points the pages at assets/brand/;
    the branding/icons/ copies of the four app icons (test_pixel_brand.py
    checks them against assets/brand/).

The vector-era PIL drawings this file used to make (a share card in capitals
with a system font, a P/X monogram in whatever serif the machine had, an arc
drawn with dots) are gone. Since the PIXEL_BRAND flip (PB-10) the old served
paths assets/apple-touch-icon.png, assets/icon-*.png and
assets/share-default.png hold copies of the pixel set in assets/brand/, so a
page, manifest or old link that names them gets the same art; this file
refreshes those copies (serve_pixel_copies) on every full run.

Usage:  python tools/generate_brand_assets.py              generator, favicon set, copies
        python tools/generate_brand_assets.py --favicons  the favicon set only
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import pixel_brand as PB  # noqa: E402  (tools/ sibling, fontTools + PIL)


def make_favicons() -> None:
    """The tiny favicons and the footer mark: the clean ball, hand-hinted
    (owner answer PX-Q4, final-pass plan 5.7 PX-23).

    Every small size is its own hand-tuned strike from tools/pixel_brand.py
    (pixel_brand_src.py holds the pixels), since a 48 px drawing downsampled
    to 16 read as an "O" on a browser tab (Part 8 defect F6): 16 and 32 are
    exact strikes, 48 is strike 24 at 2x, the SVG favicon is strike 16 on a
    16-unit grid with crisp edges, and the footer mark is strike 16 drawn 1:1.
    Same anatomy at every size: cream face, navy rim, the inward ") (" seams
    (owner answer PB-Q2) in the light ramp."""
    fav = PB.favicon_strikes()
    fav[48].save(ROOT / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)],
                 append_images=[fav[16], fav[32]])
    fav[32].save(ROOT / "assets" / "favicon-32.png")
    fav[16].save(ROOT / "assets" / "favicon-16.png")
    (ROOT / "assets" / "favicon.svg").write_bytes(
        PB.standalone_svg(PB.ball(16), "light", "eephus.io", 1).encode("utf-8"))
    print("wrote favicon.ico (16/32/48 strikes), assets/favicon-32.png, "
          "assets/favicon-16.png (footer mark), assets/favicon.svg (strike 16)")


PIXEL_COPIES = ("apple-touch-icon.png", "icon-192.png", "icon-512.png", "icon-maskable-512.png",
                "share-default.png")


def serve_pixel_copies() -> None:
    """PB-10: the pixel app icons and default card over the vector-era files at
    their old served paths (assets/), byte for byte from assets/brand/."""
    for name in PIXEL_COPIES:
        shutil.copyfile(ROOT / "assets" / "brand" / name, ROOT / "assets" / name)
    print(f"copied {len(PIXEL_COPIES)} pixel files from assets/brand/ to their old served paths")


def assemble_branding() -> None:
    """Copy the four app icons into branding/icons/ (branding/marks, animated,
    social and the transparent balls come from tools/pixel_brand.py itself;
    the favicon set, manifest and woff2 subsets are documented in assets/)."""
    B = ROOT / "branding"
    pairs = [
        (ROOT / "assets" / "apple-touch-icon.png",   B / "icons" / "apple-touch-icon.png"),
        (ROOT / "assets" / "icon-192.png",           B / "icons" / "icon-192.png"),
        (ROOT / "assets" / "icon-512.png",           B / "icons" / "icon-512.png"),
        (ROOT / "assets" / "icon-maskable-512.png",  B / "icons" / "icon-maskable-512.png"),
    ]
    n = 0
    for src, dst in pairs:
        if src.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            n += 1
    print(f"assembled branding/ bundle ({n} artifacts copied)")


if __name__ == "__main__":
    if "--favicons" in sys.argv[1:]:
        # The PX-23 set only: the hinted favicons and footer mark. Leaves every
        # other committed image alone.
        make_favicons()
        sys.exit(0)
    rc = PB.main([])
    make_favicons()
    serve_pixel_copies()
    assemble_branding()
    sys.exit(rc)
