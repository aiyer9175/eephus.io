def render_readme_routes() -> str:
    """The README routes block, sentinels included (LF line endings)."""
    import build_site

    nav: dict[str, str] = {}
    for item in build_site.NAV_ITEMS:
        if isinstance(item, dict):
            for _key, label, href in item["children"]:
                nav[href] = f"{label} ({item['group']})"
        else:
            _key, label, href = item
            nav[href] = label

    rows: list[tuple[str, str, str]] = []
    main_src = inspect.getsource(build_site.main)
    for rel, fn_name in _WRITE_CALL.findall(main_src):
        if not (rel.endswith(".html")):
            continue  # robots.txt and sitemap.xml are files, not pages
        route = _route_of(rel)
        refs = set(_ASSET_REF.findall(inspect.getsource(getattr(build_site, fn_name))))
        apps = sorted(a for a in refs if a not in _SHARED_ASSETS)
        src = f"`build_site.{fn_name}()`"
        if apps:
            src += " + " + ", ".join(f"`assets/{a}`" for a in apps)
        rows.append((route, nav.get(route) or _UNNAVED_PAGE_NAMES.get(route, "-"), src))
    rows += [
        ("/prospx/", nav.get("/prospx/", "PROSPX"),
         "hand-maintained `prospx/index.html` (single-file app)"),
        ("/collegesavant/", nav.get("/collegesavant/", "CollegeSavant"),
         "hand-maintained `collegesavant/index.html` + `collegesavant/app.js`"),
        ("/collegesavant/pitcher_index.html", "CollegeSavant pitchers",
         "hand-maintained `collegesavant/pitcher_index.html` + `collegesavant/pitcher_app.js`"),
    ]
    order = {href: i for i, href in enumerate(nav)}
    rows.sort(key=lambda r: (0, order[r[0]]) if r[0] in order else (1, r[0]))

    lines = [
        README_ROUTES_BEGIN,
        "",
        f"{len(rows)} routes. Top-nav pages come first, in nav order; the rest are",
        "linked from those pages or redirect. Full inventory with payloads: `SITE_MAP.md`.",
        "",
        "| Route | Page | Source |",
        "|---|---|---|",
    ]
    for route, page, src in rows:
        lines.append(f"| `{route}` | {_clean(page)} | {src} |")
    lines += ["", README_ROUTES_END]
    return "\n".join(lines)


def sync_readme_routes(text: str) -> str:
    """Replace the ROUTES block in README text (keeps the file's line endings)."""
    nl = "\r\n" if "\r\n" in text else "\n"
    lf = text.replace("\r\n", "\n")
    begin = lf.index(README_ROUTES_BEGIN)
    end = lf.index(README_ROUTES_END) + len(README_ROUTES_END)
    out = lf[:begin] + render_readme_routes() + lf[end:]
    return out.replace("\n", nl)


