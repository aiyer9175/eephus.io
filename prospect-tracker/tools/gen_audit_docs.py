def render_one(name: str) -> str:
    if name == "MODEL_REGISTRY.md":
        return render_model_registry()
    if name == "SITE_MAP.md":
        return render_site_map()
    if name == "DATA_SOURCES.md":
        p = ROOT / name
        return render_data_sources(p.read_text(encoding="utf-8") if p.exists() else None)
    raise KeyError(name)


def _freshness_cross_check() -> None:
    """Advisory only: warn on stderr when live artifact ages disagree with the
    registry's stamps (doc content never depends on this, by design)."""
    import model_registry
    reg = model_registry.load()
    live = model_registry.freshness(reg)
    for m in reg.get("models", []):
        f = live.get(m.get("model_id"))
        if f and m.get("stale") is not None and bool(m["stale"]) != f["stale"]:
            print(f"warning: stale flag drift for {m['model_id']}: "
                  f"stamped {m['stale']} vs live {f['stale']} "
                  "(rerun model_registry.refresh_stamps() on the pipeline)",
                  file=sys.stderr)


def main() -> None:
    _freshness_cross_check()
    for name in GENERATED_DOCS:
        content = render_one(name)
        assert content.startswith(GEN_HEADER)
        (ROOT / name).write_bytes(content.encode("utf-8"))
        print(f"wrote {name} ({len(content.splitlines())} lines)")
    readme = ROOT / "README.md"
    text = readme.read_bytes().decode("utf-8")
    synced = sync_readme_routes(text)
    if synced != text:
        readme.write_bytes(synced.encode("utf-8"))
        print("wrote README.md routes block")


if __name__ == "__main__":
    main()
