def render_model_registry() -> str:
    import model_registry

    reg = model_registry.load()
    live_problems = model_registry.validate(reg)
    models = reg.get("models", [])

    counts: dict[str, int] = {}
    for m in models:
        counts[m.get("verdict", "?")] = counts.get(m.get("verdict", "?"), 0) + 1
    count_line = ", ".join(
        f"{v}: {counts.get(v, 0)}" for v in model_registry.VERDICTS
    )

    lines = [
        GEN_HEADER,
        "# Model Registry",
        "",
        "Source: `data/model_registry.json` via `model_registry.load()`. Freshness columns",
        "(artifact age / stale) are the registry's own stamps, written by",
        f"`model_registry.refresh_stamps()` on the pipeline cadence (STALE_DAYS = {model_registry.STALE_DAYS});",
        f"stamped as of **{reg.get('checked_at', '?')}**. `validate()` at generation time: "
        + ("**clean**." if not live_problems else f"**{len(live_problems)} problem(s)** (listed below)."),
        "",
        f"**{len(models)} models.** Verdicts: {count_line}.",
        "",
        "## Instrument boundary",
        "",
        "Instruments and policy state are NOT models and carry no rows: the shadow",
        "ledger, the two-start ledger, the market publishability gate, the efv_alerts",
        "feed, the amateur_leagues ingest, and identity resolution. Each moves or gates",
        "data without making a predictive claim of its own. The boundary keeps the",
        "standing rule crisp: every model gets a row, and a row asserts a claim that",
        "can be measured.",
        "",
        "| model_id | summary | surface | predicts | champion | baseline | metric | verdict | eval artifact | age (d) | stale |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for m in models:
        art = m.get("eval_artifact") or "-"
        age = m.get("artifact_age_days")
        stale = m.get("stale")
        lines.append(
            "| " + " | ".join([
                f"`{_clean(m.get('model_id', '?'))}`",
                _clean(m.get("summary", "")),
                _clean(m.get("surface", ""), 60),
                _clean(m.get("predicts", ""), 130),
                _clean(m.get("champion", ""), 80),
                _clean(m.get("baseline", ""), 80),
                _clean(m.get("metric", ""), 80),
                f"**{_clean(m.get('verdict', '?'))}**",
                (f"`{_clean(art)}`" if art != "-" else "-"),
                ("-" if age is None else str(age)),
                ("-" if stale is None else ("yes" if stale else "no")),
            ]) + " |"
        )

    lines += [
        "",
        f"Stored problems at last refresh: {reg.get('problems') or 'none'}.",
    ]
    if live_problems:
        lines += ["", "Live `validate()` problems:", ""]
        lines += [f"- {_clean(p)}" for p in live_problems]
    lines += [
        "",
        "Verdict semantics (from `model_registry.py`): validated = committed forward",
        "backtest beats the stated baseline; provisional = partially measured;",
        "unvalidated = a predictive claim with no measurement yet;",
        "deprecated = failed validation and was retired or demoted.",
        "",
    ]
    return "\n".join(lines)


