"""Generator for the three INTROSPECTED audit deliverables at the repo root:

    MODEL_REGISTRY.md   from data/model_registry.json (model_registry.load())
    SITE_MAP.md         from build_site.NAV_ITEMS + build_site.main() + the
                        client apps' own payload fetches
    DATA_SOURCES.md     from run_monthly.py's phase structure + the docstrings
                        of the scraper/feed modules, PLUS a hand-curated prose
                        block preserved verbatim between the sentinels
                        "<!-- CURATED:BEGIN -->" / "<!-- CURATED:END -->"

Each output starts with a GENERATED header; test_generated_docs_in_sync.py
regenerates all three in memory and byte-compares them against the committed
files, so hand edits (outside the curated block) cannot survive.

Determinism contract: every byte of output is a pure function of committed
inputs (source files + data/model_registry.json). In particular the doc
renders the registry's OWN stamped freshness fields (artifact_age_days /
stale, written by model_registry.refresh_stamps() on the pipeline cadence)
rather than live mtime-vs-today ages, which would drift the byte-compare
daily. model_registry.freshness() IS still called at generation time and any
disagreement with the stamps is printed to stderr as a warning; it never
lands in the doc. Nothing here is stochastic (no seeds needed).

Run: python tools/gen_audit_docs.py
"""
