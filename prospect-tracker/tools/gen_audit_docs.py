def _clean(text: str, limit: int = 0) -> str:
    """One-line, pipe-safe, em/en-dash-free table cell text."""
    t = strip_emdashes(str(text))
    t = re.sub(r"\s+", " ", t).strip().replace("|", "\\|")
    if limit and len(t) > limit:
        t = t[: limit - 3].rstrip() + "..."
    return t


_JSON_TOKEN = re.compile(r"[A-Za-z0-9_]+\.json\b")
# In JS/HTML count *.json names in fetch strings and header comments; the
# negative lookahead drops `r.json()` response-method calls and the 3-char
# minimum drops one-letter variables. Some apps (fa.js) fetch through a
# dynamic `load("name")` helper, so those names are collected too.
_JS_PAYLOAD = re.compile(r"[\"'`/ (]((?:data/)?[a-z][a-z0-9_]{2,}\.json)\b(?!\()")
_JS_LOAD = re.compile(r'\bload\(\s*"([a-z0-9_]+)"')


def _payloads_of(paths: list[Path]) -> list[str]:
    """Sorted unique data-payload basenames fetched by the given JS/HTML files."""
    names: set[str] = set()
    for p in paths:
        if not p.exists():
            continue
        src = p.read_text(encoding="utf-8")
        for tok in _JS_PAYLOAD.findall(src):
            names.add(tok.split("/")[-1])
        for tok in _JS_LOAD.findall(src):
            names.add(tok + ".json")
    return sorted(names)


