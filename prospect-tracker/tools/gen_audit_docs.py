def _phase_rows(src: str) -> dict[str, list[tuple[str, list[str]]]]:
    """{function_name: [(phase_label, [json tokens referenced]), ...]} for
    run_daily / main / rebuild_only, introspected from run_monthly.py.

    Phases are the logged `with _step("...")` names; for main() the numbered
    banner comments (# --- N. ... ---) fill in the blocks that have no _step
    wrapper (2c, 3a, 3d*, 3e, 3f, 5), matched by their leading step token.
    The json column lists every *.json literal in the phase's source block:
    writes AND inputs (the writes usually happen inside the called module,
    so reads-vs-writes cannot be told apart from this file alone).
    """
    tree = ast.parse(src)
    spans = {n.name: (n.lineno, n.end_lineno) for n in tree.body
             if isinstance(n, ast.FunctionDef)
             and n.name in ("run_daily", "main", "rebuild_only")}
    lines = src.split("\n")

    def token_of(label: str) -> str:
        return label.split()[0].rstrip(".") if label.split() else ""

    out: dict[str, list[tuple[str, list[str]]]] = {}
    for fname, (lo, hi) in spans.items():
        phases: list[tuple[int, str]] = []   # (line_no, label)
        step_tokens: set[str] = set()
        for i in range(lo, hi):
            m = _STEP_LINE.search(lines[i - 1])
            if m:
                phases.append((i, m.group(1)))
                step_tokens.add(token_of(m.group(1)))
        if fname == "main":
            for i in range(lo, hi):
                m = _BANNER_LINE.match(lines[i - 1])
                if not m:
                    continue
                # strip trailing dash padding (some banners pad with U+2014)
                label = m.group(1).rstrip("-\u2014 .,").strip()
                if label.count("(") > label.count(")"):
                    label += " ...)"  # banner text wrapped to the next line
                if label and token_of(label) not in step_tokens:
                    phases.append((i, label + " (no _step wrapper)"))
            # post-export best-effort tail: everything after finish_run().
            for i in range(lo, hi):
                if re.match(r"^\s{8}finish_run\(run_id", lines[i - 1]) and phases \
                        and i > max(ln for ln, _ in phases):
                    phases.append((i, "post-export passes (best-effort: board/farm "
                                      "snapshots, source_backtest, consensus + draft "
                                      "weight A/B, eta_backtest, editorial_eval, "
                                      "model-registry freshness, headshots, chained "
                                      "daily refresh)"))
                    break
        phases.sort()
        if fname == "rebuild_only":
            phases = [(lo, "rebuild-only hook (no scrape): rebuild timeseries + "
                           "movement + eFV consolidation + GRPO rescore")]
        rows = []
        for idx, (ln, label) in enumerate(phases):
            end = phases[idx + 1][0] if idx + 1 < len(phases) else hi + 1
            block = "\n".join(lines[ln - 1: end - 1])
            toks = sorted(set(_JSON_TOKEN.findall(block)))
            rows.append((label, toks))
        out[fname] = rows
    return out


def _module_doc_rows() -> list[tuple[str, str]]:
    rows = []
    for name in _SOURCE_MODULES:
        p = ROOT / name
        if not p.exists():
            continue
        try:
            doc = ast.get_docstring(ast.parse(p.read_text(encoding="utf-8")))
        except SyntaxError:
            doc = None
        first = (doc or "(no module docstring)").split("\n\n")[0]
        rows.append((name, _clean(first, 240)))
    return rows


def _curated_block(existing_text: str | None) -> str:
    if existing_text:
        m = re.search(re.escape(CURATED_BEGIN) + r".*?" + re.escape(CURATED_END),
                      existing_text, re.DOTALL)
        if m:
            return m.group(0)
    return _DEFAULT_CURATED


def render_data_sources(existing_text: str | None = None) -> str:
    src = (ROOT / "run_monthly.py").read_text(encoding="utf-8")
    rows = _phase_rows(src)

    lines = [
        GEN_HEADER,
        "# Data Sources",
        "",
        "Skeleton introspected from `run_monthly.py` (phase structure) and the",
        "scraper/feed module docstrings; the freshness-risk block at the bottom is",
        "curated and survives regeneration verbatim. The json column lists every",
        "`*.json` literal in a phase's source block: outputs AND inputs (most writes",
        "happen inside the called module, so this file alone cannot split them).",
        "",
    ]
    for fname, title in (("run_daily", "Daily pipeline (`run_monthly.run_daily`)"),
                         ("main", "Monthly pipeline (`run_monthly.main`)"),
                         ("rebuild_only", "Rebuild-only hook (`run_monthly.rebuild_only`)")):
        lines += [f"## {title}", "", "| phase | data/*.json referenced in the phase block |", "|---|---|"]
        for label, toks in rows.get(fname, []):
            lines.append(f"| {_clean(label, 160)} | {_clean(', '.join(toks) if toks else '-', 400)} |")
        lines.append("")

    lines += [
        "## Scraper / feed modules (first docstring paragraph)",
        "",
        "| module | role |",
        "|---|---|",
    ]
    for name, doc in _module_doc_rows():
        lines.append(f"| `{name}` | {doc} |")

    lines += ["", _curated_block(existing_text), ""]
    return "\n".join(lines)


