def _route_of(rel: str) -> str:
    rel = rel.replace("{a['slug']}", "<slug>")
    if rel.endswith("index.html"):
        return "/" + rel[: -len("index.html")]
    return "/" + rel


def render_site_map() -> str:
    import build_site

    lines = [
        GEN_HEADER,
        "# Site Map",
        "",
        "Source of truth: `build_site.NAV_ITEMS` (the single nav definition; `_nav()`,",
        "the homepage sidebar, and the hand-maintained static nav copies all mirror it,",
        "guarded by `test_collegesavant_nav_in_sync.py`) plus the `_write()` calls in",
        "`build_site.main()`. Client-app payloads are introspected from each app's own",
        "fetch strings.",
        "",
        "## Top navigation (`build_site.NAV_ITEMS`)",
        "",
        "| # | key | label | href | group |",
        "|---|---|---|---|---|",
    ]
    n = 0
    for item in build_site.NAV_ITEMS:
        if isinstance(item, dict):
            for key, label, href in item["children"]:
                n += 1
                lines.append(f"| {n} | `{key}` | {_clean(label)} | `{href}` | {_clean(item['group'])} |")
        else:
            key, label, href = item
            n += 1
            lines.append(f"| {n} | `{key}` | {_clean(label)} | `{href}` | - |")

    lines += [
        "",
        "## PROSPX sub-sections (`build_site.PROSPX_SUBNAV`)",
        "",
        "| label | deep link |",
        "|---|---|",
    ]
    for label, href in build_site.PROSPX_SUBNAV:
        lines.append(f"| {_clean(label)} | `{href}` |")

    # ---- generated surfaces, introspected from build_site.main() ----------
    lines += [
        "",
        "## Surface inventory",
        "",
        "### Generated by `build_site.main()`",
        "",
        "Every editorial page also loads the shared runtime (nav, account/forum layer,",
        "starfield background, glossary tooltips via `assets/eephus-gl.js`, which fetches",
        "`glossary.json` + `player_links.json`, and table/chart export). The payload",
        "column below lists only what the surface's own module app fetches.",
        "",
        "| route | generator | client app | data payloads consumed | notes |",
        "|---|---|---|---|---|",
    ]
    main_src = inspect.getsource(build_site.main)
    for rel, fn_name in _WRITE_CALL.findall(main_src):
        fn = getattr(build_site, fn_name)
        fn_src = inspect.getsource(fn)
        apps = sorted({a for a in _ASSET_REF.findall(fn_src) if a not in _SHARED_ASSETS})
        payloads = _payloads_of([ROOT / "assets" / a for a in apps])
        lines.append("| " + " | ".join([
            f"`{_route_of(rel)}`",
            f"`build_site.{fn_name}()`",
            (", ".join(f"`assets/{a}`" for a in apps) if apps else "server-rendered"),
            (", ".join(f"`{p}`" for p in payloads) if payloads else "-"),
            _clean(_ROUTE_NOTES.get(rel, "")),
        ]) + " |")

    # ---- hand-maintained surfaces -----------------------------------------
    prospx_payloads = _payloads_of([ROOT / "prospx" / "index.html"])
    lines += [
        "",
        "### Hand-maintained (NOT written by build_site.py)",
        "",
        "| route | file | client app | data payloads consumed | notes |",
        "|---|---|---|---|---|",
        "| `/prospx/` | `prospx/index.html` | inline single-file app | "
        + ", ".join(f"`{p}`" for p in prospx_payloads)
        + " | prospect board, farm systems, draft, IFA, overseas, time machine; nav wired by hand |",
        "| `/collegesavant/` | `collegesavant/index.html` | `collegesavant/app.js` | "
        "data embedded as JS modules (`data.js`, `hitter_year_data.js`, `team_names.js`), no JSON fetch "
        "| hitter app + college-to-pro translation; nav wired by hand |",
        "| `/collegesavant/pitcher_index.html` | `collegesavant/pitcher_index.html` | `collegesavant/pitcher_app.js` | "
        "data embedded as JS modules (`pitcher_data.js`, `pitch_shape_data_*.js`, `team_names.js`), no JSON fetch "
        "| pitcher app; nav wired by hand |",
        "",
        "Cache note: the hand-maintained pages load `assets/site.css` UNVERSIONED (no",
        "content-hash query), so stale CSS can outlive a deploy there; the generated",
        "pages get the hash from `build_site._asset_ver()`.",
        "",
    ]
    return "\n".join(lines)


