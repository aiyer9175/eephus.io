"""CollegeSavant names a team code only when the name is verified (owner answer M20-1).

Census M03-11: the hand dictionaries composed a school part with a three-letter
mascot part and printed wrong schools ("Arizona State Wildcats" for Arizona,
"Nevada Wolverines", "Georgia Panthers" for Georgia State). team_names.js is now
generated by college_team_map.py from the NCAA D-I list and the learned
code-to-school map; an unverified code prints as the code.

Unit tests drive verify_code on fixtures; artifact tests read the SERVED
collegesavant/team_names.js and data/collegesavant_team_map.json.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

import college_team_map as ctm

ROOT = Path(__file__).parent
CS = ROOT / "collegesavant"
DOC = ROOT / "data" / "collegesavant_team_map.json"

_IDX = ctm.ncaa_index([("Arizona", 1), ("Arizona St.", 2), ("Tennessee", 3), ("Kennesaw St.", 4),
                       ("Navy", 5), ("Abilene Christian", 6), ("Georgia", 7), ("Georgia St.", 8),
                       ("Georgia Tech", 9), ("St. Thomas (MN)", 10), ("Ohio St.", 11),
                       ("Oklahoma St.", 12), ("Oregon St.", 13)])


def test_learned_school_on_the_ncaa_list_verifies():
    v = ctm.verify_code("ARI_WIL", _IDX, "Arizona")
    assert (v["source"], v["name"], v["ncaa"]) == ("learned+ncaa", "Arizona", "Arizona")


def test_learned_school_that_does_not_fit_the_letters_is_ignored():
    # Two Kennesaw State players drafted from Tennessee voted KEN_OWL to Tennessee.
    v = ctm.verify_code("KEN_OWL", _IDX, "Tennessee")
    assert v["source"] != "learned+ncaa" and v["name"] != "Tennessee"
    v = ctm.verify_code("ZZZ_OWL", _IDX, "Tennessee")
    assert v["source"] is None and "does not fit" in v["note"]


def test_letters_entry_needs_one_school_and_one_payload_code():
    assert ctm.verify_code("ABI_WIL", _IDX, None)["source"] == "dict+ncaa"
    # GEO fits Georgia, Georgia State and Georgia Tech: no letters guess.
    assert ctm.verify_code("GEO_PAN", _IDX, None)["source"] is None
    # NAV_COL beside NAV_MID: the letters belong to two payload codes.
    sib = {"nav": 2}
    assert ctm.verify_code("NAV_COL", _IDX, None, sib)["source"] is None
    assert ctm.verify_code("NAV_MID", _IDX, None, sib)["source"] is None


def test_per_code_entry_matches_one_school_and_prints_no_mascot():
    v = ctm.verify_code("OSU_BUC", _IDX, None)
    assert (v["source"], v["name"]) == ("dict+ncaa", "Ohio State")
    # "St. Thomas University" is not "St. Thomas (MN)": the state stays in the key.
    assert ctm.verify_code("THO_M", _IDX, None)["source"] is None


# --------------------------------------------------------------------------- #
# Served artifacts
# --------------------------------------------------------------------------- #
def _doc() -> dict:
    return json.loads(DOC.read_text(encoding="utf-8"))


def _js_map() -> dict:
    text = (CS / "team_names.js").read_text(encoding="utf-8")
    body = text[text.index("const TEAM_MAP = {") + len("const TEAM_MAP = "):]
    body = body[:body.index("};") + 1]
    out = {}
    for m in re.finditer(r'^\s*"?([^":\s]+)"?: \[("(?:[^"\\]|\\.)*"), (\d+)\],', body, re.M):
        out[m.group(1)] = (json.loads(m.group(2)), int(m.group(3)))
    return out


def test_served_map_is_the_verified_table():
    doc, js = _doc(), _js_map()
    ver = {t["code"]: t for t in doc["table"] if t["source"]}
    assert set(js) == set(ver)
    assert doc["mapped"] == len(ver) == len(js)
    for code, (name, espn) in js.items():
        t = ver[code]
        assert t["source"] in ("learned+ncaa", "dict+ncaa", "learned+dict"), code
        assert name == t["name"] and espn == (t["espn_id"] or 0), code
        assert t["note"], code
        names = [name] + ([t["ncaa"]] + ctm._ALIASES.get(t["ncaa"], []) if t["ncaa"] else [])
        assert ctm.fits(code, names), code
    meta = re.search(r"const TEAM_MAP_META = \{ codes: (\d+), mapped: (\d+)",
                     (CS / "team_names.js").read_text(encoding="utf-8"))
    assert (int(meta.group(1)), int(meta.group(2))) == (doc["codes"], doc["mapped"])


def test_served_map_covers_every_payload_code():
    doc = _doc()
    assert {t["code"] for t in doc["table"]} == set(ctm.payload_codes())


def test_espn_logo_ids_come_from_the_prospx_map():
    from player_images import _COLLEGE_TEAM_IDS
    ids = set(_COLLEGE_TEAM_IDS.values())
    used = {e for _n, e in _js_map().values() if e}
    assert used and used <= ids


def test_ncaa_names_are_on_the_cached_list():
    import college_stats as cst
    rows = cst.d1_team_list(ctm.NCAA_YEAR, cache_only=True)
    if not rows:
        pytest.skip("no cached NCAA D-I list on this machine")
    names = {s for s, _ in rows}
    bad = [t["code"] for t in _doc()["table"] if t["ncaa"] and t["ncaa"] not in names]
    assert not bad, bad[:5]


MiniRacer = pytest.importorskip("py_mini_racer").MiniRacer


def test_resolver_and_logo_helper():
    ctx = MiniRacer()
    ctx.eval((CS / "team_names.js").read_text(encoding="utf-8"))
    assert ctx.eval('formatTeamName("LSU_TIG")') == "Louisiana State"
    assert ctx.eval('teamLogoUrl("LSU_TIG")') == "https://a.espncdn.com/i/teamlogos/ncaa/500/99.png"
    assert ctx.eval('teamLogoUrl("NEB")') == "logos/NEB.png"
    assert ctx.eval('teamLogoUrl("ZZZ_QQQ")') is None
    note = ctx.eval("teamMapNote()")
    doc = _doc()
    assert f"{doc['mapped']} of {doc['codes']} team codes" in note
