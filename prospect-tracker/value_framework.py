def _print_worked_example(fv: float, is_pitcher: bool, position: str | None) -> None:
    role = _role_key(is_pitcher)
    probs = p_bucket_given_fv(fv, is_pitcher)
    svs = _effective_bucket_sv(is_pitcher, position, None, 0.0, _war_scale_for(fv, role))
    mids = _calibrated_midpoints(role)
    print(f"\nWorked example: FV {fv} {role}{'/'+position if position else ''}")
    print(f"  six-year avg WAR anchor target = {fv_to_6yr_avg_war(fv)}")
    print(f"  P(bucket|FV) + per-bucket midpoint WAR + bucket_SV:")
    contrib = 0.0
    for i, b in enumerate(_BUCKETS):
        c = probs[i] * svs[i]
        contrib += c
        print(f"    {b:8} P={probs[i]:.4f}  mid_war={mids[i]:.3f}  "
              f"bucket_SV=${svs[i]/1e6:8.2f}M  contrib=${c/1e6:8.2f}M")
    print(f"  weighted six-year avg WAR = {expected_six_year_avg_war(fv, is_pitcher):.3f}")
    print(f"  expected surplus = ${contrib/1e6:.2f}M  "
          f"(surplus_value_mm -> {surplus_value_mm(fv, is_pitcher, position)})")
    if is_pitcher:
        rs = pitcher_role_split(fv, True, position)
        print(f"  role split: SP={rs['sp']:.3f}  RP={rs['rp']:.3f}  bust={rs['bust']:.3f}  "
              f"(sum={rs['sp']+rs['rp']+rs['bust']:.3f})")
    d = sv_distribution(fv, is_pitcher, position)
    if d:
        pcts = " ".join(f"{k}=${v}M" for k, v in d["percentiles"].items())
        print(f"  DISTRIBUTION: mean=${d['mean']}M (mc_mean=${d['mc_mean']}M) std=${d['std']}M")
        print(f"    percentiles: {pcts}")
        print(f"    P(bust)={d['p_bust']}  P(SV>${d['threshold_mm']}M)={d['p_above_threshold']}  "
              f"downside(CVaR worst-quartile)=${d['downside_metric']}M  "
              f"risk_score(lambda={d['risk_aversion_lambda']})=${d['risk_adjusted_score']}M")
        # Prompt E: which headline metrics to surface is read from output.report,
        # never hardcoded.
        rep = _output_cfg().get("report", [])
        if rep:
            rep_vals = {
                "mean": f"${d['mean']}M",
                "p_bust": d["p_bust"],
                "prob_sv_gt_threshold": d["p_above_threshold"],
            }
            shown = "  ".join(f"{m}={rep_vals[m]}" for m in rep if m in rep_vals)
            if shown:
                print(f"    report (output.report): {shown}")


