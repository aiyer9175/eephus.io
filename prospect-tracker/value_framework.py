def _count_table(role: str) -> dict:
    """{fv_axis: [count per bucket]} for a role (round(pct*n); excludes small n)."""
    cfg = _config()
    table = cfg[f"p_bucket_given_fv_{role}"]
    axes = cfg["fit"]["role_axes"]
    excl = int(cfg["fit"]["exclude_n_le"])
    out = {}
    for key, row in table.items():
        n = int(row["n"])
        if n <= excl:
            continue
        out[float(axes[key])] = [int(round(float(row[b]) * n)) for b in _BUCKETS]
    return out


def _reconstruct_cuts(a: float, log_incs) -> list[float]:
    """4 ordered cutpoints from a base + 3 positive log-increments (exp ensures
    monotonicity for ANY parameter value, so posterior samples stay valid)."""
    cuts = [float(a)]
    for li in log_incs:
        cuts.append(cuts[-1] + math.exp(float(li)))
    return cuts


def _hier_unpack(theta) -> tuple[float, list[float], float, list[float]]:
    """theta = [s_h, s_p, a_h, lh0, lh1, lh2, a_p, lp0, lp1, lp2]."""
    return (float(theta[0]), _reconstruct_cuts(theta[2], theta[3:6]),
            float(theta[1]), _reconstruct_cuts(theta[6], theta[7:10]))


def _theta_role_params(theta, is_pitcher: bool) -> tuple[float, list[float]]:
    if is_pitcher:
        return float(theta[1]), _reconstruct_cuts(theta[6], theta[7:10])
    return float(theta[0]), _reconstruct_cuts(theta[2], theta[3:6])


def _num_hessian(f, x, eps: float = 1e-4):
    """Central finite-difference Hessian (for the Laplace covariance)."""
    import numpy as np
    n = len(x)
    H = np.zeros((n, n))
    fx = f(x)
    e = np.eye(n) * eps
    fp = [f(x + e[i]) for i in range(n)]
    fm = [f(x - e[i]) for i in range(n)]
    for i in range(n):
        H[i, i] = (fp[i] - 2 * fx + fm[i]) / eps ** 2
        for j in range(i + 1, n):
            fpp = f(x + e[i] + e[j]); fmm = f(x - e[i] - e[j])
            fpm = f(x + e[i] - e[j]); fmp = f(x - e[i] + e[j])
            H[i, j] = H[j, i] = (fpp - fpm - fmp + fmm) / (4 * eps ** 2)
    return H


def _fit_hierarchical_bayes(verbose: bool = False) -> dict:
    """Joint hitter+pitcher proportional-odds with PARTIAL POOLING (slopes and
    cutpoints shrink toward a shared mean), fit by MAP + Laplace covariance.
    Returns the MAP per-role point estimates + the joint posterior (theta_map,
    cov, layout) for credible intervals."""
    import numpy as np
    from scipy.optimize import minimize

    bcfg = _config()["fit"]["bayes"]
    counts = {"hitter": _count_table("hitter"), "pitcher": _count_table("pitcher")}
    tau_s = float(bcfg["role_pool_sd_slope"]); tau_c = float(bcfg["role_pool_sd_cut"])
    sig_s = float(bcfg["slope_prior_sd"]); sig_c = float(bcfg["cutpoint_prior_sd"])

    def neg_log_post(theta):
        s_h, cut_h, s_p, cut_p = _hier_unpack(theta)
        nlp = 0.0
        for s, cut, ct in ((s_h, cut_h, counts["hitter"]), (s_p, cut_p, counts["pitcher"])):
            for fv, cnt in ct.items():
                p = _p_bucket_proportional_odds(fv, cut, s)
                for b in range(_N_BUCKETS):
                    if cnt[b] > 0:
                        nlp -= cnt[b] * math.log(max(p[b], 1e-12))
        nlp += 0.5 * (s_h - s_p) ** 2 / tau_s ** 2                 # pool slopes
        for j in range(4):
            nlp += 0.5 * (cut_h[j] - cut_p[j]) ** 2 / tau_c ** 2   # pool cutpoints
        nlp += 0.5 * (s_h ** 2 + s_p ** 2) / sig_s ** 2            # weak level priors
        for c in cut_h + cut_p:
            nlp += 0.5 * c ** 2 / sig_c ** 2
        return nlp

    def to_raw(cut):
        return [cut[0]] + [math.log(max(cut[j + 1] - cut[j], 1e-6)) for j in range(3)]

    mle = {r: _fit_proportional_odds(*_build_training_rows(r)) for r in ("hitter", "pitcher")}
    theta0 = np.array([mle["hitter"][1], mle["pitcher"][1]]
                      + to_raw(mle["hitter"][0]) + to_raw(mle["pitcher"][0]))
    res = minimize(neg_log_post, theta0, method="L-BFGS-B", options={"maxiter": 5000})
    theta_map = res.x
    H = _num_hessian(neg_log_post, theta_map)
    try:
        cov = np.linalg.inv(H)
    except np.linalg.LinAlgError:
        cov = np.linalg.pinv(H)
    cov = 0.5 * (cov + cov.T)
    s_h, cut_h, s_p, cut_p = _hier_unpack(theta_map)
    all_fv = sorted(set(counts["hitter"]) | set(counts["pitcher"]))
    if verbose:
        print(f"[bayes] MAP slopes h={s_h:.4f} p={s_p:.4f} (indep MLE "
              f"{mle['hitter'][1]:.4f}/{mle['pitcher'][1]:.4f})")
        print(f"  param sds = {[round(float(np.sqrt(max(cov[i,i],0))),4) for i in range(len(theta_map))]}")
    return {
        "theta_map": [float(x) for x in theta_map],
        "cov": [[float(c) for c in row] for row in cov],
        "data_fv_range": [float(min(all_fv)), float(max(all_fv))],
        "map_params": {
            "hitter": {"cutpoints": [float(c) for c in cut_h], "slope": float(s_h)},
            "pitcher": {"cutpoints": [float(c) for c in cut_p], "slope": float(s_p)},
        },
        "indep_mle": {r: {"cutpoints": mle[r][0], "slope": mle[r][1]} for r in ("hitter", "pitcher")},
        "pooling": {"role_pool_sd_slope": tau_s, "role_pool_sd_cut": tau_c},
    }


def fit_and_write(out_path: Path | None = None, verbose: bool = True) -> dict:
    """Fit both roles, run the parallel-lines check, calibrate bucket midpoints,
    and WRITE data/value_framework_fitted.json. Returns the fitted dict.

    When bayes.enabled, the point estimate is the JOINT HIERARCHICAL MAP (partial
    pooling across roles), superseding the independent-MLE logit, and the Laplace
    posterior is stored for credible intervals (Prompt G)."""
    cfg = _config()
    tol = float(cfg["fit"]["parallel_lines_tol"])
    use_bayes = bool(cfg["fit"].get("bayes", {}).get("enabled"))
    bayes = _fit_hierarchical_bayes(verbose=verbose) if use_bayes else None
    fitted: dict[str, Any] = {
        "generated_by": "value_framework.py --fit",
        "framework_version": FRAMEWORK_VERSION,
        "method": {},
        "proportional_odds": {},
        "per_threshold": {},
        "parallel_lines_diagnostic": {},
        "bucket_midpoints": {},
        "reconciliation": {},
        "training_n": {},
    }
    if bayes is not None:
        fitted["bayes"] = bayes
    for role in ("hitter", "pitcher"):
        fvs, ys = _build_training_rows(role)
        fitted["training_n"][role] = len(ys)
        # Point estimate = hierarchical MAP (partial-pooled) when bayes is on,
        # else the independent-MLE proportional-odds fit.
        if bayes is not None:
            cut = bayes["map_params"][role]["cutpoints"]
            slope = bayes["map_params"][role]["slope"]
        else:
            cut, slope = _fit_proportional_odds(fvs, ys)
        per_thr = _fit_per_threshold(fvs, ys)
        diag = _parallel_lines_diagnostic(per_thr, tol)
        method = "proportional_odds" if diag["passed"] else "per_threshold_isotonic"
        fitted["method"][role] = method
        fitted["proportional_odds"][role] = {"cutpoints": cut, "slope": slope}
        fitted["per_threshold"][role] = per_thr
        fitted["parallel_lines_diagnostic"][role] = diag
        mids, recon = _calibrate_midpoints_for_role(role, cut, slope, per_thr, method)
        fitted["bucket_midpoints"][role] = mids
        fitted["reconciliation"][role] = recon
        if verbose:
            print(f"[{role}] n={len(ys)} method={method} "
                  f"parallel_lines_spread={diag['spread']:.3f} passed={diag['passed']}")
            print(f"  cutpoints={[round(c,3) for c in cut]} slope={slope:.4f}")
            print(f"  bucket_midpoints={[round(m,3) for m in mids]}")
            for k, v in recon.items():
                print(f"  reconcile FV {k}: target={v['target']} "
                      f"weighted_avg_war={v['weighted_avg_war']} resid={v['resid']}")

    out_path = out_path or _FITTED_PATH
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(fitted, indent=2, sort_keys=True), encoding="utf-8")
    _reset_caches()
    if verbose:
        print(f"wrote {out_path}")
    return fitted


