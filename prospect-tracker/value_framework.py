# =============================================================================
# Tiered $/WAR  (per-SEASON, convex; classify each season by its own WAR)
# =============================================================================
def tiered_war_value_usd(season_war: float) -> float:
    """Market $ value of ONE season's WAR. The season is classified into a tier
    by its own WAR and the whole season's WAR is valued at that tier's rate
    (convex: a star season costs more per win). Never call this on an averaged
    WAR -- value each bucket-season separately. WAR <= 0 -> $0."""
    if season_war is None or season_war <= 0:
        return 0.0
    dpw = _config()["dollars_per_war"]["tiered"]
    b1, b2 = dpw["breakpoints"]
    rates = dpw["rates"]
    if season_war < b1:
        rate = rates["lt_1"]
    elif season_war < b2:
        rate = rates["1_to_2"]
    else:
        rate = rates["2plus"]
    return float(season_war) * float(rate)


def _flat_rate_usd() -> float:
    return float(_config()["dollars_per_war"]["flat"])


# --- Back-compat helpers consumed by storage.py / mlb_trade_lookup.py ---------
def dollars_per_war(projected_war: float | None, window: tuple[int, ...] | None = None) -> float:
    """Tier $/WAR RATE in $M per WAR for a projected season WAR (back-compat API
    used by mlb_trade_lookup). None/<=0 -> low tier. `window` accepted & ignored
    (rates are config-pinned now)."""
    dpw = _config()["dollars_per_war"]["tiered"]
    b1, b2 = dpw["breakpoints"]
    rates = dpw["rates"]
    if projected_war is None:
        return float(rates["lt_1"]) / 1e6
    war = float(projected_war)
    if war < b1:
        rate = rates["lt_1"]
    elif war < b2:
        rate = rates["1_to_2"]
    else:
        rate = rates["2plus"]
    return float(rate) / 1e6


def dollars_per_war_flat(window: tuple[int, ...] | None = None) -> float:
    """Overall flat $/WAR rate in $M per WAR (for career-WAR vet valuation)."""
    return _flat_rate_usd() / 1e6


def career_war_value_mm(career_war: float | None, window: tuple[int, ...] | None = None) -> float | None:
    """Realized career WAR -> $M at the flat overall rate. None/<=0 -> None."""
    if career_war is None:
        return None
    try:
        cw = float(career_war)
    except (TypeError, ValueError):
        return None
    if cw <= 0:
        return None
    return round(cw * dollars_per_war_flat(), 2)


def present_value(amount_usd: float, year_index: int, discount_rate: float | None = None) -> float:
    """PV of a cash flow `year_index` years out (year_index=0 -> undiscounted)."""
    r = _config()["discount_rate"] if discount_rate is None else discount_rate
    return float(amount_usd) / ((1.0 + float(r)) ** int(year_index))


