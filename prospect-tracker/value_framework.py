@lru_cache(maxsize=4)
def _calibrated_midpoints(role: str) -> tuple[float, ...]:
    """v47 — the FIXED, smooth per-bucket WAR SHAPE (the band-prior levels). The
    per-FV LEVEL now comes from `_fv_war_scale` (FV-DEPENDENT midpoints = shape *
    scale): low-FV prospects de-value smoothly without the old joint midpoint
    solve forcing a bimodal split (which broke debuted-value monotonicity). bust
    pinned at 0. (The legacy fitted `bucket_midpoints` stay in the fit file for
    provenance but no longer drive valuation.)"""
    cfg = _config()["buckets"]
    return tuple(float(cfg[b]["midpoint_war"]) for b in _BUCKETS)


def _war_anchor_scale_for(role: str) -> float:
    """Per-role WAR-anchor multiplier from config['war_anchor_scale'] (DEFAULT 1.0
    == identity, so production is unchanged). This is the SINGLE shared upstream
    lever that scales the realized 6yr-avg WAR anchor the engine reconciles to,
    moving surplus AND star odds together. It is used ONLY by the Phase-5 model<->
    table reconciliation DIAGNOSTIC (fit_tier_reconciliation), which sets it
    transiently to REPORT the best-fit alignment + residual -- it is deliberately
    NOT written into any shipped valuation set, so the live board is never forced
    to the published tiers."""
    return float(_config().get("war_anchor_scale", {}).get(role, 1.0))


@lru_cache(maxsize=1024)
def _fv_war_scale(fv_half: float, role: str) -> float:
    """FV-dependent scalar k(FV) on the base bucket shape: scales it so the
    P(bucket|FV)-weighted six-year-avg WAR reconciles to the (optionally rescaled)
    fv_to_6yr_avg_war anchor at this FV. Smooth in FV (anchor + P(bucket) are
    smooth), so midpoints = shape * k(FV) never go bimodal. `fv_half` is the FV
    rounded to 0.5 (bounds the cache). bust bucket (shape 0) is unaffected.

    The anchor is multiplied by _war_anchor_scale_for(role) (default 1.0 -> no
    change); a non-unit scale is only ever set transiently by the reconciliation
    diagnostic. Cached on (fv_half, role) but READS config, so set_valuation_set /
    _reset_derived_caches must clear this cache (they do)."""
    is_pit = (role == "pitcher")
    probs = p_bucket_given_fv(fv_half, is_pit)
    base = _calibrated_midpoints(role)
    if probs is None:
        return 1.0
    denom = sum(p * b for p, b in zip(probs, base))
    anchor = fv_to_6yr_avg_war(fv_half)
    if not denom or anchor is None:
        return 1.0
    anchor = float(anchor) * _war_anchor_scale_for(role)
    return anchor / float(denom)


def _war_scale_for(fv: float | None, role: str) -> float:
    """Public helper: FV-dependent WAR scale, FV rounded to 0.5 for caching."""
    if fv is None:
        return 1.0
    try:
        return _fv_war_scale(round(float(fv) * 2) / 2.0, role)
    except (TypeError, ValueError):
        return 1.0


@lru_cache(maxsize=1024)
def _prime_war_scale(fv_half: float, role: str) -> float:
    """Prime analogue of `_fv_war_scale`: scales the bucket shape so the
    P(bucket|FV)-weighted level reconciles to the PRIME anchor (fv_to_prime_war)
    rather than the realized 6yr-avg. The higher anchor un-compresses the
    ceiling -- a 62-FV 'star' returns to ~5 WAR instead of the ~2.8 the
    realized-mean scale produces. DISPLAY path only; never used for $."""
    is_pit = (role == "pitcher")
    probs = p_bucket_given_fv(fv_half, is_pit)
    base = _calibrated_midpoints(role)
    if probs is None:
        return 1.0
    denom = sum(p * b for p, b in zip(probs, base))
    anchor = fv_to_prime_war(fv_half)
    if not denom or anchor is None:
        return 1.0
    return float(anchor) / float(denom)


def _prime_war_scale_for(fv: float | None, role: str) -> float:
    if fv is None:
        return 1.0
    try:
        return _prime_war_scale(round(float(fv) * 2) / 2.0, role)
    except (TypeError, ValueError):
        return 1.0


def prospect_prime_path(fv: float, is_pitcher: bool, debut_age: float | None = None,
                        reliever: bool = False) -> dict | None:
    """Prime/talent DISPLAY path: P(bucket|FV)-weighted per-season WAR with the
    bucket levels reconciled to the PRIME anchor. Returns {mean, p10, p90, peak}
    where p10/p90 are the 10th/90th-percentile bucket paths (realistic floor /
    ceiling) and peak is the headline prime WAR. DISPLAY ONLY -- the expected
    `war` path and surplus-$ stay on the realized anchor."""
    role = _role_key(is_pitcher)
    probs = p_bucket_given_fv(float(fv), is_pitcher)
    if probs is None:
        return None
    scale = _prime_war_scale_for(float(fv), role)
    paths = [_bucket_season_wars(role, i, reliever, debut_age, scale)
             for i in range(_N_BUCKETS)]
    n = len(paths[0])
    mean = [sum(probs[b] * paths[b][t] for b in range(_N_BUCKETS)) for t in range(n)]

    def _q_bucket(q: float) -> int:
        c = 0.0
        for i, p in enumerate(probs):
            c += p
            if c >= q:
                return i
        return _N_BUCKETS - 1

    return {"mean": mean, "p10": paths[_q_bucket(0.10)], "p90": paths[_q_bucket(0.90)],
            "peak": prospect_peak_war(float(fv), is_pitcher, debut_age)}


def prospect_peak_war(fv: float, is_pitcher: bool, debut_age: float | None = None) -> float | None:
    """Headline 'prime' WAR -- the prospect's projected best-season WAR at his
    peak age (prime-anchored). For young debutants whose 6yr control window ends
    before the peak, this surfaces the prime the window truncates."""
    anchor = fv_to_prime_war(float(fv))
    if anchor is None:
        return None
    cfg = _config()
    aging = cfg.get("aging", {})
    if debut_age is None or not aging.get("enabled", True):
        return round(anchor, 1)
    peak = float(aging["pitcher_peak_age" if is_pitcher else "hitter_peak_age"])
    n_years = int(cfg["service_time"]["control_years"])
    raw = [_aging_multiplier(float(debut_age) + k, peak, aging) for k in range(n_years)]
    mean_raw = (sum(raw) / n_years) or 1.0
    # anchor is the window-average level; the peak-age multiplier is 1.0, so the
    # peak-age projection renormalizes by 1/mean_raw.
    return round(anchor * (1.0 / mean_raw), 1)


# =============================================================================
# Aging curve -- relative WAR vs age, peak normalized to 1.0
# =============================================================================
def _aging_multiplier(age: float, peak_age: float, aging_cfg: dict) -> float:
    """Empirical relative-WAR multiplier at `age` (peak = 1.0): an asymmetric
    tent that climbs to the peak and declines (steeper) past it, floored."""
    climb = float(aging_cfg.get("climb_per_year_before_peak", 0.04))
    decline = float(aging_cfg.get("decline_per_year_after_peak", 0.07))
    floor = float(aging_cfg.get("min_multiplier", 0.25))
    if age <= peak_age:
        m = 1.0 - climb * (peak_age - age)
    else:
        m = 1.0 - decline * (age - peak_age)
    return max(floor, m)


# =============================================================================
# Per-bucket dollar surplus (FV-INDEPENDENT in WAR; timing reshapes/discounts $)
# =============================================================================
def _trajectory_shape(role: str, debut_age: float | None, bname: str | None = None) -> list[float]:
    """Per-season SHAPE (mean 1.0) across the control window. When aging is on
    and the debut age is known, the shape comes from the aging curve evaluated
    at the player's age each control season, renormalized to mean 1.0 (so the
    six-year AVERAGE still equals the level -- aging only redistributes WAR
    across the window). Otherwise the fixed bucket_trajectory_shape is used."""
    cfg = _config()
    n_years = int(cfg["service_time"]["control_years"])
    aging = cfg.get("aging", {})
    if aging.get("enabled", True) and debut_age is not None:
        peak = float(aging["pitcher_peak_age" if role == "pitcher" else "hitter_peak_age"])
        raw = [_aging_multiplier(float(debut_age) + k, peak, aging) for k in range(n_years)]
        mean_raw = (sum(raw) / n_years) or 1.0
        return [r / mean_raw for r in raw]
    shapes = cfg["bucket_trajectory_shape"]
    shape = shapes.get(bname, shapes["default"]) if bname else shapes["default"]
    if len(shape) != n_years:
        shape = (list(shape) * n_years)[:n_years]
        mean = sum(shape) / n_years or 1.0
        shape = [s / mean for s in shape]
    return list(shape)


def _reliever_level(midpoint_war: float) -> float:
    """Normalize a 200-IP-band WAR to a full BULLPEN season and cap it:
    min(ceiling, band_WAR * reliever_full_season_ip / pitcher_band_ip). E.g. a
    3.6-WAR/200-IP band -> 3.6*65/200 = 1.17 ~ 1.2 WAR. Falls back to the legacy
    flat relief_war_haircut if the IP keys are absent."""
    mw = float(midpoint_war)
    # Guard the WAR input: a non-finite or negative band WAR is floored at 0 so it
    # can never slip past min(ceil, .) as the ceiling (min(ceil, nan) == ceil in
    # CPython) or pass through as a negative full-season WAR. Unreachable via the
    # fitted midpoints / floored continuous rate today, but kept robust.
    if not math.isfinite(mw) or mw <= 0:
        return 0.0
    pos = _config()["position"]
    rip = pos.get("reliever_full_season_ip")
    band = float(pos.get("pitcher_band_ip", 200) or 200)
    if rip is None:
        return mw * float(pos.get("relief_war_haircut", 0.5))
    ceil = float(pos.get("reliever_war_ceiling", float("inf")))
    return min(ceil, mw * float(rip) / band)


def _bucket_season_wars(role: str, bucket_idx: int, reliever: bool,
                        debut_age: float | None = None, war_scale: float = 1.0) -> list[float]:
    """Per-season WAR for a bucket across the control window. The bucket level =
    base SHAPE midpoint * `war_scale` (the FV-DEPENDENT scale, default 1.0); SP
    uses that, RELIEVER uses the bullpen-normalized, ceiling-capped value. Times
    the aging/fixed shape."""
    shape = _trajectory_shape(role, debut_age, _BUCKETS[bucket_idx])
    mid = _calibrated_midpoints(role)[bucket_idx] * float(war_scale)
    level = _reliever_level(mid) if reliever else mid
    return [level * float(s) for s in shape]


def _aged_trajectory(role: str, level: float, debut_age: float | None) -> list[float]:
    """Per-season WAR for an arbitrary talent LEVEL (e.g. a continuous regressed
    true-talent rate), shaped by the same aging curve. No relief haircut -- a
    debuted player's observed/regressed rate is already at their real role."""
    return [level * float(s) for s in _trajectory_shape(role, debut_age, None)]


def _service_path_surplus_usd(season_wars: list[float], super_two: bool,
                              eta_years: float = 0.0, eta_origin: float | None = None,
                              profile=None) -> float:
    """Discounted sum over control years of (season market value - season salary),
    with performance-adaptive arbitration. Standard path = pre_arb_years league-min
    years then escalating-fraction arb years; super-two converts one pre-arb year
    into an extra (cheaper, earlier) arb year.

    Timing: control season k lands `eta_years + k` calendar years out. Each
    season's surplus is grown by $/WAR inflation and discounted at discount_rate;
    the two net to ((1+inflation)/(1+discount_rate))^(eta_years+k). With
    inflation = 0 and eta_years = 0 this is exactly the prior 1/(1+r)^k discount.

    Unified $/WAR path mode (VAL_5): see _service_path_surplus_unified_usd; the
    legacy branch below is unchanged and eta_origin is ignored there.

    `profile` = (arb_role, age at control season 0 or None). With it, under
    arb_pricing = arb_model, the arbitration seasons price through the award
    model (_arb_model_salaries) and carry the club's non-tender option
    (_cliff_sum); without it, or under the fraction ladder, nothing changes."""
    if dpw_path_active():
        return _service_path_surplus_unified_usd(season_wars, super_two, eta_years, eta_origin,
                                                 profile=profile)
    markets = [tiered_war_value_usd(w) for w in season_wars]
    salaries = _service_path_salaries(season_wars, markets, super_two, profile=profile)
    cfg = _config()
    infl = float(cfg.get("dollars_per_war_inflation", 0.0))
    r = float(cfg["discount_rate"])
    # SINGLE net real factor: $/WAR growth (infl) partially offsets the nominal
    # discount (r), applied ONCE per season as net**(eta+t). No second inflation
    # or discount is applied anywhere on this path (present_value() is intentionally
    # never called). test_salary_discount guards this.
    net = (1.0 + infl) / (1.0 + r)
    if profile is not None and arb_pricing() == "arb_model":
        pre_arb = _arb_ladder(_config()["service_time"], super_two)[0]
        return _cliff_sum([(markets[t] - salaries[t]) * (net ** (float(eta_years) + t))
                           for t in range(len(season_wars))],
                          [t >= pre_arb for t in range(len(season_wars))])
    return sum((markets[t] - salaries[t]) * (net ** (float(eta_years) + t))
               for t in range(len(season_wars)))


def _service_path_surplus_unified_usd(season_wars: list[float], super_two: bool,
                                      eta_years: float = 0.0,
                                      eta_origin: float | None = None,
                                      profile=None) -> float:
    """Unified mode (I1, I2, I6): control season t is the calendar season
    s_t = eta_origin + eta_years + t, so the priced season does not depend on
    which year the caller measured the ETA from. Each season is priced at its own
    level V(w, s_t), its salary by season (row 2), and discounted by d(s_t) to B,
    unclipped."""
    origin = _priced_origin(eta_origin)
    s0 = origin + float(eta_years)
    seasons = [s0 + t for t in range(len(season_wars))]
    markets = [season_value_usd(w, s) for w, s in zip(season_wars, seasons)]
    salaries = _service_path_salaries_unified(season_wars, seasons, super_two, profile=profile)
    if profile is not None and arb_pricing() == "arb_model":
        pre_arb = _arb_ladder(_config()["service_time"], super_two)[0]
        return _cliff_sum([(markets[t] - salaries[t]) * season_discount(seasons[t], legacy_base=origin)
                           for t in range(len(season_wars))],
                          [t >= pre_arb for t in range(len(season_wars))])
    return sum((markets[t] - salaries[t]) * season_discount(seasons[t], legacy_base=origin)
               for t in range(len(season_wars)))


def _service_path_salaries_unified(season_wars: list[float], seasons: list[float],
                                   super_two: bool, profile=None) -> list[float]:
    """Row 2 in unified mode: the league minimum of the season (league_min_for,
    which reads the CBA table and fixes the flat 0.76M against the tabled 0.78M);
    arbitration on the prior_season basis as max(minimum, frac x the prior
    season's WAR priced at the market of season s_t), and on the current_season
    basis frac x this season's market, so arbitration tracks the price of a win
    by construction under every OD-4 option."""
    cfg = _config()
    st = cfg["service_time"]
    legacy_min = float(st["league_min_usd"])
    if profile is not None and arb_pricing() == "arb_model":
        # The rungs sit at the deflator's carry-forward level; VAL_5 F-D
        # applies the arbitration index growth rule to them at its flip.
        return _arb_model_salaries(season_wars, super_two, profile,
                                   lambda t: league_min_for(seasons[t], legacy=legacy_min))
    pre_arb, arb_fracs = _arb_ladder(st, super_two)
    arb_basis = str(st.get("arb_basis", "current_season"))
    out: list[float] = []
    for t, s in enumerate(seasons):
        lm = league_min_for(s, legacy=legacy_min)
        if t < pre_arb:
            out.append(lm)
            continue
        i = t - pre_arb
        frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
        if arb_basis == "prior_season":
            w_prior = season_wars[t - 1] if t > 0 else season_wars[t]
            out.append(max(lm, frac * season_value_usd(w_prior, s)))
        else:
            out.append(frac * season_value_usd(season_wars[t], s))
    return out


def _arb_ladder(st: dict, super_two: bool) -> tuple[int, list[float]]:
    """Pre-arb year count + arb-fraction ladder for a service path (the single
    source of the super-two ladder; the prospect, remaining and consumed paths all
    build it here). Super-two drops one pre-arb year and prepends the extra EARLY
    arb year onto the standard schedule. CONSTRAINT: that prepended year is the
    player's first arbitration year held a year early, so its fraction is clamped
    to the schedule's own arb-1 step -- the ladder is monotone under every
    valuation set by construction (an earlier arb year can never pay more than the
    one after it). Under the legacy 0.40/0.60/0.80 schedule the calibrated 0.25
    sits below arb-1 and passes through unchanged (base-identity output stays
    byte-identical); under the clemens_2026 0.15/0.35/0.50/0.75 schedule the
    legacy 0.25 exceeded arb-1 and inverted the ladder, so it clamps to the 0.15
    arb-1 fraction. The clamp is a consistency constraint on the configured
    super_two_first_fraction, not a new empirical estimate of super-two awards."""
    fracs = [float(x) for x in st["arb_model"]["fractions_of_fa_value"]]
    if not super_two:
        return int(st["pre_arb_years"]), fracs
    s2_first = min(float(st["arb_model"]["super_two_first_fraction"]), fracs[0])
    return int(st["pre_arb_years"]) - 1, [s2_first] + fracs


