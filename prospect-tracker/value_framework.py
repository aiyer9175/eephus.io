class ConfigError(ValueError):
    """value_framework_config.yaml is missing a required key, or a CORE value has
    the wrong type/range. Raised at load so a malformed config fails LOUDLY at the
    point of edit instead of silently defaulting deep inside a calculation."""


def _cfg_require(node, path, types=None, *, positive=False, rng=None):
    """Walk `node` along the key tuple `path`, raising ConfigError if any level is
    missing or the leaf fails its type / positivity / range check. Returns the leaf.
    (bool is rejected where a number is required, since `True` is an int in Python.)"""
    cur = node
    seen = []
    for k in path:
        seen.append(str(k))
        if not isinstance(cur, dict) or k not in cur:
            raise ConfigError(f"missing required key: {'.'.join(seen)}")
        cur = cur[k]
    dotted = ".".join(str(k) for k in path)
    if types is not None and not isinstance(cur, types):
        raise ConfigError(f"{dotted}: expected {types}, got {type(cur).__name__} ({cur!r})")
    is_num = isinstance(cur, (int, float)) and not isinstance(cur, bool)
    if positive and not (is_num and cur > 0):
        raise ConfigError(f"{dotted}: expected a positive number, got {cur!r}")
    if rng is not None and not (is_num and rng[0] <= cur <= rng[1]):
        raise ConfigError(f"{dotted}: expected a number in [{rng[0]}, {rng[1]}], got {cur!r}")
    return cur


def _validate_config(cfg: dict) -> dict:
    """Schema/type gate for the CORE (Prompt B) config -- the base layer every
    later block extends. Checks presence, types and ranges of the keys the engine
    relies on; OPTIONAL/secondary keys keep their graceful `.get(default)` behavior
    by design. Returns cfg unchanged on success; raises ConfigError otherwise."""
    if not isinstance(cfg, dict):
        raise ConfigError("config did not parse to a mapping (empty or malformed YAML)")
    # --- Outcome buckets (order must be the engine's canonical bust..star) ---
    order = _cfg_require(cfg, ("buckets", "order"), list)
    if list(order) != list(_BUCKETS):
        raise ConfigError(f"buckets.order must be {list(_BUCKETS)}, got {list(order)}")
    for b in _BUCKETS:
        _cfg_require(cfg, ("buckets", b, "band"), str)
        _cfg_require(cfg, ("buckets", b, "midpoint_war"), (int, float))
        _cfg_require(cfg, ("buckets", b, "surplus_floor_usd"), (int, float))
    # --- P(bucket|FV) training tables: each row carries n + all five buckets ---
    for role in ("hitter", "pitcher"):
        table = _cfg_require(cfg, (f"p_bucket_given_fv_{role}",), dict)
        if not table:
            raise ConfigError(f"p_bucket_given_fv_{role} is empty")
        for key, row in table.items():
            if not isinstance(row, dict) or "n" not in row:
                raise ConfigError(f"p_bucket_given_fv_{role}['{key}'] missing 'n'")
            for b in _BUCKETS:
                if b not in row:
                    raise ConfigError(f"p_bucket_given_fv_{role}['{key}'] missing bucket '{b}'")
    # --- FV -> 6yr AVERAGE annual WAR anchor (NOT peak) ---
    if not _cfg_require(cfg, ("fv_to_6yr_avg_war",), dict):
        raise ConfigError("fv_to_6yr_avg_war is empty")
    # --- Market $/WAR: flat + tiered (breakpoints ascending, rates positive) ---
    _cfg_require(cfg, ("dollars_per_war", "flat"), (int, float), positive=True)
    bps = _cfg_require(cfg, ("dollars_per_war", "tiered", "breakpoints"), list)
    if len(bps) != 2 or not (bps[0] < bps[1]):
        raise ConfigError(f"dollars_per_war.tiered.breakpoints must be 2 ascending values, got {bps}")
    for r in ("lt_1", "1_to_2", "2plus"):
        _cfg_require(cfg, ("dollars_per_war", "tiered", "rates", r), (int, float), positive=True)
    fa = cfg["dollars_per_war"].get("fa_implied")
    if fa is not None:
        if not isinstance(fa, dict) or not isinstance(fa.get("enabled"), bool):
            raise ConfigError("dollars_per_war.fa_implied must carry a boolean 'enabled'")
        _cfg_require(cfg, ("dollars_per_war", "fa_implied", "trailing_years"), int, positive=True)
    # --- Time value of money ---
    _cfg_require(cfg, ("discount_rate",), (int, float), rng=(0.0, 1.0))
    # --- Service-time / performance-adaptive arbitration ---
    _cfg_require(cfg, ("service_time", "control_years"), int, positive=True)
    _cfg_require(cfg, ("service_time", "league_min_usd"), (int, float), positive=True)
    _cfg_require(cfg, ("service_time", "pre_arb_years"), int)
    _cfg_require(cfg, ("service_time", "arb_model", "fractions_of_fa_value"), list)
    # --- Continuous-FV fit controls ---
    _cfg_require(cfg, ("fit", "role_axes"), dict)
    _cfg_require(cfg, ("fit", "exclude_n_le"), int)
    # --- FV<=40 dollar anchor (Edwards) ---
    for k in ("anchor_usd_40fv_position", "anchor_fv", "decay_per_point", "cutover_fv", "bridge_to_fv"):
        _cfg_require(cfg, ("lowtier_anchor", k), (int, float))
    return cfg


_DPW_SERIES_PATH = _HERE / "data" / "fa_dpw_series.json"


def written_dpw_pricing() -> dict | None:
    """The ``pricing`` block of THE one written $/WAR series
    (data/fa_dpw_series.json, written by fa_market.write_dpw_series): the
    class year it prices, the ex-ante level (level_usd), the winter it was
    carried from and the rate it was carried at. None when the file or the
    block is absent or malformed. Read-only; this module never writes it."""
    try:
        doc = json.loads(_DPW_SERIES_PATH.read_text(encoding="utf-8"))
        block = doc["pricing"]
        level = float(block["level_usd"])
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return block if level > 0 else None


def _apply_fa_winter_level(cfg: dict) -> dict:
    """VAL_1 (owner decision FP2-1, 2026-09-25): ONE $/WAR level for prospect
    and veteran surplus.

    Before this, a prospect win priced at the clemens_2026 FanGraphs flat
    $11.74M while /projections/ priced a veteran win at the committed
    signings-implied series carried to $17.97M, and the Trade Machine and the
    Club Ledger added the two into one total, so a prospect win cost less
    than a veteran win inside the same number. The level is now the free-agent
    winter level every surface prices at: pricing.level_usd of the one written
    series, the latest winter's signings-implied $/WAR carried forward at the
    series' own trend to the next class year (the level /fa/ and /projections/
    price that class at).

    The clemens_2026 tier SHAPE (the published rate ratios, checksummed) is
    kept and rescaled to that level. The FV 40 dollar anchor is stated at the
    FanGraphs level ("Edwards 2018, scaled to the current overall $/WAR"), so
    it rescales by the same factor. Nothing about WAR moves: the FV-to-WAR
    anchors, the outcome odds and the control window are untouched.

    Falls back to the configured (FanGraphs) level, stamped applied False,
    when the written series has no pricing block (a fresh checkout before the
    writer has run), so a missing file is visible in every artifact stamp."""
    dpw = cfg["dollars_per_war"]
    base_flat = float(dpw["flat"])
    pricing = written_dpw_pricing()
    if pricing is None:
        dpw["_fa_reanchor"] = {"applied": False, "method": "fa_winter_level",
                               "reason": "data/fa_dpw_series.json carries no pricing block",
                               "level_usd": round(base_flat)}
        return cfg
    level = float(pricing["level_usd"])
    scale = level / base_flat
    dpw["flat"] = level
    dpw["tiered"]["rates"] = {k: float(v) * scale
                              for k, v in dpw["tiered"]["rates"].items()}
    anchor = cfg.get("lowtier_anchor") or {}
    if anchor.get("anchor_usd_40fv_position") is not None:
        anchor["anchor_usd_40fv_position"] = float(anchor["anchor_usd_40fv_position"]) * scale
    dpw["_fa_reanchor"] = {"applied": True, "method": "fa_winter_level",
                           "class_year": pricing.get("class_year"),
                           "level_usd": round(level),
                           "base_flat_usd": round(base_flat),
                           "scale": round(scale, 4),
                           "anchor_winter": pricing.get("anchor_winter"),
                           "carry_rate": pricing.get("carry_rate"),
                           "series": "data/fa_dpw_series.json pricing.level_usd",
                           "shape": "clemens_2026 tier ratios and the FV 40 anchor rescaled to the level"}
    return cfg


def _apply_fa_implied_reanchor(cfg: dict) -> dict:
    """v3 (surplus) — re-anchor the $/WAR LEVEL to the FA module's
    signings-implied series (data/fa_dpw_series.json: per-winter total
    guarantee over total discounted projected contract WAR — what clubs
    ACTUALLY paid per win on the open market, the Gate-2-validated
    estimator). The tier curve keeps its fitted convex SHAPE (the rate
    ratios); only the level rescales, so a prospect's surplus is priced
    against the same market the FA module prices contracts against.
    Trailing-N-winter mean smooths single-offseason variance, mirroring
    the v44 trailing-average decision. Falls back silently to the curated
    historical table when the series file is absent (fresh checkout) —
    the re-anchor is an upgrade, never a dependency."""
    fa = (cfg.get("dollars_per_war") or {}).get("fa_implied") or {}
    if not fa.get("enabled"):
        return cfg
    if fa.get("method") == "fa_winter_level":
        return _apply_fa_winter_level(cfg)
    try:
        series = json.loads((_HERE / "data" / "fa_dpw_series.json")
                            .read_text(encoding="utf-8"))["usd_per_war_by_winter"]
    except (OSError, ValueError, KeyError):
        return cfg
    winters = sorted(int(k) for k in series)
    n = int(fa.get("trailing_years", 3))
    tail = winters[-n:]
    if not tail:
        return cfg
    level = sum(float(series[str(y)]) for y in tail) / len(tail)
    dpw = cfg["dollars_per_war"]
    base_flat = float(dpw["flat"])
    scale = level / base_flat
    dpw["flat"] = level
    dpw["tiered"]["rates"] = {k: float(v) * scale
                              for k, v in dpw["tiered"]["rates"].items()}
    dpw["_fa_reanchor"] = {"applied": True, "winters": tail,
                           "level_usd": round(level),
                           "base_flat_usd": round(base_flat),
                           "scale": round(scale, 4),
                           "method": "fa_signings_implied trailing mean; tier shape preserved"}
    return cfg


