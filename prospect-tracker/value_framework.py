def outcome_implied_fv(predicted_war, *, exposure_seasons: int = 6) -> float | None:
    """The industry-scale FV whose EMPIRICAL first-6yr outcome mean equals `predicted_war`.

    Side-neutral, age-neutral and position-neutral by construction: the curve is indexed on
    consensus FV alone, so this is a pure monotone function of predicted WAR. That is what
    makes the ship safe -- within a side the eFV ordering, the per-side rank-quantile
    display map and therefore SURPLUS PRICING are untouched (surplus re-prices off
    xfv_grade_display, which reads rank_war, never this grade).

    Clamps to [20, 80]. A non-positive prediction reads exactly 20.0, matching what
    `realized_implied_fv` did at the same input, so the FV20 floor population does not move.

    `exposure_seasons` exists to make the window explicit at every call site rather than
    implicit in a default: the curve IS the six-season-from-debut window (the label
    efv_score trains on), and asking for any other window is a category error, not a
    rescale. See the block comment above for what this map is and is not calibrated for."""
    if predicted_war is None:
        return None
    if int(exposure_seasons) != 6:
        raise ValueError(
            f"outcome_implied_fv is defined on the 6-season window only (got "
            f"{exposure_seasons}); the curve's label is first-6yr total WAR on the label series")
    try:
        war = float(predicted_war)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(war):
        return None
    c = _outcome_curve()
    ks, vs = c["knots"], c["value"]
    if war <= vs[0]:
        return ks[0]
    if war >= vs[-1]:
        return ks[-1]
    for (k0, v0), (k1, v1) in zip(zip(ks, vs), zip(ks[1:], vs[1:])):
        if v0 <= war <= v1:
            return k0 + (k1 - k0) * ((war - v0) / (v1 - v0))
    return ks[-1]


def _fv_tier_index(fv: float, edges) -> int:
    for i, e in enumerate(edges):
        if fv < float(e):
            return i
    return len(edges)


def fit_source_calibration(records, *, holdout_year=None) -> dict:
    """Estimate per-source BIAS + reliability from historical graded-player ->
    outcome data (Prompt N). `records`: iterable of dicts:
        {source_fvs: {source: fv}, is_pitcher, realized_war  (Prompt-F reconstructed),
         [exposure_seasons], [age], [position], [cohort_year]}

    Returns a calibration dict consumed by calibrated_consensus_fv:
      (1) per_source[s].bias  -- shrunk mean (source FV - realized-implied FV);
          >0 => grades too high => de-bias down. Conditional cells by (role, fv_tier),
          partial-pooled toward the source overall (3). Thin sources -> 0 bias (3).
      (2) per_source[s].var   -- de-biased error variance (skill -> weight).
      (4) covariance          -- cross-source error covariance for GLS weights.
      (6) rolling recency decay by cohort_year; (7) optional holdout_year exclusion."""
    import numpy as np
    scfg = _config().get("source_calibration", {})
    tiers = [float(x) for x in scfg.get("fv_tiers", [47.5, 55.0])]
    k_bias = float(scfg.get("bias_shrink_pseudocount", 30))
    k_cell = float(scfg.get("cell_shrink_pseudocount", 20))
    min_n = float(scfg.get("min_players_for_source", 5))
    halflife = float(scfg.get("rolling_halflife_years", 0) or 0)
    ridge = float(scfg.get("ridge", 0.05))
    cond = set(scfg.get("conditional_by") or [])
    conditional = bool(cond & {"role", "fv_tier"})
    shrink_thin = bool(scfg.get("shrink_thin_history", True))
    estimate_bias = bool(scfg.get("estimate_bias", True))

    recs = [r for r in (records or []) if r.get("source_fvs")]
    if holdout_year is not None:
        recs = [r for r in recs if r.get("cohort_year") != holdout_year]
    years = [r.get("cohort_year") for r in recs if r.get("cohort_year") is not None]
    y_ref = max(years) if years else None

    rows, src_set = [], set()
    for r in recs:
        isp = bool(r.get("is_pitcher"))
        rif = realized_implied_fv(r.get("realized_war"), isp, exposure_seasons=r.get("exposure_seasons"),
                                  age=r.get("age"), position=r.get("position"))
        if rif is None:
            continue
        w = 1.0
        if halflife > 0 and y_ref is not None and r.get("cohort_year") is not None:
            w = 0.5 ** ((y_ref - r["cohort_year"]) / halflife)
        errs, cells = {}, {}
        for s, fv in r["source_fvs"].items():
            try:
                fvf = float(fv)
            except (TypeError, ValueError):
                continue
            if not math.isfinite(fvf):
                continue
            errs[s] = fvf - rif
            cells[s] = (_role_key(isp), _fv_tier_index(fvf, tiers))
            src_set.add(s)
        if errs:
            rows.append({"errs": errs, "w": w, "cells": cells})

    sources = sorted(src_set)
    per_source = {}
    for s in sources:
        es = [(row["errs"][s], row["w"]) for row in rows if s in row["errs"]]
        n = len(es)
        wsum = sum(w for _, w in es) or 1.0
        raw_bias = sum(e * w for e, w in es) / wsum
        thin = n < min_n
        if not estimate_bias or (thin and shrink_thin):
            bias = 0.0
        else:
            bias = raw_bias * (wsum / (wsum + k_bias))            # shrink toward 0 by history depth
        var = (sum(w * (e - raw_bias) ** 2 for e, w in es) / wsum) if n > 1 else None
        cellbias = {}
        if conditional and not thin and estimate_bias:
            cmap = {}
            for row in rows:
                if s in row["errs"]:
                    cmap.setdefault(row["cells"][s], []).append((row["errs"][s], row["w"]))
            for key, lst in cmap.items():
                cw = sum(w for _, w in lst) or 1.0
                craw = sum(e * w for e, w in lst) / cw
                cellbias[key] = (cw * craw + k_cell * bias) / (cw + k_cell)   # pool toward source bias
        per_source[s] = {"bias": bias, "raw_bias": raw_bias, "n": n,
                         "var": var, "thin": thin, "cells": cellbias}

    # (4) cross-source error covariance on de-biased residuals over common players.
    nS = len(sources)
    idx = {s: i for i, s in enumerate(sources)}
    known = [per_source[s]["var"] for s in sources if per_source[s]["var"] is not None]
    default_var = (sum(known) / len(known)) if known else 1.0
    Sigma = np.zeros((nS, nS))
    Wt = np.zeros((nS, nS))
    for row in rows:
        present = [s for s in row["errs"] if s in idx]
        w = row["w"]
        for a in present:
            ra = row["errs"][a] - per_source[a]["raw_bias"]
            for b in present:
                rb = row["errs"][b] - per_source[b]["raw_bias"]
                Sigma[idx[a], idx[b]] += w * ra * rb
                Wt[idx[a], idx[b]] += w
    for i in range(nS):
        for j in range(nS):
            if Wt[i, j] > 0:
                Sigma[i, j] /= Wt[i, j]
            elif i != j:
                Sigma[i, j] = 0.0
        if Sigma[i, i] <= 0:
            Sigma[i, i] = per_source[sources[i]]["var"] or default_var
    if nS:
        Sigma += np.eye(nS) * ridge * default_var                 # invertibility + shrink to independence

    return {
        "sources": sources, "per_source": per_source,
        "covariance": Sigma.tolist() if nS else [],
        "default_var": float(default_var), "tiers": tiers,
        "n_records": len(rows), "holdout_year": holdout_year,
    }


def calibrated_consensus_fv(source_fvs, calibration=None, *, is_pitcher: bool = False,
                            position: str | None = None, age: float | None = None) -> dict | None:
    """Rebuild the consensus FV from per-source grades + a fitted calibration (Prompt
    N step 5): (a) de-bias each source (conditional by role/tier), (b) covariance-
    aware GLS reliability weights (redundant sources share weight), (c) the weighted
    consensus FV, (d) its uncertainty `fv_sd` (SD of the combined estimate -> feed
    Prompt I via combined_fv_uncertainty). Sources absent from the calibration get
    no bias + the default variance; a single source reduces to that source de-biased.
    None if no usable FV."""
    import numpy as np
    items = []
    for s, fv in (source_fvs or {}).items():
        try:
            fvf = float(fv)
        except (TypeError, ValueError):
            continue
        if math.isfinite(fvf):
            items.append((s, fvf))
    if not items:
        return None
    cal = calibration or {}
    ps = cal.get("per_source", {})
    sidx = {s: i for i, s in enumerate(cal.get("sources", []))}
    Sig_full = np.array(cal["covariance"]) if cal.get("covariance") else None
    default_var = float(cal.get("default_var", 1.0))
    tiers = cal.get("tiers", [47.5, 55.0])
    role = _role_key(is_pitcher)

    present, debiased, vdiag, cidx = [], [], [], []
    for s, fvf in items:
        info = ps.get(s)
        if info is not None:
            b = info.get("cells", {}).get((role, _fv_tier_index(fvf, tiers)), info["bias"])
            present.append(s); debiased.append(fvf - b)
            vdiag.append(max(info["var"] if info["var"] is not None else default_var, 1e-9))
        else:
            present.append(s); debiased.append(fvf); vdiag.append(default_var)
        cidx.append(sidx.get(s))
    m = len(present)
    if m == 1:
        return {"consensus_fv": round(debiased[0], 3), "fv_sd": round(math.sqrt(vdiag[0]), 3),
                "weights": {present[0]: 1.0}, "debiased": {present[0]: round(debiased[0], 3)},
                "n_sources": 1}
    Sig = np.diag(np.array(vdiag, dtype=float))
    if Sig_full is not None:
        for i in range(m):
            for j in range(m):
                if cidx[i] is not None and cidx[j] is not None:
                    Sig[i, j] = Sig_full[cidx[i], cidx[j]]
    try:
        inv = np.linalg.inv(Sig)
    except np.linalg.LinAlgError:
        inv = np.linalg.pinv(Sig)
    w = inv @ np.ones(m)
    w = np.clip(w, 0.0, None)                                     # no negative weights on an FV grade
    w = w / w.sum() if w.sum() > 0 else np.ones(m) / m
    debiased = np.array(debiased, dtype=float)
    return {
        "consensus_fv": round(float(w @ debiased), 3),
        "fv_sd": round(math.sqrt(max(float(w @ Sig @ w), 0.0)), 3),    # combined-estimate uncertainty
        "weights": {present[i]: round(float(w[i]), 4) for i in range(m)},
        "debiased": {present[i]: round(float(debiased[i]), 3) for i in range(m)},
        "n_sources": m,
    }


def combined_fv_uncertainty(disagreement_sd, skill_sd) -> float:
    """Combine Prompt-I cross-source DISAGREEMENT sd with the Prompt-N consensus-
    precision (SKILL) sd in quadrature -> the fv_dispersion to pass to sv_distribution
    so the consensus carries BOTH uncertainty sources (5d)."""
    a = float(disagreement_sd or 0.0)
    b = float(skill_sd or 0.0)
    return math.sqrt(a * a + b * b)


def source_calibration_cv(records) -> dict:
    """Leave-one-cohort-year-out CV (Prompt N step 7): for each cohort year, FIT the
    calibration WITHOUT that year, then de-bias the held-out year's grades and
    measure the reduction in |source FV - realized-implied FV|. Never fits and
    evaluates on the same data. Returns {per_year, pooled} with mae before/after."""
    recs = [r for r in (records or []) if r.get("source_fvs") and r.get("cohort_year") is not None]
    years = sorted({r["cohort_year"] for r in recs})
    before_all, after_all, per_year = [], [], {}
    for y in years:
        cal = fit_source_calibration(recs, holdout_year=y)
        b_err, a_err = [], []
        for r in (x for x in recs if x["cohort_year"] == y):
            isp = bool(r.get("is_pitcher"))
            rif = realized_implied_fv(r.get("realized_war"), isp, exposure_seasons=r.get("exposure_seasons"),
                                      age=r.get("age"), position=r.get("position"))
            if rif is None:
                continue
            role = _role_key(isp)
            for s, fv in r["source_fvs"].items():
                info = cal["per_source"].get(s)
                if info is None:
                    continue
                try:
                    fvf = float(fv)
                except (TypeError, ValueError):
                    continue
                b = info["cells"].get((role, _fv_tier_index(fvf, cal["tiers"])), info["bias"])
                b_err.append(abs(fvf - rif))
                a_err.append(abs((fvf - b) - rif))
        if b_err:
            per_year[y] = {"n": len(b_err),
                           "mae_before": round(sum(b_err) / len(b_err), 3),
                           "mae_after": round(sum(a_err) / len(a_err), 3)}
            before_all += b_err
            after_all += a_err
    pooled = {"n": len(before_all),
              "mae_before": round(sum(before_all) / len(before_all), 3) if before_all else None,
              "mae_after": round(sum(after_all) / len(after_all), 3) if after_all else None}
    return {"per_year": per_year, "pooled": pooled}


