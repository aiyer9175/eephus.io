# Debuted-player mode (Prompt D): realized (consumed) + remaining (projected)
# =============================================================================
def _remaining_path_surplus_usd(season_wars: list[float], start_k: int, super_two: bool,
                                profile=None) -> float:
    """Value control seasons [start_k:] on the ACTUAL service clock (salary by
    absolute service year), discounting from NOW (the player is already in MLB,
    so the first remaining season is undiscounted). start_k=0 reproduces the
    full prospect path at eta=0 exactly.

    Unified $/WAR path mode (VAL_5, row 4): see
    _remaining_path_surplus_unified_usd; the legacy branch below is unchanged.

    `profile` as in _service_path_surplus_usd: under arb_pricing = arb_model the
    WHOLE path's salaries come from _arb_model_salaries (so start_k = 0 still
    reproduces the prospect path) and the seasons from start_k carry the
    non-tender option."""
    if dpw_path_active():
        return _remaining_path_surplus_unified_usd(season_wars, start_k, super_two,
                                                   profile=profile)
    cfg = _config()
    st = cfg["service_time"]
    league_min = float(st["league_min_usd"])
    pre_arb, arb_fracs = _arb_ladder(st, super_two)
    net = (1.0 + float(cfg.get("dollars_per_war_inflation", 0.0))) / (1.0 + float(cfg["discount_rate"]))
    if profile is not None and arb_pricing() == "arb_model":
        sal = _arb_model_salaries(season_wars, super_two, profile, lambda t: league_min)
        ks = range(int(start_k), len(season_wars))
        return _cliff_sum([(tiered_war_value_usd(season_wars[k]) - sal[k]) * (net ** (k - int(start_k)))
                           for k in ks], [k >= pre_arb for k in ks])
    # Honor service_time.arb_basis + the league-min floor EXACTLY like
    # _service_path_salaries (the prospect path), so start_k=0 really does reproduce
    # the full prospect path at eta=0. Under the production clemens_2026 set
    # (arb_basis=prior_season) the old current-season hardcode priced every debuted
    # player's arb seasons on the wrong market, inflating remaining/trade value
    # ~$0.3-1.5M per player vs the prospect model on the identical WAR path.
    arb_basis = str(st.get("arb_basis", "current_season"))
    markets = [tiered_war_value_usd(w) for w in season_wars]
    total = 0.0
    start_k = int(start_k)
    for k in range(start_k, len(season_wars)):
        market = markets[k]
        if k < pre_arb:
            salary = league_min
        else:
            i = k - pre_arb
            frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
            if arb_basis == "prior_season":
                prior_market = markets[k - 1] if k > 0 else markets[k]
                salary = max(league_min, frac * prior_market)
            else:
                salary = frac * market   # matches _service_path_salaries exactly (no floor)
        total += (market - salary) * (net ** (k - start_k))
    return total


def _remaining_path_surplus_unified_usd(season_wars: list[float], start_k: int,
                                        super_two: bool, profile=None) -> float:
    """Row 4, unified: the remaining control seasons are calendar seasons
    s = N + 1 + (k - start_k) (the first remaining season is season B whatever
    the caller's calendar year), priced at their own level with salaries by
    season (row 2), discounted by d(s) to B."""
    cfg = _config()
    st = cfg["service_time"]
    legacy_min = float(st["league_min_usd"])
    pre_arb, arb_fracs = _arb_ladder(st, super_two)
    arb_basis = str(st.get("arb_basis", "current_season"))
    first = float(last_realized_winter() + 1)
    total = 0.0
    start_k = int(start_k)
    if profile is not None and arb_pricing() == "arb_model":
        sal = _arb_model_salaries(season_wars, super_two, profile,
                                  lambda k: league_min_for(first + (k - start_k), legacy=legacy_min))
        ks = range(start_k, len(season_wars))
        return _cliff_sum([(season_value_usd(season_wars[k], first + (k - start_k)) - sal[k])
                           * season_discount(first + (k - start_k), legacy_base=first)
                           for k in ks], [k >= pre_arb for k in ks])
    for k in range(start_k, len(season_wars)):
        s = first + (k - start_k)
        market = season_value_usd(season_wars[k], s)
        lm = league_min_for(s, legacy=legacy_min)
        if k < pre_arb:
            salary = lm
        else:
            i = k - pre_arb
            frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
            if arb_basis == "prior_season":
                w_prior = season_wars[k - 1] if k > 0 else season_wars[k]
                salary = max(lm, frac * season_value_usd(w_prior, s))
            else:
                salary = frac * market
        total += (market - salary) * season_discount(s, legacy_base=first)
    return total


def _remaining_bucket_sv_usd(role: str, reliever: bool, debut_age: float | None,
                             start_k: int, super_two_fraction: float,
                             war_scale: float = 1.0) -> list[float]:
    """Per-bucket surplus over the REMAINING control window (years start_k..end),
    aging-shaped from debut_age, super-two blended by `super_two_fraction`, at the
    FV-dependent `war_scale`."""
    floors = _config()["buckets"]
    out = []
    for b in range(_N_BUCKETS):
        wars = _bucket_season_wars(role, b, reliever, debut_age, war_scale)
        f = float(super_two_fraction)
        prof = (arb_role(role, reliever), debut_age)
        sv = ((1.0 - f) * _remaining_path_surplus_usd(wars, start_k, False, profile=prof)
              + f * _remaining_path_surplus_usd(wars, start_k, True, profile=prof))
        out.append(max(float(floors[_BUCKETS[b]].get("surplus_floor_usd", 0)), sv))
    return out


def _effective_remaining_bucket_sv(is_pitcher: bool, position: str | None, debut_age: float | None,
                                   start_k: int, super_two_fraction: float,
                                   war_scale: float = 1.0) -> list[float]:
    """Per-bucket REMAINING surplus with the pitcher role-outcome layer applied
    (mirror of _effective_bucket_sv over the remaining window), at the FV-dependent
    `war_scale`. At start_k=0 this reduces to _effective_bucket_sv, so a 0-sample
    debuted pitcher matches the prospect path exactly. Hitter path unchanged."""
    if not is_pitcher:
        return _remaining_bucket_sv_usd("hitter", False, debut_age, start_k, super_two_fraction, war_scale)
    sp = _remaining_bucket_sv_usd("pitcher", False, debut_age, start_k, super_two_fraction, war_scale)
    rp = _remaining_bucket_sv_usd("pitcher", True, debut_age, start_k, super_two_fraction, war_scale)
    p_rp = _pitcher_rp_by_bucket(position)
    haz = float(_config().get("pitcher_role_mix", {}).get("injury_hazard", 0.0))
    out = []
    for b in range(_N_BUCKETS):
        v = (1.0 - p_rp[b]) * sp[b] + p_rp[b] * rp[b]
        if b != 0:
            v *= (1.0 - haz)
        out.append(v)
    return out


def _remaining_continuous_sv_usd(role: str, true_talent_rate: float, debut_age: float | None,
                                 start_k: int, super_two_fraction: float,
                                 reliever: bool = False) -> float:
    """Surplus over the remaining window at a single continuous true-talent rate
    (the regressed projection -- used when the sample graduates a player out of
    the coarse buckets). `reliever` normalizes the 200-IP-band rate to a full
    bullpen season (the same ceiling/IP-normalization the bucket path uses)."""
    level = max(0.0, float(true_talent_rate))
    if reliever:
        level = _reliever_level(level)
    wars = _aged_trajectory(role, level, debut_age)
    f = float(super_two_fraction)
    prof = (arb_role(role, reliever), debut_age)
    sv = ((1.0 - f) * _remaining_path_surplus_usd(wars, start_k, False, profile=prof)
          + f * _remaining_path_surplus_usd(wars, start_k, True, profile=prof))
    return max(0.0, sv)


def _mixture_draws_mm(weights, bucket_svs_usd, target_mean_usd: float, seed: int, n: int):
    """Monte Carlo draws ($M) from a bucket mixture with given weights + per-bucket
    surplus, mean-preserving within-bucket Gamma, scaled so the sample mean tracks
    target_mean_usd. (Generalizes _sv_draws_mm to arbitrary weights/SVs.)"""
    import numpy as np
    cvs = [float(_config().get("distribution", {}).get("within_bucket_cv", {}).get(b, 0.0)) for b in _BUCKETS]
    w = np.asarray(weights, dtype=float)
    w = w / w.sum() if w.sum() > 0 else np.ones(_N_BUCKETS) / _N_BUCKETS
    mix_mean = float(sum(wi * sv for wi, sv in zip(w, bucket_svs_usd)))
    if mix_mean <= 0:
        return np.full(int(n), max(0.0, target_mean_usd) / 1e6)
    scale = target_mean_usd / mix_mean
    eff = [sv * scale for sv in bucket_svs_usd]
    rng = np.random.RandomState(int(seed) % (2 ** 32))
    idx = rng.choice(_N_BUCKETS, size=int(n), p=w)
    sv = np.empty(int(n), dtype=float)
    for b in range(_N_BUCKETS):
        mask = idx == b
        cnt = int(mask.sum())
        if cnt == 0:
            continue
        m, cv = eff[b], cvs[b]
        if cv <= 0 or m <= 0:
            sv[mask] = max(0.0, m)
        else:
            sv[mask] = rng.gamma(1.0 / (cv * cv), m * cv * cv, size=cnt)
    return sv / 1e6


def _realized_consumed_usd(consumed_seasons) -> float:
    """(1) REALIZED piece: banked surplus on control years already played, from
    ACTUAL recorded fWAR and ACTUAL salary paid (no projection). Each season:
    fWAR * $/WAR(that season) - salary_paid; compounded to present value at the
    discount rate (most recent season = now). consumed_seasons: list of dicts
    {fwar, salary_mm, [dpw_mm]} oldest-first.

    Unified $/WAR path mode (VAL_5, row 27): see _realized_consumed_unified_usd."""
    if not consumed_seasons:
        return 0.0
    if dpw_path_active():
        return _realized_consumed_unified_usd(consumed_seasons)
    flat = _flat_rate_usd()
    r = float(_config()["discount_rate"])
    n = len(consumed_seasons)
    total = 0.0
    for i, s in enumerate(consumed_seasons):
        fwar = float(s.get("fwar", 0.0))
        salary_usd = float(s.get("salary_mm", 0.0)) * 1e6
        # Market on the KERNEL-consistent tiered curve (matches the projected/remaining
        # path); legacy dicts without market_mm fall back to fwar * hard-step dpw.
        if s.get("market_mm") is not None:
            market_usd = float(s["market_mm"]) * 1e6
        else:
            dpw = float(s["dpw_mm"]) * 1e6 if s.get("dpw_mm") is not None else flat
            market_usd = fwar * dpw
        total += (market_usd - salary_usd) * ((1.0 + r) ** (n - 1 - i))   # compound past -> now
    return total


def _realized_level_ratio() -> float:
    """price_level(B) / F: the consumed seasons' market priced at the level of the
    remaining leg (row 27)."""
    return price_level(pricing_base_season()) / _flat_rate_usd()


def _realized_consumed_unified_usd(consumed_seasons) -> float:
    """Row 27, unified: each consumed season's MARKET term (either branch) times
    price_level(B)/F, so the realized leg prices at the remaining leg's level;
    salaries paid stay as given (realized_consumed_seasons scales its own
    market-linked estimates); compounding stays at discount_rate, the backward
    item this design leaves out of scope."""
    k = _realized_level_ratio()
    flat = _flat_rate_usd()
    r = float(_config()["discount_rate"])
    n = len(consumed_seasons)
    total = 0.0
    for i, s in enumerate(consumed_seasons):
        fwar = float(s.get("fwar", 0.0))
        salary_usd = float(s.get("salary_mm", 0.0)) * 1e6
        if s.get("market_mm") is not None:
            market_usd = float(s["market_mm"]) * 1e6
        else:
            dpw = float(s["dpw_mm"]) * 1e6 if s.get("dpw_mm") is not None else flat
            market_usd = fwar * dpw
        total += (market_usd * k - salary_usd) * ((1.0 + r) ** (n - 1 - i))
    return total


def _realized_consumed_seasons_unified(rows, salary_by_year, super_two) -> list[dict]:
    """Row 27, unified: the engine's market-linked salary ESTIMATES (arbitration
    frac x market, the post-control fair market) scale by price_level(B)/F with
    the market they are netted against; salary_by_year actuals and the
    league-minimum floor stay nominal at their table values. market_mm stays at
    the level F (the realized leg applies the ratio once)."""
    k = _realized_level_ratio()
    cfg = _config()
    st = cfg["service_time"]
    league_min_mm = float(st["league_min_usd"]) / 1e6
    control_years = int(st["control_years"])
    pre_arb, arb_fracs = _arb_ladder(st, super_two)
    sby = salary_by_year or {}
    arb_basis = str(st.get("arb_basis", "current_season"))
    markets_mm = [tiered_war_value_usd(w) / 1e6 for _, w in rows]
    consumed = []
    for t, (yr, war) in enumerate(rows):
        market_mm = markets_mm[t]
        actual = sby.get(yr, sby.get(str(yr)))
        if actual is not None and float(actual) > 0:
            salary_mm = float(actual) / 1e6
        elif t < pre_arb:
            salary_mm = league_min_mm
        elif t < control_years:
            i = t - pre_arb
            frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
            base_mkt = markets_mm[t - 1] if (arb_basis == "prior_season" and t > 0) else market_mm
            salary_mm = max(league_min_mm, frac * base_mkt * k)
        else:
            salary_mm = max(league_min_mm, market_mm * k)
        consumed.append({"fwar": war, "salary_mm": round(salary_mm, 4),
                         "market_mm": round(market_mm, 4),
                         "dpw_mm": round(dollars_per_war(war), 6), "year": yr})
    return consumed


def realized_consumed_seasons(season_wars_by_year, *, salary_by_year=None,
                              super_two: bool = False) -> list[dict]:
    """Build the consumed-seasons list ({fwar, salary_mm, dpw_mm}, oldest-first)
    that debuted_player_value / _realized_consumed_usd consume, from a player's
    ACTUAL per-year fWAR. Salary is estimated on the engine's OWN service-time
    model (single source of truth -- no separate frontend salary table): the
    first `pre_arb_years` seasons at league minimum, then
    arb_model.fractions_of_fa_value of THAT season's tiered market value
    (super-two drops one pre-arb year and prepends the extra early arb year at
    super_two_first_fraction clamped to the arb-1 step; see _arb_ladder),
    then full tiered market for any post-control (FA) seasons; every year floored
    at the league minimum. A real per-year salary (USD) supplied in
    `salary_by_year` (e.g. Spotrac) OVERRIDES the estimate for that year.

    `season_wars_by_year`: a {year: fWAR} mapping or an iterable of (year, war).
    Seasons are ordered oldest-first and indexed against the control clock by
    position (the same approximation the prior frontend model used). dpw_mm is
    the tier rate the season's market was valued at, so the downstream
    `fwar * dpw - salary` reproduces tiered_war_value_usd(fwar) exactly."""
    if not season_wars_by_year:
        return []
    if isinstance(season_wars_by_year, dict):
        items = [(y, season_wars_by_year[y]) for y in season_wars_by_year]
    else:
        items = list(season_wars_by_year)
    rows = []
    for y, w in items:
        try:
            yr = int(y)
            war = float(w)
        except (TypeError, ValueError):
            continue
        if not math.isfinite(war):
            continue
        rows.append((yr, war))
    if not rows:
        return []
    rows.sort(key=lambda t: t[0])
    if dpw_path_active():
        return _realized_consumed_seasons_unified(rows, salary_by_year, super_two)

    cfg = _config()
    st = cfg["service_time"]
    league_min_mm = float(st["league_min_usd"]) / 1e6
    control_years = int(st["control_years"])
    pre_arb, arb_fracs = _arb_ladder(st, super_two)
    sby = salary_by_year or {}

    arb_basis = str(st.get("arb_basis", "current_season"))
    markets_mm = [tiered_war_value_usd(w) / 1e6 for _, w in rows]   # $M market, 0 for war<=0
    consumed = []
    for t, (yr, war) in enumerate(rows):
        market_mm = markets_mm[t]
        actual = sby.get(yr, sby.get(str(yr)))
        if actual is not None and float(actual) > 0:
            salary_mm = float(actual) / 1e6
        elif t < pre_arb:
            salary_mm = league_min_mm
        elif t < control_years:
            i = t - pre_arb
            frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
            # Arb salaries settle on the PRIOR season's market under prior_season basis
            # (the production convention), not this season's.
            base_mkt = markets_mm[t - 1] if (arb_basis == "prior_season" and t > 0) else market_mm
            salary_mm = max(league_min_mm, frac * base_mkt)
        else:                                                  # post-control: paid ~fair market
            salary_mm = max(league_min_mm, market_mm)
        # Store the tiered MARKET (kernel-consistent with the projected/remaining path),
        # not fwar * hard-step dollars_per_war -- the banked realized surplus is now
        # market - salary, on the same $/WAR curve as every other surplus. dpw_mm kept
        # for back-compat display / legacy consumers.
        consumed.append({"fwar": war, "salary_mm": round(salary_mm, 4),
                         "market_mm": round(market_mm, 4),
                         "dpw_mm": round(dollars_per_war(war), 6), "year": yr})
    return consumed


def _lowtier_remaining_scale(fv: float, is_pitcher: bool, position: str | None,
                             debut_age: float | None) -> float:
    """For FV below the Edwards bridge, the ratio of the prospect anchor/bridge
    value to the raw (role-mixed) bucket pipeline (full window) -- applied to the
    debuted remaining mean so a 0-sample player matches surplus_value_mm exactly
    below FV 45 too. Uses the SAME role-mix as the remaining computation so the
    ratio is over the same quantity. 1.0 at FV >= bridge_to (pure pipeline)."""
    a = _config()["lowtier_anchor"]
    if fv >= float(a["bridge_to_fv"]):
        return 1.0
    svs = _effective_bucket_sv(is_pitcher, position, debut_age, 0.0, _war_scale_for(fv, _role_key(is_pitcher)))
    full_pipe = _pipeline_surplus_from_svs(fv, is_pitcher, svs)
    if full_pipe <= 0:
        return 1.0
    prospect = expected_surplus_usd(fv, is_pitcher, position, age=debut_age, eta_years=0)
    return (prospect / full_pipe) if prospect is not None else 1.0


def _debuted_remaining_draws(posterior, remaining_bucket_sv, mix_mean_usd: float,
                             continuous_mean_usd: float, w_grad: float, scale: float,
                             seed: int, n: int):
    """Two-component remaining-SV draws ($M): the posterior bucket mixture (weight
    1-w_grad) and the continuous graduated projection (weight w_grad), then * the
    low-tier scale. Mean = ((1-w_grad)*mix_mean + w_grad*continuous_mean)*scale,
    so it matches the reported remaining mean while keeping the bust mass at $0
    and the graduated upside as a separate component."""
    import numpy as np
    n = int(n)
    mix = _mixture_draws_mm(posterior, remaining_bucket_sv, mix_mean_usd, seed, n)   # mean = mix_mean
    cv = float(_config().get("debuted", {}).get("continuous_cv", 0.35))
    cm = max(0.0, continuous_mean_usd) / 1e6
    rng = np.random.RandomState((int(seed) + 7919) % (2 ** 32))
    if cm <= 0 or cv <= 0:
        cont = np.full(n, cm)
    else:
        cont = rng.gamma(1.0 / (cv * cv), cm * cv * cv, size=n)
    take_cont = rng.random_sample(n) < float(w_grad)
    draws = np.where(take_cont, cont, mix)
    return draws * float(scale)


def _talent_regression(fv, is_pitcher: bool, observed_war: float,
                       observed_pa: float | None, observed_ip: float | None,
                       fv_reflects_mlb: float = 0.0) -> dict:
    """SHARED reliability core used by BOTH the debuted-player Bayes update (Prompt D)
    and WAG (Prompt M) -- same constants (reliability.*, debuted.*), same residual.

    Regresses an observed WAR RATE toward the FV-implied prior-mean talent (Marcel:
    blend observed with k_reg pseudo-seasons of the prior) and updates the outcome-
    bucket prior by a sample-tempered Gaussian likelihood. Everything is on the
    200-IP / 600-PA BAND scale for ALL roles -- the reliever role-VALUE haircut is a
    dollar effect applied ONCE downstream (_reliever_level), NEVER on the talent /
    grade-inference scale, so a reliever's rate (and thus WAG) is not distorted.

    Returns: prior, posterior (bucket weights), mids (calibrated midpoints),
    prior_mean_rate (FV-implied talent rate / full season), obs_rate (observed rate /
    full season, None if no sample), true_talent (regressed rate), w_obs (reliability
    weight k_eff/(k_eff+k_reg)), sigma (SD of the rate estimate), posterior_sd (SD of
    the regressed true-talent rate), w_grad, k_eff, k_reg, ref, sample, role."""
    cfg = _config()
    role = _role_key(is_pitcher)
    deb = cfg.get("debuted", {})
    rel = cfg.get("reliability", {})
    ref = float(deb["full_season_pa"]) if not is_pitcher else float(deb["full_season_ip"])
    sample = max(0.0, float((observed_pa if not is_pitcher else observed_ip) or 0.0))
    k_eff = sample * (1.0 - min(1.0, max(0.0, float(fv_reflects_mlb))))     # avoid FV/MLB double-count
    if not is_pitcher and k_eff > 0:
        dstab = float(rel.get("defense_seasons_to_stabilize", 3))
        seasons_played = sample / ref
        if seasons_played < dstab:                                          # early hitter defense is noise
            pen = float(deb.get("defense_early_penalty", 0.0))
            k_eff *= (1.0 - pen * (1.0 - seasons_played / max(dstab, 1e-9)))
    prior = p_bucket_given_fv(fv, is_pitcher)
    _ws = _war_scale_for(fv, role)                                      # FV-dependent bucket level
    mids_role = [m * _ws for m in _calibrated_midpoints(role)]
    prior_mean_rate = sum(p * m for p, m in zip(prior, mids_role))
    obs_rate = (float(observed_war) * ref / sample) if sample > 0 else None
    k_reg = float(rel["hitter_regression_pa"]) if not is_pitcher else float(rel["pitcher_regression_ip"])
    sd_full = float(deb["obs_war_sd_per_full_season"][role])
    if obs_rate is None or k_eff <= 0:
        posterior = list(prior)
        true_talent = prior_mean_rate
        w_obs = w_grad = 0.0
        sigma = None
        posterior_sd = sd_full * math.sqrt(ref / max(k_reg, 1e-9))          # prior-only spread
    else:
        true_talent = (obs_rate * k_eff + prior_mean_rate * k_reg) / (k_eff + k_reg)
        w_obs = k_eff / (k_eff + k_reg)
        sigma = sd_full * math.sqrt(ref / max(k_eff, 1e-9))                 # SD of the rate estimate
        posterior_sd = sd_full * math.sqrt(ref / (k_eff + k_reg))          # SD of the regressed mean
        loglik = [-0.5 * ((obs_rate - m) / sigma) ** 2 for m in mids_role]
        logpost = [math.log(max(pr, 1e-300)) + w_obs * ll for pr, ll in zip(prior, loglik)]
        mx = max(logpost)
        ex = [math.exp(lp - mx) for lp in logpost]
        ssum = sum(ex)
        posterior = [e / ssum for e in ex] if ssum > 0 else list(prior)
        k_grad = float(deb["graduation_sample"]["hitter_pa" if not is_pitcher else "pitcher_ip"])
        w_grad = k_eff / (k_eff + k_grad)
    return {
        "role": role, "ref": ref, "sample": sample, "k_eff": k_eff, "k_reg": k_reg,
        "prior": prior, "mids": mids_role, "prior_mean_rate": prior_mean_rate,
        "obs_rate": obs_rate, "true_talent": true_talent, "w_obs": w_obs,
        "w_grad": w_grad, "sigma": sigma, "posterior_sd": posterior_sd, "posterior": posterior,
    }


def debuted_player_value(
    fv: float | None,
    is_pitcher: bool,
    position: str | None = None,
    *,
    observed_war: float = 0.0,
    observed_pa: float | None = None,
    observed_ip: float | None = None,
    service_time: float = 0.0,
    super_two: bool = False,
    super_two_known: bool = True,
    age: float | None = None,
    consumed_seasons: list | None = None,
    fv_reflects_mlb: float = 0.0,
    draws: int | None = None,
    seed: int | None = None,
    threshold_mm: float | None = None,
    risk_lambda: float | None = None,
) -> dict | None:
    """Value a DEBUTED player: REALIZED (consumed control years, actual WAR+salary)
    + REMAINING (projected). Recorded WAR plays two non-overlapping roles -- banked
    production (realized) and EVIDENCE that Bayes-updates the bucket prior for the
    remaining years (trade value). Reduces EXACTLY to the prospect model at 0 PA/IP.

    Returns: trade_value_mm (remaining only -- consumed is sunk), total_value_mm
    (realized + remaining), realized_mm, `remaining` (the Prompt-E distribution
    dict), prior/posterior bucket weights, regressed true_talent_war, and the
    observed/graduation weights. `fv_reflects_mlb` (0..1) down-weights the update
    when the FV already ingested MLB data (double-count guard; use_pre_debut_fv)."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None

    cfg = _config()
    role = _role_key(is_pitcher)
    deb = cfg.get("debuted", {})
    rel = cfg.get("reliability", {})
    st = cfg["service_time"]
    control_years = int(st["control_years"])
    dcfg = cfg.get("distribution", {})
    n = _mc_draws(draws)
    thr = float(threshold_mm if threshold_mm is not None else dcfg.get("sv_threshold_mm", 50.0))
    lam = _risk_lambda(risk_lambda)
    base_seed = int(seed if seed is not None else dcfg.get("seed", 1234567))

    # --- (2)(3)(5) SHARED reliability core: regress observed rate -> true talent and
    # update the outcome-bucket prior (the SAME _talent_regression WAG uses, so the
    # Prompt-D posterior and WAG move with one residual / weight / set of constants). ---
    tr = _talent_regression(f, is_pitcher, observed_war, observed_pa, observed_ip, fv_reflects_mlb)
    prior, posterior = tr["prior"], tr["posterior"]
    true_talent, obs_rate = tr["true_talent"], tr["obs_rate"]
    w_obs, w_grad = tr["w_obs"], tr["w_grad"]
    sample, k_eff = tr["sample"], tr["k_eff"]

    # --- (4) remaining control window on the ACTUAL service clock ---
    n_consumed = max(0, min(control_years, int(round(float(service_time)))))
    start_k = n_consumed
    s2cfg = st["super_two"]
    s2_frac_pop = float(s2cfg["fraction"]) if s2cfg.get("enabled") else 0.0
    # super-two is uncertain for a just-debuted player -> blend by population rate
    # (matches the prospect model exactly at continuity); known thereafter.
    # S1 (audit B1, gated): a SERVICED player whose super-two status is genuinely
    # unknown (super_two_known=False) is otherwise treated as non-super-two (0);
    # blend by the population rate instead, the same treatment the just-debuted
    # player already gets. KNOWN-status players are unchanged, and with the flag
    # off or super_two_known=True (the default) this is byte-identical to before.
    _s1_on = bool((cfg.get("surplus_levers") or {}).get("super_two_population_blend"))
    if sample <= 0 and float(service_time) <= 0:
        super_two_fraction = s2_frac_pop                       # just-debuted: population blend
    elif _s1_on and not super_two_known:
        super_two_fraction = s2_frac_pop                       # S1: unknown serviced -> population
    else:
        super_two_fraction = 1.0 if super_two else 0.0         # known status
    # Round debut age to the same 0.5-yr grid the prospect path uses (_round_timing),
    # so continuity at 0 PA is exact at fractional ages too.
    debut_age = (round((float(age) - n_consumed) * 2) / 2) if age is not None else None

    # Role-mixed remaining bucket SVs (pitcher SP/RP blend per bucket; reduces to
    # _effective_bucket_sv at start_k=0 so 0-sample continuity with the prospect
    # path is exact). Hitter path unchanged.
    remaining_bucket_sv = _effective_remaining_bucket_sv(is_pitcher, position, debut_age,
                                                         start_k, super_two_fraction,
                                                         _war_scale_for(fv, _role_key(is_pitcher)))
    posterior_mixture_mean = sum(p * sv for p, sv in zip(posterior, remaining_bucket_sv))
    # Continuous (graduated) projection, role-mixed: blend the full-SP and the
    # bullpen-capped RP continuous values by the posterior-weighted P(reliever)
    # over the non-bust mass, with the same attrition haircut as the buckets.
    cont_sp = _remaining_continuous_sv_usd(role, true_talent, debut_age, start_k, super_two_fraction)
    if is_pitcher:
        p_rp_b = _pitcher_rp_by_bucket(position)
        nonbust = sum(posterior[1:]) or 1.0
        p_rp_eff = sum(posterior[b] * p_rp_b[b] for b in range(1, _N_BUCKETS)) / nonbust
        haz = float(cfg.get("pitcher_role_mix", {}).get("injury_hazard", 0.0))
        cont_rp = _remaining_continuous_sv_usd(role, true_talent, debut_age, start_k,
                                               super_two_fraction, reliever=True)
        continuous_mean = ((1.0 - p_rp_eff) * cont_sp + p_rp_eff * cont_rp) * (1.0 - haz)
    else:
        continuous_mean = cont_sp
    blend_usd = max(0.0, (1.0 - w_grad) * posterior_mixture_mean + w_grad * continuous_mean)
    # FV < bridge_to: scale to the prospect Edwards anchor/bridge so a 0-sample
    # player matches surplus_value_mm exactly below FV 45 too (scale 1.0 at >=45).
    lowtier_scale = _lowtier_remaining_scale(f, is_pitcher, position, debut_age)
    remaining_mean_usd = blend_usd * lowtier_scale

    # --- (6) remaining distribution via the Prompt-E contract: a genuine TWO-
    # component mixture -- the posterior bucket mixture (weight 1-w_grad, keeping
    # the bust mass at $0) and the continuous graduated projection (weight w_grad).
    # Mean-preserving by construction (no cross-scaling artifact).
    seed_mix = base_seed + int(round(f * 100)) + (1 if is_pitcher else 0)
    sv_mm = _debuted_remaining_draws(posterior, remaining_bucket_sv, posterior_mixture_mean,
                                     continuous_mean, w_grad, lowtier_scale, seed_mix, n)
    import numpy as _np
    p_bust_eff = float((_np.asarray(sv_mm) <= 0.1).mean())   # P(remaining ~ $0) going forward
    remaining_dist = _dist_output(sv_mm, p_bust_eff, remaining_mean_usd / 1e6,
                                  threshold_mm=thr, risk_lambda=lam)

    realized_usd = _realized_consumed_usd(consumed_seasons)
    trade_value_mm = round(apply_calibration(remaining_mean_usd / 1e6, f, is_pitcher), 1)
    if n_consumed >= control_years:
        # No control year left: the remaining value is $0 by definition. The isotonic
        # calibration's bottom knot would otherwise serve its $1.0M floor (M10, once
        # service time reached the engine and 363 graduates priced at 0 years left).
        trade_value_mm = 0.0
    total_value_mm = round(realized_usd / 1e6 + trade_value_mm, 1)
    return {
        "trade_value_mm": trade_value_mm,      # REMAINING control years only (consumed = sunk)
        "total_value_mm": total_value_mm,      # realized banked + remaining
        "realized_mm": round(realized_usd / 1e6, 2),
        "remaining": remaining_dist,           # Prompt-E distribution dict (the trade-value distribution)
        "prior": {b: round(prior[i], 4) for i, b in enumerate(_BUCKETS)},
        "posterior": {b: round(posterior[i], 4) for i, b in enumerate(_BUCKETS)},
        "true_talent_war": round(true_talent, 3),
        "obs_rate_war_per_season": (round(obs_rate, 3) if obs_rate is not None else None),
        "w_observed": round(w_obs, 3),
        "w_graduated": round(w_grad, 3),
        "service_time": float(service_time),
        "consumed_control_years": n_consumed,
        "remaining_control_years": control_years - n_consumed,
        "k_eff": round(k_eff, 1),
    }


# =============================================================================
# WAG -- WAR Above Grade (Prompt M), rebuilt on the FV-projection core
# =============================================================================
# WAG = observed WAR - the FV-implied expectation OVER THE SAME EXPOSURE. It reuses
# the SAME outcome-bucket WAR core as surplus value and the debuted update (no
# separate FV->WAR table), truncates the FV trajectory to the player's exposure and
# age-places it on the aging curve (the rookie-ramp fix), reports counting + rate +
# a distribution-aware standardized signal (percentile/z), and a reliability-
# regressed true-talent WAG sharing the debuted-mode constants.
def _norm_cdf(z: float) -> float:
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def _cred_z(cred: float) -> float:
    """Two-sided z for a central credible mass (0.90 -> 1.6449)."""
    try:
        from scipy.stats import norm
        return float(norm.ppf(0.5 + min(max(float(cred), 0.0), 0.999999) / 2.0))
    except Exception:
        return 1.6448536269514722


def _exposure_seasons(is_pitcher: bool, exposure_pa, exposure_ip, service_years, ref):
    """Resolve exposure to (sample in PA|IP, season-equivalents). `service_years`
    (if given) wins; else PA/IP over the role full-season reference `ref`."""
    if service_years is not None:
        try:
            se = max(0.0, float(service_years))
        except (TypeError, ValueError):
            se = 0.0
        return se * ref, se
    raw = exposure_ip if is_pitcher else exposure_pa
    try:
        sample = max(0.0, float(raw or 0.0))
    except (TypeError, ValueError):
        sample = 0.0
    return sample, (sample / ref if ref > 0 else 0.0)


def _bucket_cumulative_war(traj: list[float], seasons: float) -> float:
    """Cumulative WAR over `seasons` season-equivalents of a per-season trajectory
    (pro-rates the partial final season; extends flat past the control window)."""
    if seasons <= 0 or not traj:
        return 0.0
    full = int(seasons)
    total = sum(traj[k] if k < len(traj) else traj[-1] for k in range(full))
    frac = seasons - full
    if frac > 0:
        total += frac * (traj[full] if full < len(traj) else traj[-1])
    return total


def expected_war(fv, is_pitcher: bool, position: str | None = None, *,
                 exposure_pa: float | None = None, exposure_ip: float | None = None,
                 service_years: float | None = None, age: float | None = None) -> dict | None:
    """SHARED FV-implied WAR DISTRIBUTION over a given EXPOSURE (Prompt M core).

    Built on the SAME bucket trajectory core as surplus value and the debuted update
    (p_bucket_given_fv x _bucket_season_wars x calibrated midpoints) -- NO separate
    FV->WAR lookup. The FV trajectory is TRUNCATED to the player's actual exposure
    and AGE-PLACED on the aging curve (rookie ramp): debut age = age - seasons
    played, so the seasons he HAS played sit on the correct part of the curve.
    Returns the distribution of cumulative WAR a player of this FV would post over
    THIS exposure: `mean` (expected cumulative WAR), `mean_rate` (per full season),
    `sd` (bucket spread + observation noise), `seasons`, and per-bucket `components`
    [(weight, cum_war, sd_within)] for percentile / z. None for bad FV."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    cfg = _config()
    role = _role_key(is_pitcher)
    deb = cfg.get("debuted", {})
    ref = float(deb["full_season_pa"]) if not is_pitcher else float(deb["full_season_ip"])
    sample, seasons = _exposure_seasons(is_pitcher, exposure_pa, exposure_ip, service_years, ref)
    probs = p_bucket_given_fv(f, is_pitcher)
    # Debut age on the same 0.5-yr grid the prospect/debuted timing uses; None when
    # age is unknown -> the fixed (non-aged) trajectory shape.
    debut_age = (round((float(age) - seasons) * 2) / 2) if age is not None else None
    sd_full = float(deb["obs_war_sd_per_full_season"][role])
    sd_within = sd_full * math.sqrt(max(seasons, 0.0))             # cumulative obs noise over exposure
    comps, mean = [], 0.0
    for b in range(_N_BUCKETS):
        # Band-scale trajectory (reliever=False): WAG grades on the talent/band scale;
        # the reliever role-VALUE haircut is a $ effect applied once downstream only.
        traj = _bucket_season_wars(role, b, False, debut_age, _war_scale_for(f, role))
        cum_b = _bucket_cumulative_war(traj, seasons)
        comps.append((float(probs[b]), cum_b, sd_within))
        mean += probs[b] * cum_b
    var = sum(w * (sw * sw + cb * cb) for w, cb, sw in comps) - mean * mean  # mixture variance
    return {
        "mean": mean,
        "mean_rate": (mean / seasons if seasons > 0 else 0.0),
        "sd": math.sqrt(max(0.0, var)),
        "seasons": seasons,
        "sample": sample,
        "ref": ref,
        "components": comps,
        "probs": list(probs),
    }


def wag(fv, is_pitcher: bool, observed_war: float, *, position: str | None = None,
        exposure_pa: float | None = None, exposure_ip: float | None = None,
        service_years: float | None = None, age: float | None = None,
        fv_reflects_mlb: float = 0.0, cred: float | None = None) -> dict | None:
    """WAR Above Grade on the FV-projection core (Prompt M).

    WAG = observed WAR - the FV-implied expectation OVER THE SAME EXPOSURE (rookie
    ramp via aging). Reports:
      counting_wag -- observed WAR - exposure-matched expected cumulative WAR
      rate_wag     -- observed rate - expected rate (per 600 PA / 200 IP)
      percentile   -- HEADLINE standardized signal: the player's position (PIT) in
                      the FV's predicted distribution AT THIS EXPOSURE (0.5 = on
                      grade, >0.5 ahead); distribution-aware, comparable across FVs
      z            -- (observed - expected) / sd at this exposure
      regressed_wag (+ lo/hi) -- reliability-REGRESSED true-talent rate WAG, shrunk
                      toward 0 by w_obs with an uncertainty band; SHARES the debuted
                      core, so it and the Prompt-D posterior move with the same sign
                      and sample weight
      true_talent_war, w_obs  -- shared with debuted_player_value
      below_meaningful_exposure -- flag when exposure < wag.meaningful_exposure

    Reliever-safe (grades on the band/talent scale). Continuity: zero exposure ->
    WAG 0, percentile 0.5, z 0. None for missing / unparseable FV."""
    ew = expected_war(fv, is_pitcher, position, exposure_pa=exposure_pa,
                      exposure_ip=exposure_ip, service_years=service_years, age=age)
    if ew is None:
        return None
    cfg = _config()
    wcfg = cfg.get("wag", {})
    seasons, ref, sample = ew["seasons"], ew["ref"], ew["sample"]
    me = wcfg.get("meaningful_exposure", {})
    thr_exposure = float(me.get("pitcher_ip", 0) if is_pitcher else me.get("hitter_pa", 0))
    # When the expected baseline is matched to SEASONS (service_years) but the REAL
    # accumulated PA/IP is also supplied, the meaningful-exposure GATE and the
    # talent-regression RELIABILITY stay on the real load: an injury-shortened
    # player is graded over the seasons he's been in the majors (so WAG reflects
    # accumulation, not a small-sample rate) yet a thin multi-season sample is
    # still gated + heavily regressed rather than treated as a full season load.
    real_exp = exposure_ip if is_pitcher else exposure_pa
    gate_sample = float(real_exp) if real_exp is not None else sample
    below = gate_sample < thr_exposure

    # Shared talent-level regression (same core/constants as the Prompt-D update),
    # weighted by the REAL exposure when supplied, else the season-implied load.
    if exposure_pa is not None or exposure_ip is not None:
        eff_pa, eff_ip = exposure_pa, exposure_ip
    elif service_years is not None:
        eff_pa = None if is_pitcher else seasons * ref
        eff_ip = (seasons * ref) if is_pitcher else None
    else:
        eff_pa, eff_ip = None, None
    tr = _talent_regression(fv, is_pitcher, observed_war, eff_pa, eff_ip, fv_reflects_mlb)
    standardized = str(wcfg.get("standardized", "percentile"))

    if seasons <= 0 or sample <= 0:                                # continuity: no information
        return {
            "counting_wag": 0.0, "rate_wag": 0.0, "percentile": 0.5, "z": 0.0,
            "regressed_wag": 0.0, "regressed_lo": 0.0, "regressed_hi": 0.0,
            "true_talent_war": round(tr["prior_mean_rate"], 3),
            "expected_war": 0.0, "expected_rate": round(tr["prior_mean_rate"], 3),
            "observed_war": round(float(observed_war), 3), "observed_rate": None,
            "w_obs": 0.0, "exposure": sample, "seasons": 0.0,
            "below_meaningful_exposure": True, "standardized": standardized,
        }

    observed = float(observed_war)
    observed_rate = observed * ref / sample
    counting = observed - ew["mean"]
    rate = observed_rate - ew["mean_rate"]
    z = (counting / ew["sd"]) if ew["sd"] > 0 else 0.0
    # Percentile (PIT): mixture CDF of the predicted cumulative WAR at the observed.
    pit = 0.0
    for w_b, cum_b, sw in ew["components"]:
        pit += w_b * (_norm_cdf((observed - cum_b) / sw) if sw > 1e-12
                      else (1.0 if observed >= cum_b else 0.0))
    pit = min(1.0, max(0.0, pit))

    # regressed_wag is the per-SEASON rate WAG (observed WAR/season vs the FV-implied
    # WAR/season) shrunk toward 0 by the real-PA reliability weight w_obs, so a thin
    # sample regresses hard. Season-based per the service-years framing — driven by
    # accumulation over the seasons a player has been in the majors, NOT the per-PA
    # rate. (true_talent_war below is the PA-rate true-talent, unchanged, and still
    # feeds the debuted posterior / surplus.)
    w_obs = float(tr["w_obs"])
    regressed = w_obs * rate
    sd_season = (ew["sd"] / seasons) if seasons > 0 else 0.0
    half = _cred_z(cred if cred is not None else cfg.get("fit", {}).get("bayes", {}).get("credible_mass", 0.90)) \
        * sd_season * (1.0 - w_obs)
    return {
        "counting_wag": round(counting, 3),
        "rate_wag": round(rate, 3),
        "percentile": round(pit, 4),
        "z": round(z, 3),
        "regressed_wag": round(regressed, 3),
        "regressed_lo": round(regressed - half, 3),
        "regressed_hi": round(regressed + half, 3),
        "true_talent_war": round(tr["true_talent"], 3),
        "expected_war": round(ew["mean"], 3),
        "expected_rate": round(ew["mean_rate"], 3),
        "observed_war": round(observed, 3),
        "observed_rate": round(observed_rate, 3),
        "w_obs": round(tr["w_obs"], 3),
        "exposure": sample,
        "seasons": round(seasons, 3),
        "below_meaningful_exposure": below,
        "standardized": standardized,
    }


def wag_boom_bust(wag_result: dict | None) -> str:
    """Categorize a player's WAR-above-grade as boom / bust / settled / unsettled,
    keyed on the STANDARDIZED WAG -- his percentile (PIT) in the FV's predicted
    outcome distribution AT HIS EXPOSURE (Prompt M) -- NOT a raw WAR delta. So it
    is distribution-aware and comparable across FVs, and an exposure below
    wag.meaningful_exposure (or no WAG) stays 'unsettled' (too thin to call). The
    thresholds live in config.wag.boom_bust."""
    if not wag_result or wag_result.get("below_meaningful_exposure"):
        return "unsettled"
    pct = wag_result.get("percentile")
    if pct is None:
        return "unsettled"
    bb = _config().get("wag", {}).get("boom_bust", {})
    if float(pct) >= float(bb.get("boom_percentile", 0.80)):
        return "boom"
    if float(pct) <= float(bb.get("bust_percentile", 0.20)):
        return "bust"
    return "settled"


def _wag_for_player(p: dict) -> dict | None:
    """wag(...) for a player dict: {fv, is_pitcher, position, age, observed_war,
    and exposure as `pa`/`ip` or `service_years`, optional `fv_reflects_mlb`}."""
    return wag(p.get("fv"), bool(p.get("is_pitcher")), float(p.get("observed_war", 0.0) or 0.0),
               position=p.get("position"), exposure_pa=p.get("pa"), exposure_ip=p.get("ip"),
               service_years=p.get("service_years"), age=p.get("age"),
               fv_reflects_mlb=float(p.get("fv_reflects_mlb", 0.0) or 0.0))


def wag_leaderboard(players, *, n: int = 10, by: str = "percentile",
                    include_below_exposure: bool = False) -> dict:
    """WAG risers / fallers (Prompt M aggregate). `players`: iterable of player dicts
    (see _wag_for_player). `by` in {percentile, z, rate_wag, counting_wag,
    regressed_wag}. Drops players with no WAG; excludes sub-meaningful-exposure
    unless include_below_exposure. Returns {'risers': [...], 'fallers': [...]}."""
    rows = []
    for p in (players or []):
        w = _wag_for_player(p)
        if w is None or (w["below_meaningful_exposure"] and not include_below_exposure):
            continue
        rows.append({**p, "wag": w})
    rows.sort(key=lambda r: r["wag"].get(by, 0.0), reverse=True)
    return {"risers": rows[:n], "fallers": list(reversed(rows[-n:])) if rows else []}


def wag_mean_by(players, *, group_by: str = "source", metric: str = "regressed_wag",
                include_below_exposure: bool = False) -> dict:
    """Mean WAG by group -- the bias signal feeding Prompt N (mean WAG by FV SOURCE:
    a source whose grads systematically beat grade is grading low/cold) plus org /
    position / level rollups. Returns {group: {mean, mean_percentile, n}}."""
    groups: dict = {}
    for p in (players or []):
        w = _wag_for_player(p)
        if w is None or (w["below_meaningful_exposure"] and not include_below_exposure):
            continue
        d = groups.setdefault(p.get(group_by, "?"), {"_sum": 0.0, "_pit": 0.0, "n": 0})
        d["_sum"] += float(w.get(metric, 0.0))
        d["_pit"] += float(w.get("percentile", 0.5))
        d["n"] += 1
    return {g: {"mean": round(d["_sum"] / max(1, d["n"]), 3),
                "mean_percentile": round(d["_pit"] / max(1, d["n"]), 4), "n": d["n"]}
            for g, d in groups.items()}


# =============================================================================
# Source-calibration loop (Prompt N): de-bias + reliability-weight the consensus
# =============================================================================
# Closes the loop M -> N -> core. Each industry source's TRACK RECORD over its
# historically graded players (the per-source error of its FV vs the realized-
# implied FV, where realized WAR is reconstructed by Prompt F) yields:
#   * a per-source BIAS (de-bias the grade; conditional by role x FV-tier, shrunk),
#   * a covariance-aware reliability WEIGHT (GLS: w ~ Sigma^-1 1, so a cluster of
#     copy-cat sources shares one source's weight, not N).
# The rebuilt consensus FV -- de-biased, reliability-weighted, with a precision-
# based uncertainty -- feeds the FV-projection core (surplus_value_mm / wag) AND
# Prompt I (combined with the disagreement spread). Complements I (which uses
# cross-source DISAGREEMENT for uncertainty); N uses each source's history.
#
# Inputs REUSE Prompt F's realized reconstruction: the caller sets
# record["realized_war"] = backtest._realized_control_war(record.realized) -- this
# module never reimplements the outcome reconstruction (and avoids importing
# backtest, which imports this module).
def _expected_control_war(fv, is_pitcher, exposure_seasons, age=None, position=None):
    ew = expected_war(fv, is_pitcher, position, service_years=exposure_seasons, age=age)
    return ew["mean"] if ew else None


# Concave exponent for the FanGraphs-shaped re-spread of the FV 20-45 low end (see
# realized_implied_fv). <1 makes FV rise fast off zero WAR (FanGraphs' 30/40/45 ladder
# spans only a small WAR band), so a positive-but-low projection reads up-down/bench,
# not org. 0.45 lands a ~0.6 6yr-WAR breakout (e.g. a CPX masher) in the mid-30s.
_LOWEND_FG_EXP = 0.45


def realized_implied_fv(realized_war, is_pitcher: bool, *, exposure_seasons=None,
                        age=None, position=None) -> float | None:
    """Invert the FV-projection core: the FV whose FV-implied expected control-window
    WAR equals `realized_war` over the same exposure. Monotone -> bisection on the upper
    range; clamps to the [20, 80] grade range.

    LOW END (FV 20-45): the bucket-inversion COLLAPSES here. The org-guy outcome tail
    (even a 20-FV prospect becomes a real player ~1% of the time) inflates
    expected_control_war(<=~44) to ~1 WAR, so every positive-but-low projection maps to the
    FV-20 floor and the FanGraphs 30/40/45 ladder (org -> up-down -> bench -> low reg) is
    unreachable. Instead we re-spread the [0, war45] WAR range across FV [20, 45] with a
    concave (FanGraphs-shaped) curve, so a genuine breakout reads up-down/bench, not org.
    This is MONOTONE in realized_war, so the model's OOS ranking (Spearman) is unchanged --
    it only adds low-end display granularity to match the industry FV->WAR scale."""
    if realized_war is None:
        return None
    cy = exposure_seasons if exposure_seasons is not None else int(_config()["service_time"]["control_years"])
    ehi = _expected_control_war(80.0, is_pitcher, cy, age, position)
    war45 = _expected_control_war(45.0, is_pitcher, cy, age, position)
    if ehi is None or war45 is None:
        return None
    if realized_war >= ehi:
        return 80.0
    # Low end: FanGraphs-shaped re-spread of FV 20-45 (the bucket curve is flat/unusable here)
    if war45 > 0 and realized_war < war45:
        if realized_war <= 0:
            return 20.0
        return 20.0 + 25.0 * ((realized_war / war45) ** _LOWEND_FG_EXP)
    # High end: bisection FV 45-80 (where the bucket curve resolves cleanly)
    lo, hi = 45.0, 80.0
    for _ in range(40):
        mid = 0.5 * (lo + hi)
        em = _expected_control_war(mid, is_pitcher, cy, age, position)
        if em is None:
            return None
        if em < realized_war:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


