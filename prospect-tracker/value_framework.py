def _roster_group(position: str | None, is_pitcher: bool = False) -> str:
    """Map a prospect's position to a roster slot-group key for the logjam cap."""
    pos_cfg = _config()["position"]
    p = _pos_primary(position)
    if p is not None and p in set(pos_cfg["reliever_positions"]):
        return "RP"
    if (p is not None and p in set(pos_cfg["pitcher_positions"])) or (p is None and is_pitcher):
        return "SP"
    if p in ("CF", "LF", "RF", "OF"):
        return "OF"
    return p if p is not None else "UTIL"


def system_surplus_distribution(prospects, *, draws=None, seed=None, correlation=None,
                                apply_cap=None, threshold_mm=None, risk_lambda=None,
                                percentiles=None) -> dict | None:
    """Farm-system surplus ROLLUP as a DISTRIBUTION, not a sum of means (Prompt K).
    `prospects` is an iterable of dicts, each {fv, is_pitcher, position, [age],
    [eta_years], [fv_dispersion | source_fvs], [n_sources]} -- the same inputs the
    per-prospect distribution takes. Returns the Prompt-E-style system output dict
    plus `sum_of_means`, `realization_discount`, `n_prospects`, `correlation`,
    `cap_applied`; or None if no valid prospect.

    Two system effects beyond the naive sum of means:
      * OUTCOME CORRELATION (single-factor Gaussian copula): each prospect's Monte
        Carlo draws are REORDERED to a shared correlation rho via Z_i = sqrt(rho)*G
        + sqrt(1-rho)*E_i. Reordering exactly preserves every marginal, so the
        system MEAN is always the sum of individual means -- only the SPREAD grows
        (wider for rho > 0: booms and busts co-move).
      * ROSTER-REALIZATION / LOGJAM cap: per draw, prospects are grouped by roster
        slot; the top `position_slots[group]` keep full value and the blocked
        excess realizes at `trade_recovery` (it must be traded, not played).

    Continuity: rho = 0 AND cap disabled -> the rollup mean reduces EXACTLY to the
    sum of individual mean SVs (the copula is a permutation; no cap touches it)."""
    import numpy as np
    items = list(prospects or [])
    if not items:
        return None
    pcfg = _config().get("portfolio", {})
    dcfg = _config().get("distribution", {})
    n = int(draws if draws is not None else dcfg.get("monte_carlo_draws", 20000))
    rho = float(correlation if correlation is not None else pcfg.get("outcome_correlation", 0.0))
    rho = min(max(rho, 0.0), 0.999)
    cap = bool(pcfg.get("roster_realization_cap", False)) if apply_cap is None else bool(apply_cap)
    thr = float(threshold_mm if threshold_mm is not None else dcfg.get("sv_threshold_mm", 50.0))
    lam = float(risk_lambda if risk_lambda is not None else dcfg.get("risk_aversion_lambda", 0.0))
    base_seed = int(seed if seed is not None else dcfg.get("seed", 1234567))

    # Per-prospect marginal draws (sorted ascending) + exact mean; the copula below
    # reorders each prospect's OWN draws, preserving its marginal exactly.
    sorted_draws, groups_idx, som = [], {}, 0.0
    valid = 0
    for pr in items:
        fv_sd, _, _ = _resolve_fv_sd(pr.get("fv_dispersion"), pr.get("source_fvs"), pr.get("n_sources"))
        d, _, mean_usd = _sv_draws_mm(pr.get("fv"), bool(pr.get("is_pitcher")), pr.get("position"),
                                      n, seed=base_seed, age=pr.get("age"),
                                      eta_years=pr.get("eta_years"), fv_sd=fv_sd)
        if d is None:
            continue
        sorted_draws.append(np.sort(np.asarray(d, dtype=float)))
        groups_idx.setdefault(_roster_group(pr.get("position"), bool(pr.get("is_pitcher"))), []).append(valid)
        som += mean_usd / 1e6
        valid += 1
    if valid == 0:
        return None

    rng = np.random.RandomState(base_seed % (2 ** 32))
    g_factor = rng.standard_normal(n)
    sq_rho, sq_1mrho = math.sqrt(rho), math.sqrt(1.0 - rho)
    mat = np.empty((valid, n), dtype=float)
    for i in range(valid):
        z = sq_rho * g_factor + sq_1mrho * rng.standard_normal(n)
        ranks = np.argsort(np.argsort(z))               # 0..n-1; high z -> high SV
        mat[i] = sorted_draws[i][ranks]                 # marginal preserved, co-moved by z
    # Logjam realization cap, per draw, per roster group.
    if cap:
        system = np.zeros(n)
        default_slots = int(pcfg.get("default_slots", 2))
        slot_map = pcfg.get("position_slots", {}) or {}
        # A blocked prospect realizes a FRACTION of its SV via trade -- clamp to
        # [0,1] so a misconfigured value can never turn the logjam into a premium.
        t = min(1.0, max(0.0, float(pcfg.get("trade_recovery", 0.5))))
        for g, idxs in groups_idx.items():
            block = mat[idxs, :]
            s = int(slot_map.get(g, default_slots))
            if len(idxs) <= s:
                system += block.sum(axis=0)
            else:
                desc = -np.sort(-block, axis=0)          # descending per draw (column)
                system += desc[:s, :].sum(axis=0) + t * desc[s:, :].sum(axis=0)
    else:
        system = mat.sum(axis=0)

    mean_mm = float(system.mean())
    out = _dist_output(system, 0.0, mean_mm, threshold_mm=thr, risk_lambda=lam,
                       pct_list=(percentiles if percentiles is not None else dcfg.get("percentiles")))
    out.pop("p_bust", None)                              # not meaningful for a multi-prospect aggregate
    out["sum_of_means"] = round(som, 2)
    # Floor at a clean 0.0: with trade_recovery in [0,1] the capped mean can never
    # exceed the sum of means, so the only sub-zero value is float-summation noise
    # in the exact-continuity case (which would otherwise serialize as -0.0).
    disc = round(1.0 - mean_mm / som, 4) if som > 0 else 0.0
    out["realization_discount"] = disc if disc > 0.0 else 0.0
    out["n_prospects"] = valid
    out["correlation"] = round(rho, 4)
    out["cap_applied"] = cap
    return out


