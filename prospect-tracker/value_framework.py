# FV -> 6-year AVERAGE annual WAR anchor (FanGraphs primer; NOT peak)
# =============================================================================
# Whether the recalibrated realized anchor is SERVED. Set from the verdict in
# docs/PROSPECT_ANCHOR_GATE.md, never from the size of the correction, and a flip
# is the owner's call even on a PASS of the lever's out-of-fold check.
# False: fv_to_6yr_avg_war reads empirical_anchors.anchors, reproducing today's
# payload byte for byte. True: it reads empirical_anchors_v2.anchors, whichever
# form (table, or the scaled table of the one-parameter twin, section 11.3) that
# key records. ONE read site. war_anchor_scale is never the vehicle.
# Flipping it moves every priced prospect number (section 13.1) and no grade, no
# rank, no veteran projection, no betting number and no arbitration award.
# With it, in ONE commit: bump calibration.version, refit and re-stamp the dollar
# map, repoint --emit-snapshots at fv_to_6yr_avg_war() over the knot set so the
# glossary's table is the served anchor (12.2), re-emit data/value_framework.{json,js},
# re-capture prospx_current.yaml, move the pins, and re-run every export that
# stamps calibration_version().
SERVE_PROSPECT_ANCHOR_V2 = False     # env override EEPHUS_PROSPECT_ANCHOR_V2, read at call time


def fv_to_6yr_avg_war(fv: float | None) -> float | None:
    """Monotone (piecewise-linear) interpolation of the config anchor mapping FV
    to the six-year AVERAGE annual WAR. Clamps outside the anchor range."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    # Prefer the EMPIRICAL anchors re-derived from resolved cohorts (continuous
    # calibration, written to the fit file by --fit); fall back to the config seed.
    cal = _config().get("anchor_calibration", {})
    fitted_anchors = None
    if cal.get("use_empirical"):
        fitted = _fitted()
        # SERVE_PROSPECT_ANCHOR_V2: the ONE read site (docs/PROSPECT_ANCHOR_GATE.md
        # 12.1), read at call time. While the key is absent the flag moves nothing.
        env = os.environ.get("EEPHUS_PROSPECT_ANCHOR_V2")
        v2_on = (SERVE_PROSPECT_ANCHOR_V2 if env is None
                 else env.strip().lower() in ("1", "true", "on", "yes"))
        if v2_on:
            fitted_anchors = (fitted.get("empirical_anchors_v2") or {}).get("anchors")
        if not fitted_anchors:
            fitted_anchors = (fitted.get("empirical_anchors") or {}).get("anchors")
    anchor = fitted_anchors or _config()["fv_to_6yr_avg_war"]
    pts = sorted((float(k), float(v)) for k, v in anchor.items())
    if f <= pts[0][0]:
        return pts[0][1]
    if f >= pts[-1][0]:
        return pts[-1][1]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= f <= x1:
            t = (f - x0) / (x1 - x0)
            return y0 * (1 - t) + y1 * t
    return pts[-1][1]


def fv_to_prime_war(fv: float | None) -> float | None:
    """PRIME/TALENT anchor: FV -> peak-season annual WAR for a prospect who
    sticks and plays a full prime season (industry-style FV->WAR; a 60 FV ~ a
    3-WAR regular at peak). DISPLAY ONLY -- drives the prospect prime path
    (warPTH) + headline warPeak; never the expected-value/$ path, which stays on
    `fv_to_6yr_avg_war`. Monotone interpolation, clamped; falls back to scaling
    the realized anchor if the prime table is absent."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    table = _config().get("fv_to_prime_war")
    if not table:
        base = fv_to_6yr_avg_war(f)
        return None if base is None else round(base * 1.85, 3)   # rough talent/realized ratio
    pts = sorted((float(k), float(v)) for k, v in table.items())
    if f <= pts[0][0]:
        return pts[0][1]
    if f >= pts[-1][0]:
        return pts[-1][1]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= f <= x1:
            t = (f - x0) / (x1 - x0)
            return y0 * (1 - t) + y1 * t
    return pts[-1][1]


# =============================================================================
# P(bucket | FV) -- the continuous, smooth, monotone mixture weights
# =============================================================================
def _logistic(z: float) -> float:
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    ez = math.exp(z)
    return ez / (1.0 + ez)


def _normalize_clip(probs: list[float]) -> list[float]:
    clipped = [max(0.0, p) for p in probs]
    s = sum(clipped)
    if s <= 0:
        # Degenerate -- fall back to all-bust.
        out = [0.0] * _N_BUCKETS
        out[0] = 1.0
        return out
    return [p / s for p in clipped]


def _p_bucket_proportional_odds(fv: float, cutpoints: list[float], slope: float) -> list[float]:
    """Ordered logit: P(Y<=j) = logistic(cut_j - slope*fv), j=0..K-2."""
    cum_le = [_logistic(c - slope * fv) for c in cutpoints]  # length K-1, ascending in j
    probs = [cum_le[0]]
    for j in range(1, len(cum_le)):
        probs.append(cum_le[j] - cum_le[j - 1])
    probs.append(1.0 - cum_le[-1])
    return _normalize_clip(probs)


def _p_bucket_per_threshold(fv: float, thresholds: list[dict]) -> list[float]:
    """Per-threshold cumulative logits P(Y>j) = logistic(a_j + b_j*fv), with an
    isotonic (non-increasing in j) monotonicity correction, then differenced."""
    cg = [_logistic(t["intercept"] + t["slope"] * fv) for t in thresholds]  # P(Y>j)
    # Enforce non-increasing cumulative survival across thresholds.
    for j in range(1, len(cg)):
        if cg[j] > cg[j - 1]:
            cg[j] = cg[j - 1]
    probs = [1.0 - cg[0]]
    for j in range(1, len(cg)):
        probs.append(cg[j - 1] - cg[j])
    probs.append(cg[-1])
    return _normalize_clip(probs)


@lru_cache(maxsize=4)
def _pchip_bucket_interpolators(role: str):
    """Fallback when no fit is present: monotone-cubic (PCHIP) interpolation of
    each bucket probability across the anchor FVs, renormalized at eval time."""
    from scipy.interpolate import PchipInterpolator  # lazy

    cfg = _config()
    table = cfg[f"p_bucket_given_fv_{role}"]
    axes = cfg["fit"]["role_axes"]
    rows = sorted(((float(axes[k]), v) for k, v in table.items()), key=lambda r: r[0])
    xs = [r[0] for r in rows]
    interps = {}
    for b in _BUCKETS:
        ys = [float(r[1][b]) for r in rows]
        interps[b] = PchipInterpolator(xs, ys, extrapolate=True)
    return interps


def _p_bucket_pchip(fv: float, role: str) -> list[float]:
    interps = _pchip_bucket_interpolators(role)
    return _normalize_clip([float(interps[b](fv)) for b in _BUCKETS])


def p_bucket_given_fv(fv: float, is_pitcher: bool) -> list[float] | None:
    """Smooth, monotone P(bucket|FV) as a 5-vector [bust,bench,regular,good,star].
    Uses the fitted ordered-logit (or per-threshold-isotonic) parameters; falls
    back to PCHIP interpolation of the training rows if no fit is committed.
    Returns None for missing / unparseable / non-finite FV (matching the dollar
    APIs' degrade-to-None contract)."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    role = _role_key(is_pitcher)
    fit = _fitted()
    method = (fit.get("method") or {}).get(role)
    if method == "proportional_odds":
        po = fit["proportional_odds"][role]
        return _p_bucket_proportional_odds(f, po["cutpoints"], po["slope"])
    if method == "per_threshold_isotonic":
        return _p_bucket_per_threshold(f, fit["per_threshold"][role])
    return _p_bucket_pchip(f, role)


def expected_six_year_avg_war(fv: float, is_pitcher: bool) -> float | None:
    """P(bucket|FV)-weighted six-year average annual WAR (the quantity the
    reconciliation calibration pins to fv_to_6yr_avg_war). None on bad FV.
    This is the BUST-INCLUSIVE expectation (used by the surplus model)."""
    probs = p_bucket_given_fv(fv, is_pitcher)
    if probs is None:
        return None
    role = _role_key(is_pitcher)
    mids = _calibrated_midpoints(role)
    return sum(p * m for p, m in zip(probs, mids)) * _war_scale_for(fv, role)


def survivor_expected_war(fv: float, is_pitcher: bool) -> float | None:
    """SURVIVOR expected WAR/yr = E[WAR | the prospect did NOT bust], derived from
    the SAME calibrated model as the surplus (bucket probabilities x FV-dependent
    bucket midpoints, conditioned on the non-bust buckets). This is the single
    source of truth for the FV->WAR expectation that WAG measures graduates against
    (graduates are, by definition, survivors), so WAG and the surplus model can no
    longer drift onto inconsistent FV->WAR assumptions. None on bad FV / all-bust."""
    probs = p_bucket_given_fv(fv, is_pitcher)
    if probs is None:
        return None
    role = _role_key(is_pitcher)
    scale = _war_scale_for(fv, role)
    mids = [m * scale for m in _calibrated_midpoints(role)]
    p_survive = sum(probs[1:])                      # non-bust mass
    if p_survive <= 1e-9:
        return None
    return sum(probs[b] * mids[b] for b in range(1, len(mids))) / p_survive


# =============================================================================
# Hierarchical-Bayes credible intervals on P(bucket|FV) and SV (Prompt G)
# =============================================================================
def _bayes_block() -> dict | None:
    return _fitted().get("bayes")


@lru_cache(maxsize=4)
def _bayes_theta_draws(n: int, seed: int):
    """Draws of the joint parameter vector from the Laplace posterior MVN(MAP,
    cov). Cached (deterministic given n, seed). None if no bayes posterior."""
    import numpy as np
    b = _bayes_block()
    if not b:
        return None
    rng = np.random.RandomState(int(seed) % (2 ** 32))
    return rng.multivariate_normal(np.asarray(b["theta_map"], dtype=float),
                                   np.asarray(b["cov"], dtype=float), size=int(n))


def p_bucket_posterior_draws(fv, is_pitcher, *, draws=None, seed=None):
    """Posterior draws (n x 5) of P(bucket|FV) from the hierarchical Laplace
    posterior, with extra logit widening beyond the [45,60] data range (honest
    extrapolation uncertainty). None when no bayes posterior is committed."""
    import numpy as np
    b = _bayes_block()
    if not b:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    bcfg = _config()["fit"].get("bayes", {})
    n = int(draws if draws is not None else bcfg.get("posterior_draws", 4000))
    seed = int(seed if seed is not None else bcfg.get("seed", 20260531))
    theta = _bayes_theta_draws(n, seed)
    if theta is None:
        return None
    lo, hi = b["data_fv_range"]
    extra = float(bcfg.get("extrapolation_extra_sd_per_fv", 0.0)) * max(0.0, f - hi, lo - f)
    shift = (np.random.RandomState((seed + 101) % (2 ** 32)).normal(0.0, extra, size=len(theta))
             if extra > 0 else None)
    out = np.empty((len(theta), _N_BUCKETS))
    for i, th in enumerate(theta):
        s, cut = _theta_role_params(th, is_pitcher)
        if shift is not None:                       # shared logit shift widens P in extrapolation
            cut = [c + shift[i] for c in cut]
        out[i] = _p_bucket_proportional_odds(f, cut, s)
    return out


def p_bucket_credible(fv, is_pitcher, *, cred=None, draws=None, seed=None) -> dict | None:
    """Posterior median + central credible interval for each bucket probability.
    Degenerates to a zero-width interval at the point estimate if no bayes fit."""
    import numpy as np
    d = p_bucket_posterior_draws(fv, is_pitcher, draws=draws, seed=seed)
    if d is None:
        p = p_bucket_given_fv(fv, is_pitcher)
        if p is None:
            return None
        return {b: {"median": round(p[i], 4), "lo": round(p[i], 4), "hi": round(p[i], 4)}
                for i, b in enumerate(_BUCKETS)}
    cred = float(cred if cred is not None else _config()["fit"]["bayes"].get("credible_mass", 0.90))
    loq, hiq = (1 - cred) / 2 * 100, (1 - (1 - cred) / 2) * 100
    return {b: {"median": round(float(np.percentile(d[:, i], 50)), 4),
                "lo": round(float(np.percentile(d[:, i], loq)), 4),
                "hi": round(float(np.percentile(d[:, i], hiq)), 4)}
            for i, b in enumerate(_BUCKETS)}


def sv_credible_interval(fv, is_pitcher, position=None, *, cred=None, age=None,
                         eta_years=None, draws=None, seed=None, eta_origin=None) -> dict | None:
    """EPISTEMIC credible interval on the EXPECTED surplus value ($M): the
    hierarchical P(bucket|FV) posterior propagated through the bucket SVs. This
    is the parameter/model uncertainty -- distinct from (and combinable with) the
    within-model OUTCOME spread reported by sv_distribution. Widens for thin
    cells and in extrapolation. (For FV below the Edwards bridge, point_mm uses
    the anchor while the interval reflects the bucket-pipeline spread.)"""
    import numpy as np
    point = surplus_value_mm(fv, is_pitcher, position, age=age, eta_years=eta_years,
                             eta_origin=eta_origin)
    cred = float(cred if cred is not None else _config()["fit"]["bayes"].get("credible_mass", 0.90))
    try:
        f = float(fv)
    except (TypeError, ValueError):
        f = None
    degenerate = {"point_mm": point, "median_mm": point, "lo_mm": point, "hi_mm": point,
                  "cred": cred, "regime": "point"}
    if point is None or f is None or not math.isfinite(f) or _bayes_block() is None:
        return degenerate
    a = _config()["lowtier_anchor"]
    cutover, bridge_to = float(a["cutover_fv"]), float(a["bridge_to_fv"])
    role = _role_key(is_pitcher)
    debut_age, eta_eff = _resolve_timing(age, eta_years)
    da, ee = _round_timing(debut_age, eta_eff)
    pm = position_multiplier(position)
    if f <= cutover:
        # Pure Edwards anchor -- a fixed dollar figure with NO parameter
        # uncertainty, so the epistemic interval degenerates at the point.
        return {**degenerate, "regime": "anchor"}
    # Mirror expected_surplus_usd's regime: the pipeline component is evaluated at
    # FV for the pipeline region and at bridge_to for the (cutover, bridge) bridge,
    # so the interval brackets the SAME quantity as point_mm.
    bucket_sv = _effective_bucket_sv(is_pitcher, position, da, ee,
                                     _war_scale_for(f if f >= bridge_to else bridge_to, _role_key(is_pitcher)),
                                     eta_origin)
    draw_fv = f if f >= bridge_to else bridge_to
    d = p_bucket_posterior_draws(draw_fv, is_pitcher, draws=draws, seed=seed)
    if d is None:
        return degenerate
    pipe = np.array([sum(pr * s for pr, s in zip(prob, bucket_sv)) for prob in d])  # USD, no pm
    if f >= bridge_to:
        base = pipe
        regime = "pipeline"
    else:
        anchor = _lowtier_anchor_usd(cutover, role, ee, eta_origin)
        t = (f - cutover) / (bridge_to - cutover)
        base = anchor * (1 - t) + pipe * t
        regime = "bridge"
    vals = np.array([apply_calibration(max(0.0, v * pm) / 1e6, f, is_pitcher) for v in base])
    loq, hiq = (1 - cred) / 2 * 100, (1 - (1 - cred) / 2) * 100
    return {"point_mm": point,
            "median_mm": round(float(np.percentile(vals, 50)), 1),
            "lo_mm": round(float(np.percentile(vals, loq)), 1),
            "hi_mm": round(float(np.percentile(vals, hiq)), 1),
            "cred": cred, "regime": regime}


