def _build_training_rows(role: str) -> tuple[list[float], list[int]]:
    """Reconstruct integer counts from the published % table and expand to one
    (fv, bucket_ordinal) row per player. Excludes rows with n <= exclude_n_le."""
    cfg = _config()
    table = cfg[f"p_bucket_given_fv_{role}"]
    axes = cfg["fit"]["role_axes"]
    excl = int(cfg["fit"]["exclude_n_le"])
    fvs: list[float] = []
    ys: list[int] = []
    for key, row in table.items():
        n = int(row["n"])
        if n <= excl:
            continue
        fv = float(axes[key])
        for bi, b in enumerate(_BUCKETS):
            count = int(round(float(row[b]) * n))
            fvs.extend([fv] * count)
            ys.extend([bi] * count)
    return fvs, ys


def _fit_proportional_odds(fvs: list[float], ys: list[int]) -> tuple[list[float], float]:
    """Fit a proportional-odds ordered logit; return (cutpoints[K-1], slope)."""
    import numpy as np
    from statsmodels.miscmodels.ordinal_model import OrderedModel

    x = np.asarray(fvs, dtype=float).reshape(-1, 1)
    y = np.asarray(ys, dtype=int)
    model = OrderedModel(y, x, distr="logit")
    res = model.fit(method="bfgs", disp=False, maxiter=2000)
    k_exog = x.shape[1]
    beta = float(res.params[k_exog - 1])  # single FV slope
    raw_thresh = res.params[k_exog:]
    thresh = model.transform_threshold_params(raw_thresh)  # [-inf, c0..c_{K-2}, +inf]
    cutpoints = [float(c) for c in thresh[1:-1]]
    # Verify our closed-form reproduces statsmodels' predicted probabilities.
    pred = res.model.predict(res.params, exog=x[:5] if len(x) >= 5 else x)
    for i in range(min(5, len(x))):
        mine = _p_bucket_proportional_odds(float(x[i, 0]), cutpoints, beta)
        if not np.allclose(mine, pred[i], atol=1e-5):
            raise RuntimeError(
                f"proportional-odds reproduction mismatch at fv={x[i,0]}: "
                f"mine={mine} sm={list(pred[i])}"
            )
    return cutpoints, beta


def _fit_per_threshold(fvs: list[float], ys: list[int]) -> list[dict]:
    """Fit K-1 binary cumulative logits P(Y>j) = logistic(a_j + b_j*fv)."""
    import numpy as np
    from sklearn.linear_model import LogisticRegression

    x = np.asarray(fvs, dtype=float).reshape(-1, 1)
    y = np.asarray(ys, dtype=int)
    intercept_mag = float(_config()["fit"].get("degenerate_logit_intercept", 50.0))
    out = []
    for j in range(_N_BUCKETS - 1):
        target = (y > j).astype(int)
        if target.min() == target.max():
            # Degenerate threshold (all same) -- use a flat near-0/1 logit.
            out.append({"intercept": intercept_mag if target.max() == 1 else -intercept_mag, "slope": 0.0})
            continue
        lr = LogisticRegression(C=1e6, solver="lbfgs", max_iter=5000)
        lr.fit(x, target)
        out.append({"intercept": float(lr.intercept_[0]), "slope": float(lr.coef_[0][0])})
    return out


def _parallel_lines_diagnostic(per_threshold: list[dict], tol: float) -> dict:
    slopes = [t["slope"] for t in per_threshold]
    spread = (max(slopes) - min(slopes)) if slopes else 0.0
    return {"threshold_slopes": slopes, "spread": spread, "passed": spread <= tol}


def _calibrate_midpoints_for_role(role: str, po_cut: list[float], po_slope: float,
                                  per_thr: list[dict], method: str) -> tuple[list[float], dict]:
    """Solve for FV-independent bucket midpoints so the P(bucket|FV)-weighted
    six-year-average annual WAR reconciles to fv_to_6yr_avg_war at reconcile_fvs.
    bust pinned at 0; monotone non-decreasing; small ridge toward band priors
    handles columns with ~no probability mass (e.g. pitcher star)."""
    import numpy as np
    from scipy.optimize import minimize

    cfg = _config()
    fc = cfg["fit"]
    fvs = [float(x) for x in cfg["reconcile_fvs"]]

    def probs_at(fv: float) -> list[float]:
        if method == "proportional_odds":
            return _p_bucket_proportional_odds(fv, po_cut, po_slope)
        return _p_bucket_per_threshold(fv, per_thr)

    P = np.array([probs_at(fv) for fv in fvs])      # (k, 5)
    A = P[:, 1:]                                     # drop bust (midpoint 0); (k,4)
    targets = np.array([fv_to_6yr_avg_war(fv) for fv in fvs])
    # Weight the user-named reconciliation targets (50/55/60) heavily.
    w_named = float(fc.get("reconcile_weight_named", 3.0))
    named = {float(x) for x in fc.get("reconcile_weight_fvs", [50, 55, 60])}
    w = np.array([w_named if fv in named else 1.0 for fv in fvs])
    priors = np.array([float(x) for x in fc["midpoint_priors"]])  # bench..star
    ridge = float(fc["midpoint_ridge"])
    min_gap = float(fc["midpoint_min_gap"])

    def obj(m):
        resid = A @ m - targets
        return float(np.sum(w * resid ** 2) + ridge * np.sum((m - priors) ** 2))

    # Keep buckets strictly ordered AND distinct (>= min_gap apart) so the
    # solver can't collapse bench/regular/good onto one another.
    cons = [
        {"type": "ineq", "fun": (lambda m, i=i: m[i + 1] - m[i] - min_gap)}
        for i in range(3)
    ]
    cons.append({"type": "ineq", "fun": lambda m: m[0] - min_gap})  # bench >= bust(0)+gap
    bounds = [(0.0, 12.0)] * 4
    sol = minimize(obj, priors.copy(), method="SLSQP", bounds=bounds,
                   constraints=cons, options={"maxiter": 1000, "ftol": 1e-12})
    m = [0.0] + [float(v) for v in sol.x]
    # Reconciliation residuals at the named + reconcile FVs.
    recon = {}
    for fv in sorted(set(fvs) | named):
        pr = probs_at(fv)
        wavg = sum(p * mm for p, mm in zip(pr, m))
        recon[str(fv)] = {"target": fv_to_6yr_avg_war(fv), "weighted_avg_war": round(wavg, 4),
                          "resid": round(wavg - fv_to_6yr_avg_war(fv), 4)}
    return m, recon


