def _sv_curve(is_pitcher: bool, position: str | None = None) -> list[float]:
    """Dense FV->SV($M) curve at a given position tag. position=None -> the
    GENERIC role-mixed pitcher (or hitter); 'SP'/'RP' tags select the starter /
    capped-reliever role-outcome blends."""
    snap = _config()["snapshot"]
    lo = float(snap["sv_curve_fv_min"])
    hi = float(snap["sv_curve_fv_max"])
    step = float(snap["sv_curve_step"])
    n = int(round((hi - lo) / step)) + 1
    out = []
    for i in range(n):
        fv = lo + i * step
        usd = expected_surplus_usd(fv, is_pitcher, position)
        out.append(round((usd or 0.0) / 1e6, 4))
    return out


