"""Single source of truth for FV -> surplus-value ($) conversions.

v2.0 -- DISCRETE CAREER-PATH MIXTURE MODEL (replaces the v1 point-estimate model
audited in docs/sv-audit.md).

Why the rewrite (the bug behind the old model):
  The v1 model collapsed a distribution into a point estimate BEFORE running it
  through nonlinear functions, in two places at once -- a single `p_success`
  multiplier across career outcomes, and a `ramp` average of WAR across years --
  then converted once. For nonlinear f (tiered $/WAR, arbitration),
  E[f(X)] != f(E[X]); collapsing first misprices the distribution. The gap is
  largest -- and positive -- in the mid-FV band (~45-52), where a prospect's
  outcomes straddle the convex $/WAR tiers (bust -> $0, regular in the 1-2 tier,
  star in 2+) so valuing each outcome on its own WAR beats collapsing to one
  averaged WAR; at high FV, where all plausible outcomes already sit in the flat
  2+ tier, the convexity no longer binds. (See point_estimate_surplus_usd for the
  verified, FV-dependent sign of the gap -- it is NOT a uniform star premium.)

The fix -- transform at the finest granularity, aggregate LAST:
  1. A prospect's career is modeled as a mixture over 5 ordinal OUTCOME BUCKETS
     (bust < bench < regular < good < star), each a per-season WAR talent band
     (Clemens 2025).
  2. Continuous FV sets only the MIXTURE WEIGHTS P(bucket|FV) -- a smooth,
     monotone ordered-logistic curve fit separately for hitters and pitchers.
     FV changes the *probability* of each outcome, never the *value* of an
     outcome (a 57-FV star and a 55-FV star have the same career), so the
     per-bucket dollar surplus is FV-independent and expected surplus is a clean
     dot product `sum_b P(b|FV) * SV_b` -- automatically continuous & monotone.
  3. Each bucket gets a per-season WAR TRAJECTORY (level calibrated so the
     P(bucket|FV)-weighted six-year-average annual WAR reconciles to the
     FanGraphs primer's FV -> avg-annual-WAR anchor -- NOT peak). The `ramp` is
     retired.
  4. Each SEASON is valued on its OWN WAR through the tiered $/WAR schedule, then
     discounted to present value. We never average WAR first.
  5. Salary is performance-adaptive: pre-arb ~ league min; arb years scale as an
     escalating fraction of that season's market value (a star's arb >> a
     bench player's). Super-Two is a config option.
  6. bucket_SV = discounted sum over control years of (season value - season
     salary), floored at $0 where a bust would be released/non-tendered. Expected
     SV = sum_b P(b|FV) * bucket_SV.
  7. FV <= 40 uses a direct Edwards dollar anchor (bridged to the fitted region).
  8. No positional $ multiplier: WAR already contains a positional adjustment, so
     applying one double-counts (see audit FLAG 7). The only position effect is a
     WAR-INPUT haircut for relievers (the Clemens bands are 200-IP-normalized).

ALL tunable numbers live in value_framework_config.yaml; ALL fitted parameters
(ordered-logit cutpoints + slopes, calibrated bucket midpoints, diagnostics) live
in data/value_framework_fitted.json, regenerated by:

    python value_framework.py --fit            # refit from the config tables
    python value_framework.py --emit-snapshots # rewrite data/value_framework.{json,js}

This module contains NO hardcoded valuation constants. Runtime evaluation is pure
arithmetic over the committed config + fitted files (no statsmodels/scipy needed
unless you --fit or hit the PCHIP fallback).

Downstream consumers (storage.py surplus leaves, mlb_trade_lookup.py contract
surplus, index.html via the emitted snapshot) read FROM this module / its snapshot.
"""

