@lru_cache(maxsize=4)
def _calibrated_midpoints(role: str) -> tuple[float, ...]:
    """Per-bucket six-year-average WAR levels. Read from the fitted file if
    present; else fall back to the config seed midpoints. bust is pinned at 0."""
    fit = _fitted()
    mids = (fit.get("bucket_midpoints") or {}).get(role)
    if mids and len(mids) == _N_BUCKETS:
        return tuple(float(x) for x in mids)
    cfg = _config()["buckets"]
    return tuple(float(cfg[b]["midpoint_war"]) for b in _BUCKETS)


# =============================================================================
# Aging curve -- relative WAR vs age, peak normalized to 1.0
# =============================================================================
def _aging_multiplier(age: float, peak_age: float, aging_cfg: dict) -> float:
    """Empirical relative-WAR multiplier at `age` (peak = 1.0): an asymmetric
    tent that climbs to the peak and declines (steeper) past it, floored."""
    climb = float(aging_cfg.get("climb_per_year_before_peak", 0.04))
    decline = float(aging_cfg.get("decline_per_year_after_peak", 0.07))
    floor = float(aging_cfg.get("min_multiplier", 0.25))
    if age <= peak_age:
        m = 1.0 - climb * (peak_age - age)
    else:
        m = 1.0 - decline * (age - peak_age)
    return max(floor, m)


# =============================================================================
# Per-bucket dollar surplus (FV-INDEPENDENT in WAR; timing reshapes/discounts $)
# =============================================================================
def _trajectory_shape(role: str, debut_age: float | None, bname: str | None = None) -> list[float]:
    """Per-season SHAPE (mean 1.0) across the control window. When aging is on
    and the debut age is known, the shape comes from the aging curve evaluated
    at the player's age each control season, renormalized to mean 1.0 (so the
    six-year AVERAGE still equals the level -- aging only redistributes WAR
    across the window). Otherwise the fixed bucket_trajectory_shape is used."""
    cfg = _config()
    n_years = int(cfg["service_time"]["control_years"])
    aging = cfg.get("aging", {})
    if aging.get("enabled", True) and debut_age is not None:
        peak = float(aging["pitcher_peak_age" if role == "pitcher" else "hitter_peak_age"])
        raw = [_aging_multiplier(float(debut_age) + k, peak, aging) for k in range(n_years)]
        mean_raw = (sum(raw) / n_years) or 1.0
        return [r / mean_raw for r in raw]
    shapes = cfg["bucket_trajectory_shape"]
    shape = shapes.get(bname, shapes["default"]) if bname else shapes["default"]
    if len(shape) != n_years:
        shape = (list(shape) * n_years)[:n_years]
        mean = sum(shape) / n_years or 1.0
        shape = [s / mean for s in shape]
    return list(shape)


def _reliever_level(midpoint_war: float) -> float:
    """Normalize a 200-IP-band WAR to a full BULLPEN season and cap it:
    min(ceiling, band_WAR * reliever_full_season_ip / pitcher_band_ip). E.g. a
    3.6-WAR/200-IP band -> 3.6*65/200 = 1.17 ~ 1.2 WAR. Falls back to the legacy
    flat relief_war_haircut if the IP keys are absent."""
    mw = float(midpoint_war)
    # Guard the WAR input: a non-finite or negative band WAR is floored at 0 so it
    # can never slip past min(ceil, .) as the ceiling (min(ceil, nan) == ceil in
    # CPython) or pass through as a negative full-season WAR. Unreachable via the
    # fitted midpoints / floored continuous rate today, but kept robust.
    if not math.isfinite(mw) or mw <= 0:
        return 0.0
    pos = _config()["position"]
    rip = pos.get("reliever_full_season_ip")
    band = float(pos.get("pitcher_band_ip", 200) or 200)
    if rip is None:
        return mw * float(pos.get("relief_war_haircut", 0.5))
    ceil = float(pos.get("reliever_war_ceiling", float("inf")))
    return min(ceil, mw * float(rip) / band)


def _bucket_season_wars(role: str, bucket_idx: int, reliever: bool,
                        debut_age: float | None = None) -> list[float]:
    """Per-season WAR for a bucket across the control window. SP level = the
    calibrated 200-IP-band midpoint; RELIEVER level = the bullpen-normalized,
    ceiling-capped value (the role-outcome layer values relief outcomes at their
    real, far lower, full-season WAR). Times the aging/fixed shape."""
    shape = _trajectory_shape(role, debut_age, _BUCKETS[bucket_idx])
    mid = _calibrated_midpoints(role)[bucket_idx]
    level = _reliever_level(mid) if reliever else mid
    return [level * float(s) for s in shape]


def _aged_trajectory(role: str, level: float, debut_age: float | None) -> list[float]:
    """Per-season WAR for an arbitrary talent LEVEL (e.g. a continuous regressed
    true-talent rate), shaped by the same aging curve. No relief haircut -- a
    debuted player's observed/regressed rate is already at their real role."""
    return [level * float(s) for s in _trajectory_shape(role, debut_age, None)]


def _service_path_surplus_usd(season_wars: list[float], super_two: bool,
                              eta_years: float = 0.0) -> float:
    """Discounted sum over control years of (season market value - season salary),
    with performance-adaptive arbitration. Standard path = pre_arb_years league-min
    years then escalating-fraction arb years; super-two converts one pre-arb year
    into an extra (cheaper, earlier) arb year.

    Timing: control season k lands `eta_years + k` calendar years out. Each
    season's surplus is grown by $/WAR inflation and discounted at discount_rate;
    the two net to ((1+inflation)/(1+discount_rate))^(eta_years+k). With
    inflation = 0 and eta_years = 0 this is exactly the prior 1/(1+r)^k discount."""
    cfg = _config()
    st = cfg["service_time"]
    league_min = float(st["league_min_usd"])
    fracs = list(st["arb_model"]["fractions_of_fa_value"])
    if super_two:
        pre_arb = int(st["pre_arb_years"]) - 1
        arb_fracs = [float(st["arb_model"]["super_two_first_fraction"])] + fracs
    else:
        pre_arb = int(st["pre_arb_years"])
        arb_fracs = fracs
    infl = float(cfg.get("dollars_per_war_inflation", 0.0))
    r = float(cfg["discount_rate"])
    net = (1.0 + infl) / (1.0 + r)
    total = 0.0
    for t, war in enumerate(season_wars):
        market = tiered_war_value_usd(war)
        if t < pre_arb:
            salary = league_min
        else:
            i = t - pre_arb
            frac = arb_fracs[i] if i < len(arb_fracs) else arb_fracs[-1]
            salary = frac * market
        total += (market - salary) * (net ** (float(eta_years) + t))
    return total


@lru_cache(maxsize=512)
def _bucket_sv_usd(role: str, reliever: bool,
                   debut_age: float | None = None, eta_years: float = 0.0) -> tuple[float, ...]:
    """The 5 per-bucket surplus values ($USD), given timing. WAR levels are
    FV-independent; `debut_age` reshapes each bucket's trajectory along the aging
    curve and `eta_years` discounts the control window from projected debut.
    Blends the standard and super-two service paths and floors each bucket at its
    config floor (bust -> $0). Cached on rounded timing keys."""
    cfg = _config()
    st = cfg["service_time"]
    s2 = st["super_two"]
    f = float(s2["fraction"]) if s2.get("enabled") else 0.0
    floors = cfg["buckets"]
    out = []
    for b in range(_N_BUCKETS):
        wars = _bucket_season_wars(role, b, reliever, debut_age)
        sv_std = _service_path_surplus_usd(wars, False, eta_years)
        sv_s2 = _service_path_surplus_usd(wars, True, eta_years) if f > 0 else sv_std
        sv = (1.0 - f) * sv_std + f * sv_s2
        floor = float(floors[_BUCKETS[b]].get("surplus_floor_usd", 0))
        out.append(max(floor, sv))
    return tuple(out)


def _round_timing(debut_age: float | None, eta_years: float) -> tuple[float | None, float]:
    """Round timing args to bound the _bucket_sv_usd cache (0.5-yr age, 0.25-yr ETA)."""
    da = round(float(debut_age) * 2) / 2 if debut_age is not None else None
    ee = round(float(eta_years) * 4) / 4
    return da, ee


# =============================================================================
# Pitcher role-outcome layer (Prompt J): P(reliever | bucket) blend
# =============================================================================
def _pitcher_rp_by_bucket(position: str | None) -> list[float]:
    """P(reliever | bucket) (5-vector; bust index = 0). A GENERIC pitcher uses
    the config base; an RP-tagged prospect -> 1.0 on every non-bust bucket; an
    SP-tagged prospect scales the base down (relieves less). Failed starters
    relieve more at LOWER quality; elite arms stick as SP."""
    cfg = _config()
    mix = cfg.get("pitcher_role_mix", {})
    base = mix.get("p_rp_by_bucket", {})
    primary = _pos_primary(position)
    out = [0.0] * _N_BUCKETS
    if primary in set(cfg["position"]["reliever_positions"]):
        return [0.0] + [1.0] * (_N_BUCKETS - 1)
    mult = float(mix.get("starter_tag_multiplier", 1.0)) if primary == "SP" else 1.0
    for i, b in enumerate(_BUCKETS):
        if b == "bust":
            continue
        out[i] = min(1.0, float(base.get(b, 0.0)) * mult)
    return out


def _effective_bucket_sv(is_pitcher: bool, position: str | None,
                         debut_age: float | None, eta_years: float) -> tuple[float, ...]:
    """Per-bucket surplus ($USD) with the pitcher role-outcome layer applied.
    Hitters: the plain bucket SVs (path unchanged). Pitchers: each bucket blends
    the full-SP value and the bullpen-capped RP value by P(reliever|bucket),
    with an optional injury/attrition haircut on the non-bust buckets."""
    if not is_pitcher:
        return _bucket_sv_usd("hitter", False, debut_age, eta_years)
    sp = _bucket_sv_usd("pitcher", False, debut_age, eta_years)   # full 200-IP-band SP
    rp = _bucket_sv_usd("pitcher", True, debut_age, eta_years)    # bullpen-capped RP
    p_rp = _pitcher_rp_by_bucket(position)
    haz = float(_config().get("pitcher_role_mix", {}).get("injury_hazard", 0.0))
    out = []
    for b in range(_N_BUCKETS):
        v = (1.0 - p_rp[b]) * sp[b] + p_rp[b] * rp[b]
        if b != 0:                                                # attrition on non-bust outcomes
            v *= (1.0 - haz)
        out.append(v)
    return tuple(out)


def pitcher_role_split(fv, is_pitcher: bool, position: str | None = None) -> dict | None:
    """The SP / RP / bust outcome split for a pitcher at FV (reconciles to the
    pitcher base rates: bust = P(bucket=bust|FV); the non-bust mass is divided
    SP vs RP by P(reliever|bucket)). None for hitters / bad FV."""
    if not is_pitcher:
        return None
    probs = p_bucket_given_fv(fv, True)
    if probs is None:
        return None
    p_rp_b = _pitcher_rp_by_bucket(position)
    bust = float(probs[0])
    rp = sum(probs[i] * p_rp_b[i] for i in range(1, _N_BUCKETS))
    sp = sum(probs[i] * (1.0 - p_rp_b[i]) for i in range(1, _N_BUCKETS))
    return {"sp": round(sp, 4), "rp": round(rp, 4), "bust": round(bust, 4)}


def bucket_surplus_usd(is_pitcher: bool, position: str | None = None, *,
                       age: float | None = None, eta_years: float | None = None) -> dict[str, float]:
    """Public view of the per-bucket surplus constants (transparency / snapshot /
    comparison test), with the pitcher role-outcome layer applied."""
    debut_age, eta_eff = _resolve_timing(age, eta_years)
    da, ee = _round_timing(debut_age, eta_eff)
    svs = _effective_bucket_sv(is_pitcher, position, da, ee)
    return {b: svs[i] for i, b in enumerate(_BUCKETS)}


# =============================================================================
# Timing resolution: age + ETA -> (age at projected debut, effective ETA gap)
# =============================================================================
def _resolve_timing(age: float | None, eta_years: float | None) -> tuple[float | None, float]:
    """Resolve raw (current age, years-to-debut) into (debut_age, eta_eff).
    debut_age = age + ETA (None if aging off or age missing -> fixed shape).
    eta_eff is the discounting gap, 0 when discount_from='now' (prior behavior)."""
    cfg = _config()
    discount_from = str(cfg.get("discount_from", "debut")).lower()
    try:
        eta = float(eta_years) if eta_years is not None else float(cfg.get("default_eta_years", 0.0))
    except (TypeError, ValueError):
        eta = float(cfg.get("default_eta_years", 0.0))
    if not math.isfinite(eta) or eta < 0:
        eta = 0.0
    eta_eff = eta if discount_from == "debut" else 0.0
    debut_age = None
    if cfg.get("aging", {}).get("enabled", True) and age is not None:
        try:
            a = float(age)
            if math.isfinite(a):
                debut_age = a + eta
        except (TypeError, ValueError):
            debut_age = None
    return debut_age, eta_eff


# =============================================================================
# Expected surplus  (= sum_b P(b|FV) * bucket_SV)  with FV<=40 dollar anchor
# =============================================================================
def _pipeline_surplus_from_svs(fv: float, is_pitcher: bool, svs) -> float:
    """Mixture pipeline surplus from PRE-COMPUTED per-bucket SVs (the role-mixed
    effective bucket values from _effective_bucket_sv). The bucket SVs are
    FV-independent, so the same vector serves any FV through P(bucket|FV)."""
    probs = p_bucket_given_fv(fv, is_pitcher)
    return sum(p * s for p, s in zip(probs, svs))


def _lowtier_anchor_usd(fv: float, role: str, eta_years: float = 0.0) -> float:
    cfg = _config()
    a = cfg["lowtier_anchor"]
    val = float(a["anchor_usd_40fv_position"])
    if role == "pitcher":
        val *= float(a.get("pitcher_scale", 1.0))
    anchor_fv = float(a["anchor_fv"])
    if fv < anchor_fv:
        val *= math.exp(-float(a["decay_per_point"]) * (anchor_fv - fv))
    # Discount the anchor lump from projected debut, consistent with the pipeline.
    infl = float(cfg.get("dollars_per_war_inflation", 0.0))
    r = float(cfg["discount_rate"])
    val *= ((1.0 + infl) / (1.0 + r)) ** float(eta_years)
    return val


def point_estimate_surplus_usd(fv: float | None, is_pitcher: bool, position: str | None = None,
                               *, age: float | None = None, eta_years: float | None = None) -> float | None:
    """COLLAPSED comparator (NOT the production path). Mirrors the v1 mistake of
    aggregating BEFORE the nonlinear transforms: collapse the outcome mixture to
    a single expected per-season WAR (E[X]) on a flat trajectory, then value that
    one number through the tiered $/WAR + arbitration. Provided only so the
    validation/demonstration can quantify the Jensen gap E[f(X)] - f(E[X]).

    Direction of the gap (verified empirically, not assumed): POSITIVE in the
    mid-FV band (~45-52), where the outcome distribution straddles the convex
    $/WAR tiers (bust at $0, regulars in the 1-2 tier, the rarer star in 2+) so
    valuing each bucket on its own WAR beats collapsing to one averaged WAR. It
    narrows to ~0 and goes slightly NEGATIVE at high FV (>=~52): there the
    calibrated bucket WARs all sit inside the flat 2+ tier (cross-bucket
    convexity no longer binds), and the comparator's flat trajectory skips the
    early-season sub-2.0 tier dips that the real shaped+discounted trajectories
    pay. So the mixture matters MOST in the mid-FV band where prospect valuation
    is hardest -- the benefit is NOT uniform and is NOT a star-bucket premium at
    the top. (To raise value vs the actual v1 model, compare surplus_value_mm to
    the v1 figures in docs/sv-audit.md: e.g. the FV 58.33 SS rises 107.8 -> ~125.)"""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    role = _role_key(is_pitcher)
    reliever = is_pitcher and is_reliever_position(position)
    # E[X]: the probability-weighted six-year average annual WAR, then a flat
    # trajectory at that level (collapse across years too -- the v1 ramp/avg).
    probs = p_bucket_given_fv(f, is_pitcher)
    mids = _calibrated_midpoints(role)
    haircut = float(_config()["position"]["relief_war_haircut"]) if reliever else 1.0
    e_war = sum(p * m for p, m in zip(probs, mids)) * haircut
    n_years = int(_config()["service_time"]["control_years"])
    wars = [e_war] * n_years
    st = _config()["service_time"]
    s2 = st["super_two"]
    fr = float(s2["fraction"]) if s2.get("enabled") else 0.0
    _, eta_eff = _resolve_timing(age, eta_years)
    sv = ((1.0 - fr) * _service_path_surplus_usd(wars, False, eta_eff)
          + fr * _service_path_surplus_usd(wars, True, eta_eff))
    return max(0.0, sv * position_multiplier(position))


def expected_surplus_usd(fv: float | None, is_pitcher: bool, position: str | None = None,
                         *, age: float | None = None, eta_years: float | None = None,
                         apply_position_mult: bool = True) -> float | None:
    """Expected cost-controlled surplus value in USD for a prospect at continuous
    FV, given optional timing (current `age` + `eta_years` to debut). Below the
    Edwards cutover uses the direct dollar anchor; in (cutover, bridge) it
    linearly bridges anchor->fitted pipeline for continuity; above it uses the
    mixture pipeline. Timing reshapes the per-bucket trajectory (aging) and
    discounts the control window from projected debut (ETA gap).

    `position` ALWAYS drives the pitcher role-outcome layer (SP/RP/generic curve
    selection). `apply_position_mult=False` gates ONLY the (default-off) market-
    scarcity $ multiplier -- it does NOT discard the role tag."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f):
        return None
    role = _role_key(is_pitcher)
    debut_age, eta_eff = _resolve_timing(age, eta_years)
    da, ee = _round_timing(debut_age, eta_eff)
    # Role-mixed effective per-bucket SVs (hitter path unchanged; pitcher blends
    # SP and bullpen-capped RP per bucket by P(reliever|bucket)).
    svs = _effective_bucket_sv(is_pitcher, position, da, ee)
    a = _config()["lowtier_anchor"]
    cutover = float(a["cutover_fv"])
    bridge_to = float(a["bridge_to_fv"])
    if f <= cutover:
        base = _lowtier_anchor_usd(f, role, ee)
    elif f < bridge_to:
        lo = _lowtier_anchor_usd(cutover, role, ee)
        hi = _pipeline_surplus_from_svs(bridge_to, is_pitcher, svs)
        t = (f - cutover) / (bridge_to - cutover)
        base = lo * (1 - t) + hi * t
    else:
        base = _pipeline_surplus_from_svs(f, is_pitcher, svs)
    if apply_position_mult:
        base *= position_multiplier(position)  # 1.0 unless market_scarcity enabled
    return max(0.0, base)


# =============================================================================
# Public valuation API  (preserved signatures; now backed by the mixture model)
# =============================================================================
def apply_calibration(predicted_mm: float | None, fv: float | None = None,
                      is_pitcher: bool | None = None) -> float | None:
    """Apply the empirical CALIBRATION correction (the Prompt F backtest's
    documented, reversible, versioned shrinkage layer) to a RAW predicted SV in
    $M. Reads config['calibration']; DEFAULT is identity (enabled: false) ->
    returns the prediction unchanged, so the model ships uncalibrated until a
    real-data backtest writes fitted params. method 'linear' => slope*x +
    intercept; 'isotonic' => monotone interpolation on fitted breakpoints. The
    backtest itself fits against RAW (uncalibrated) predictions to avoid
    circularity, so it reads expected_surplus_usd directly, not this."""
    if predicted_mm is None:
        return None
    cal = _config().get("calibration", {})
    if not cal.get("enabled"):
        return predicted_mm
    x = float(predicted_mm)
    if str(cal.get("method", "linear")).lower() == "isotonic":
        iso = cal.get("isotonic", {})
        xs = [float(v) for v in iso.get("x_mm", [])]
        ys = [float(v) for v in iso.get("y_mm", [])]
        if len(xs) >= 2 and len(xs) == len(ys):
            if x <= xs[0]:
                return ys[0]
            if x >= xs[-1]:
                return ys[-1]
            for i in range(len(xs) - 1):
                if xs[i] <= x <= xs[i + 1]:
                    span = xs[i + 1] - xs[i]
                    t = (x - xs[i]) / span if span else 0.0
                    return ys[i] * (1 - t) + ys[i + 1] * t
        return x  # malformed table -> identity
    lin = cal.get("linear", {})
    return float(lin.get("slope", 1.0)) * x + float(lin.get("intercept_mm", 0.0))


def surplus_value_mm(
    fv: float | None,
    is_pitcher: bool,
    position: str | None = None,
    *,
    window: tuple[int, ...] | None = None,
    apply_position_mult: bool = True,
    age: float | None = None,
    eta_years: float | None = None,
) -> float | None:
    """Expected 6yr cost-controlled surplus value in $M for a prospect at FV.

    Backed by the career-path mixture model: expected SV = sum over outcome
    buckets of P(bucket|FV) * bucket_surplus, where each bucket surplus is built
    season-by-season (tiered $/WAR market value minus performance-adaptive
    salary, discounted) and aggregated last.

    `position` selects the hitter/pitcher/SP/RP role-outcome curve; it applies NO
    $/position multiplier (WAR already contains a positional adjustment).
    `apply_position_mult` and `window` are retained for backward compatibility:
    window is ignored; apply_position_mult=False suppresses ONLY the (default-off)
    market-scarcity $ multiplier -- the role tag is still honored (so an RP stays
    on the capped relief curve). Returns None for missing/unparseable FV.
    """
    if fv is None:
        return None
    usd = expected_surplus_usd(fv, is_pitcher, position, age=age, eta_years=eta_years,
                               apply_position_mult=apply_position_mult)
    if usd is None:
        return None
    return round(apply_calibration(usd / 1e6, fv, is_pitcher), 1)


def dollars_per_fv(
    fv: float | None,
    is_pitcher: bool,
    position: str | None = None,
    *,
    window: tuple[int, ...] | None = None,
) -> float | None:
    """$M of cost-controlled surplus per FV-point (portfolio efficiency metric)."""
    if fv is None:
        return None
    try:
        f = float(fv)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(f) or f <= 0:
        return None
    sv = surplus_value_mm(fv, is_pitcher, position)
    if sv is None:
        return None
    return round(sv / f, 3)


# =============================================================================
# Surplus-value DISTRIBUTION  (Monte Carlo)  -- the standard output contract
# =============================================================================
# The mixture model already PRODUCES a distribution -- P(bucket|FV) over five
# bucket-level surpluses. Collapsing it to a single mean discards the risk
# structure that distinguishes a safe regular from a boom/bust lottery ticket.
# sv_distribution() exposes the whole thing as the contract every downstream
# consumer reports through.
def risk_adjusted_score(mean_mm: float, downside_mm: float, risk_lambda: float) -> float:
    """Risk-adjusted surplus: mean penalized by its downside shortfall.

        score = mean - lambda * (mean - downside)

    `downside` is a downside metric <= mean (e.g. the worst-quartile CVaR). At
    lambda = 0 the score IS the mean (so ranking by score == ranking by mean);
    at lambda > 0 a prospect with a worse (lower) downside is penalized more, so
    two prospects with the SAME mean but different downside rank differently."""
    return float(mean_mm) - float(risk_lambda) * (float(mean_mm) - float(downside_mm))


# =============================================================================
# Source-disagreement uncertainty (Prompt I): the SPREAD across scouting sources
# is a free uncertainty signal. Carry per-source FVs, turn their dispersion into
# an FV sampling SD, and widen the Prompt-E distribution WITHOUT moving the mean.
# =============================================================================
def aggregate_source_fvs(source_fvs, *, weights=None, scale_offsets=None) -> dict | None:
    """Aggregate per-source FV grades into a (consensus, dispersion) summary, with
    OPTIONAL per-source scale-normalization (some sources grade hotter) and
    accuracy-weighting (e.g. from a Prompt-F backtest). `source_fvs` is a dict
    {source_name: fv} or a plain iterable of FVs. Returns {consensus, dispersion
    (= the WEIGHTED population stddev), spread (= max-min of the normalized FVs),
    n} or None if no finite FV. Equal weight + no offset (the defaults) reproduce
    the simple mean / population-stddev that consensus.py already computes. Bad
    inputs (non-numeric, non-finite FV, a non-finite offset, non-positive or
    non-finite weight) are dropped, so a malformed source degrades, never poisons."""
    cfg = _config().get("source_disagreement", {})
    offs = scale_offsets if scale_offsets is not None else (cfg.get("source_scale_offsets") or {})
    wts = weights if weights is not None else (cfg.get("source_weights") or {})
    items = source_fvs.items() if isinstance(source_fvs, dict) else [(None, v) for v in source_fvs]
    xs, ws = [], []
    for name, fv in items:
        try:
            v = float(fv)
        except (TypeError, ValueError):
            continue
        if name is not None:
            v -= float(offs.get(name, 0.0) or 0.0)
        if not math.isfinite(v):                      # guards a bad FV AND a bad offset
            continue
        w = float(wts.get(name, 1.0)) if name is not None else 1.0
        if not math.isfinite(w) or w <= 0:
            continue
        xs.append(v)
        ws.append(w)
    if not xs:
        return None
    wsum = sum(ws)
    consensus = sum(w * x for w, x in zip(ws, xs)) / wsum
    var = sum(w * (x - consensus) ** 2 for w, x in zip(ws, xs)) / wsum
    return {"consensus": consensus, "dispersion": math.sqrt(max(0.0, var)),
            "spread": max(xs) - min(xs), "n": len(xs)}


def _source_fv_sd(dispersion, n_sources=None) -> float:
    """Map a source-disagreement dispersion statistic to an effective disagreement
    magnitude (in FV points) that drives the variance widening. `dispersion` is
    interpreted per config.dispersion_stat: a population stddev ('stddev' mode) or
    a max-min spread ('spread' mode); callers on the precomputed-scalar path must
    pass the matching stat (the source_fvs path picks it in _resolve_fv_sd). 0.0
    when disabled, too few sources, or dispersion missing / non-finite / <= 0."""
    cfg = _config().get("source_disagreement", {})
    if not cfg.get("enabled", True) or dispersion is None:
        return 0.0
    try:
        d = float(dispersion)
    except (TypeError, ValueError):
        return 0.0
    if not math.isfinite(d) or d <= 0:
        return 0.0
    if n_sources is not None and int(n_sources) < int(cfg.get("min_sources", 2)):
        return 0.0
    if str(cfg.get("dispersion_stat", "stddev")).lower() == "spread":
        sd = float(cfg.get("spread_to_sd", 0.5)) * d
    else:
        sd = float(cfg.get("fv_sd_per_stddev", 1.0)) * d
    return max(0.0, min(float(cfg.get("max_fv_sd", float("inf"))), sd))


def _resolve_fv_sd(fv_dispersion, source_fvs, n_sources):
    """Resolve the disagreement magnitude + the dispersion actually used. If raw
    per-source FVs are given, aggregate them (optionally normalized/weighted) and
    pick the configured stat (stddev or max-min spread); else use the precomputed
    dispersion (which the caller supplies in the configured stat). Returns
    (fv_sd, dispersion, n)."""
    if source_fvs is not None:
        agg = aggregate_source_fvs(source_fvs)
        if agg is None:
            return 0.0, None, 0
        spread_mode = str(_config().get("source_disagreement", {}).get("dispersion_stat", "stddev")).lower() == "spread"
        disp = agg["spread"] if spread_mode else agg["dispersion"]
        return _source_fv_sd(disp, agg["n"]), disp, agg["n"]
    return _source_fv_sd(fv_dispersion, n_sources), fv_dispersion, n_sources


def _sv_draws_mm(fv, is_pitcher, position, n, seed=None, age=None, eta_years=None, fv_sd=0.0):
    """Monte Carlo SV draws ($M): sample bucket ~ P(bucket|FV), then a
    mean-preserving within-bucket Gamma (bust = point mass at $0). The bucket
    means are scaled so the mixture mean equals the (anchor/timing-adjusted)
    expected surplus. Returns (draws_mm ndarray, probs, mean_usd) or
    (None, None, None) for bad FV. Shared by sv_distribution and sv_draws.

    `fv_sd` > 0 (Prompt I) adds SOURCE-DISAGREEMENT spread by inflating each
    within-bucket coefficient of variation in quadrature (cv_eff = sqrt(cv^2 +
    (k*fv_sd)^2)). The bucket PROBABILITIES (and hence each bucket mean and the
    mixture mean) are left at the consensus, so the distribution mean is EXACTLY
    unchanged while the outcome variance grows MONOTONICALLY with disagreement at
    every FV -- no FV-jitter mean-shift to fight, so no narrowing artifact. bust
    (mean $0) stays a $0 point mass under any cv. fv_sd = 0 reproduces the plain
    distribution exactly."""
    import numpy as np
    mean_usd = expected_surplus_usd(fv, is_pitcher, position, age=age, eta_years=eta_years)
    if mean_usd is None:
        return None, None, None
    cfg = _config().get("distribution", {})
    cv_map = cfg.get("within_bucket_cv", {})
    f = float(fv)
    debut_age, eta_eff = _resolve_timing(age, eta_years)
    da, ee = _round_timing(debut_age, eta_eff)
    probs = p_bucket_given_fv(f, is_pitcher)
    bucket_sv = list(_effective_bucket_sv(is_pitcher, position, da, ee))
    pipeline_mean = sum(p * s for p, s in zip(probs, bucket_sv))
    scale = (mean_usd / pipeline_mean) if pipeline_mean > 0 else 0.0
    eff_sv = [s * scale for s in bucket_sv]
    cvs = [float(cv_map.get(b, 0.0)) for b in _BUCKETS]
    fv_sd = float(fv_sd or 0.0)
    if fv_sd > 0:
        # Source disagreement -> incremental OUTCOME variance (Prompt I). Add a
        # common variance component (k*fv_sd)^2 to every bucket's squared cv, in
        # quadrature. Each bucket mean is preserved (Gamma is mean-preserving) and
        # bucket probabilities stay at consensus, so the mixture mean is untouched;
        # only the spread grows, monotonically and at every FV.
        k = float(_config().get("source_disagreement", {}).get("fv_sd_to_cv", 0.0))
        add2 = (k * fv_sd) ** 2
        cvs = [math.sqrt(c * c + add2) for c in cvs]
    base_seed = int(seed if seed is not None else cfg.get("seed", 1234567))
    rng = np.random.RandomState((base_seed + int(round(f * 100)) + (1 if is_pitcher else 0)) % (2 ** 32))
    p = np.asarray(probs, dtype=float)
    p = p / p.sum()
    bucket_idx = rng.choice(_N_BUCKETS, size=int(n), p=p)
    sv = np.empty(int(n), dtype=float)
    for b in range(_N_BUCKETS):
        mask = bucket_idx == b
        cnt = int(mask.sum())
        if cnt == 0:
            continue
        m = eff_sv[b]
        cv = cvs[b]
        if cv <= 0 or m <= 0:
            sv[mask] = max(0.0, m)
        else:
            sv[mask] = rng.gamma(1.0 / (cv * cv), m * cv * cv, size=cnt)
    # MEAN-PRESERVING re-center: pin the sample mean to the deterministic expected
    # SV (removing finite-sample MC drift -> mc_mean == mean). The bucket probs are
    # the consensus regardless of fv_sd, so there is NO systematic mean shift to
    # undo: the factor is ~1.0 and identical in spirit for plain and widened draws,
    # so it never shrinks the widening. bust stays $0 under multiplicative scaling.
    cur = float(sv.mean())
    if cur > 0:
        sv = sv * (mean_usd / cur)
    return sv / 1e6, probs, mean_usd


def sv_draws(fv, is_pitcher, position=None, *, draws=None, seed=None,
             age=None, eta_years=None, fv_dispersion=None, source_fvs=None, n_sources=None):
    """Raw Monte Carlo SV draws ($M, numpy array) for a prospect -- e.g. for the
    backtest's PIT / interval-coverage checks. None for bad FV. Source-disagreement
    spread (Prompt I) is applied when fv_dispersion / source_fvs is supplied."""
    cfg = _config().get("distribution", {})
    n = int(draws if draws is not None else cfg.get("monte_carlo_draws", 20000))
    fv_sd, _, _ = _resolve_fv_sd(fv_dispersion, source_fvs, n_sources)
    out, _, _ = _sv_draws_mm(fv, is_pitcher, position, n, seed=seed, age=age,
                             eta_years=eta_years, fv_sd=fv_sd)
    return out


def sv_distribution(
    fv: float | None,
    is_pitcher: bool,
    position: str | None = None,
    *,
    draws: int | None = None,
    threshold_mm: float | None = None,
    risk_lambda: float | None = None,
    seed: int | None = None,
    age: float | None = None,
    eta_years: float | None = None,
    fv_dispersion: float | None = None,
    source_fvs=None,
    n_sources: int | None = None,
) -> dict | None:
    """STANDARD OUTPUT CONTRACT -- the full surplus-value distribution for a
    prospect (not just its mean). Returns the `output` dict:

        mean                -- $M, the deterministic point-estimate SV (2 dp)
        percentiles         -- {"p5":.., "p50":.., "p95":..} in $M, monotone
        p_bust              -- P(career outcome = bust)
        p_above_threshold   -- P(SV > threshold_mm)
        downside_metric     -- CVaR over the worst `downside_quantile` ($M)
        risk_adjusted_score -- mean - lambda*(mean - downside_metric) ($M)
        std, mc_mean, draws, risk_aversion_lambda, threshold_mm  -- bookkeeping

    Monte Carlo: sample bucket ~ P(bucket|FV), then a within-bucket SV from a
    MEAN-PRESERVING Gamma (positive, right-skewed). The bucket means are first
    scaled so the mixture mean equals the (anchor-adjusted) expected surplus, so
    `mean` equals surplus_value_mm() up to rounding (this `mean` keeps 2 dp,
    surplus_value_mm rounds to 1) and the MC sample mean tracks it. Returns None
    for missing / unparseable / non-finite FV."""
    import numpy as np

    cfg = _config().get("distribution", {})
    n = int(draws if draws is not None else cfg.get("monte_carlo_draws", 20000))
    thr = float(threshold_mm if threshold_mm is not None else cfg.get("sv_threshold_mm", 50.0))
    lam = float(risk_lambda if risk_lambda is not None else cfg.get("risk_aversion_lambda", 0.0))
    pct_list = cfg.get("percentiles", [5, 10, 25, 50, 75, 90, 95])
    dq = float(cfg.get("downside_quantile", 0.25))

    fv_sd, dispersion, n_src = _resolve_fv_sd(fv_dispersion, source_fvs, n_sources)
    sv_mm, probs, mean_usd = _sv_draws_mm(fv, is_pitcher, position, n,
                                          seed=seed, age=age, eta_years=eta_years, fv_sd=fv_sd)
    if sv_mm is None:
        return None
    out = _dist_output(sv_mm, float(probs[_BUCKETS.index("bust")]), mean_usd / 1e6,
                       threshold_mm=thr, risk_lambda=lam, pct_list=pct_list, dq=dq)
    # Prompt I bookkeeping: the source-disagreement inputs that widened the spread
    # (0 / None -> the plain Prompt-E distribution). The reported `mean` is the
    # deterministic consensus SV regardless, so two prospects with the same
    # consensus FV but different spread share a mean and differ only in spread.
    out["fv_sd"] = round(float(fv_sd), 3)
    out["fv_dispersion"] = (round(float(dispersion), 3)
                            if dispersion is not None and fv_sd > 0 else None)
    if n_src is not None:
        out["n_sources"] = int(n_src)
    return out


def _dist_output(sv_mm, p_bust: float, mean_mm: float, *, threshold_mm: float,
                 risk_lambda: float, pct_list=None, dq=None) -> dict:
    """Build the STANDARD Prompt-E output dict from a draw array + the reported
    (exact) mean + the bust probability. Shared by sv_distribution and the
    debuted-player remaining piece so both report through the same contract."""
    import numpy as np
    cfg = _config().get("distribution", {})
    pct_list = pct_list if pct_list is not None else cfg.get("percentiles", [5, 10, 25, 50, 75, 90, 95])
    dq = float(dq if dq is not None else cfg.get("downside_quantile", 0.25))
    sv_mm = np.asarray(sv_mm, dtype=float)
    pcts = {f"p{int(pp)}": round(float(np.percentile(sv_mm, pp)), 2) for pp in pct_list}
    cutoff = float(np.quantile(sv_mm, dq))
    worst = sv_mm[sv_mm <= cutoff]
    downside = float(worst.mean()) if worst.size else float(sv_mm.min())
    mean_mm = round(float(mean_mm), 2)
    return {
        "mean": mean_mm,
        "percentiles": pcts,
        "p_bust": round(float(p_bust), 4),
        "p_above_threshold": round(float((sv_mm > threshold_mm).mean()), 4),
        "downside_metric": round(downside, 2),
        "risk_adjusted_score": round(risk_adjusted_score(mean_mm, downside, risk_lambda), 2),
        "std": round(float(sv_mm.std()), 2),
        "mc_mean": round(float(sv_mm.mean()), 2),
        "draws": int(len(sv_mm)),
        "risk_aversion_lambda": float(risk_lambda),
        "threshold_mm": float(threshold_mm),
    }


