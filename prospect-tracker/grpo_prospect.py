    import sys, argparse
    logging.basicConfig(level=logging.INFO, stream=sys.stderr)
    ap = argparse.ArgumentParser(description="GRPO prospect breakout scorer")
    ap.add_argument("--retrain",    action="store_true", help="Retrain model")
