_LEVEL_IDX = {"CPX": 0, "DSL": 0, "ACL": 0, "FCL": 0,
               "A": 1, "A+": 2, "AA": 3, "AAA": 4, "MLB": 5}
_POS_BUCKET = {
    "C": 0,
    "SS": 1, "CF": 2,
    "2B": 3, "3B": 3,
    "LF": 4, "RF": 4, "1B": 4, "OF": 4, "DH": 4,
    "SP": 5, "RHP": 5, "LHP": 5, "P": 5,
    # SIRP / MIRP added 2026-07-30. They are the site's primary relief designations
    # (FanGraphs publishes them, not bare "RP") and they were MISSING, so the
    # `.get(pos, 4)` fallback below fed 310 relief prospects to the policy in bucket 4,
    # the LF/RF/1B/OF/DH corner-BAT bucket. A reliever scored as a corner bat is the
    # worst available miss in this map: bucket 4 is the low-defensive-value hitter slot.
    "RP": 6, "CL": 6, "SIRP": 6, "MIRP": 6,
}
# Multi-position labels ("SS/3B", "C/1B") and two-way ("TWP") also fell through to the
# corner-bat default. Resolve on the FIRST listed slot, which is how every other consumer
# reads these, and fall back to a NEUTRAL bucket rather than a hitter one so an unknown
# label can never be silently priced as a specific kind of player.
_POS_BUCKET_DEFAULT = 3          # neutral infield slot, not the corner-bat bucket


def _pos_bucket(pos) -> int:
    """Bucket index for a position label, tolerant of the compound and relief forms the
    live board actually carries. Measured 2026-07-30: 356 of the served rows used a label
    absent from _POS_BUCKET, 310 of them relief designations."""
    if not pos:
        return _POS_BUCKET_DEFAULT
    p = str(pos).strip().upper()
    if p in _POS_BUCKET:
        return _POS_BUCKET[p]
    if p == "TWP":               # two-way: score on the bat, which is the longer career
        return _POS_BUCKET_DEFAULT
    head = p.split("/")[0].strip()
    return _POS_BUCKET.get(head, _POS_BUCKET_DEFAULT)
# Approximate level baselines for relative features
_LEVEL_BASELINES = {
    # (k_pct, bb_pct, avg_ev)
    "CPX": (28.0, 9.0, 80.0), "DSL": (28.0, 9.0, 80.0),
    "A":   (25.0, 8.0, 82.0),
    "A+":  (24.0, 8.5, 83.0),
    "AA":  (23.5, 8.0, 84.5),
    "AAA": (23.0, 8.8, 86.0),
    "MLB": (22.5, 8.5, 88.5),
}


def _safe(val: Any, default: float = 0.0) -> float:
    try:
        v = float(val)
        return v if math.isfinite(v) else default
    except (TypeError, ValueError):
        return default


def _pos_primary(pos: str | None) -> str:
    if not pos:
        return "OF"
    return str(pos).upper().strip().split("/")[0].strip()


def extract_features(player: dict, level_norms: dict | None = None) -> dict:
    """Extract the feature vector used by the GRPO policy.

    Works for both active prospects and historical players.
    Returns a flat dict of numeric features (None for unavailable).
    """
    pos   = _pos_primary(player.get("position"))
    level = (player.get("current_level") or "CPX").upper().replace("COMPLEX", "CPX")
    age   = _safe(player.get("age"), 20.0)
    fv    = _safe(player.get("fv_close"), 35.0)

    # Age vs level differential (negative = young for level)
    avl = player.get("age_vs_level") or {}
    avl_diff = _safe(avl.get("diff"), 0.0)

    # Statline rates
    sl = player.get("statline") or {}
    k_pct  = _safe(sl.get("k_pct"))
    bb_pct = _safe(sl.get("bb_pct"))

    # Zone metrics
    zm = player.get("zone_metrics") or {}
    o_swing = _safe(zm.get("o_swing_pct") or zm.get("actual_o_swing_pct"), None)

    # Statcast contact quality
    sc  = player.get("statcast_metrics") or {}
    cq  = (sc or {}).get("contact_quality") or {}
    # Also check level splits for the player's current level
    for split in ((sc or {}).get("level_splits") or []):
        if (split.get("level") or "").upper() == level:
            cq = split.get("contact_quality") or cq
            break
    max_ev   = _safe(cq.get("max_ev") or cq.get("p90_ev"))
    avg_ev   = _safe(cq.get("avg_ev"))
    xwoba    = _safe(cq.get("xwoba_est") or cq.get("xwoba"))
    barrel   = _safe(cq.get("barrel_pct"))
    hard_hit = _safe(cq.get("hard_hit_pct"))

    # Pedigree: log-scale bonus → [0,1]
    acq = player.get("acquisition") or {}
    bonus = _safe(acq.get("bonus_usd"), 0)
    pedigree = min(1.0, math.log10(max(1, bonus) / 10_000) / 5.0) if bonus > 0 else 0.0

    # Level-relative approach metrics
    bl = _LEVEL_BASELINES.get(level, _LEVEL_BASELINES["A"])
    k_rel  = k_pct  - bl[0] if k_pct  else None   # negative = below avg = good
    bb_rel = bb_pct - bl[1] if bb_pct else None    # positive = above avg = good
    ev_rel = avg_ev - bl[2] if avg_ev else None    # positive = above avg = good

    # MLB career data (for graduated players used in training)
    cw    = player.get("career_war") or {}
    war_seasons = int(cw.get("war_seasons_count") or 0)
    war_per_yr  = _safe(cw.get("war_per_yr"))

    return {
        "age":           age,
        "age_vs_level":  avl_diff,
        "level_idx":     _LEVEL_IDX.get(level, 0),
        "pos_bucket":    _pos_bucket(pos),
        "fv":            fv,
        "k_pct":         k_pct,
        "k_pct_rel":     k_rel,
        "bb_pct":        bb_pct,
        "bb_pct_rel":    bb_rel,
        "o_swing_pct":   o_swing,
        "max_ev":        max_ev if max_ev else avg_ev,   # fallback to avg
        "avg_ev":        avg_ev,
        "ev_rel":        ev_rel,
        "xwoba_est":     xwoba,
        "barrel_pct":    barrel,
        "hard_hit_pct":  hard_hit,
        "pedigree":      pedigree,
        "bonus_usd":     bonus,
        "war_seasons":   war_seasons,
        "war_per_yr":    war_per_yr,   # outcome feature (only for training)
    }


def assign_group(player: dict, features: dict | None = None) -> str:
    """Assign a player to a GRPO comparison group.

    Groups are defined by:  position × level × age_tier × raw_power_tier

    The group key is the primary axis for within-group relative scoring.
    Players with no group peers get lower confidence scores.
    """
    if features is None:
        features = extract_features(player)

    pos   = _pos_primary(player.get("position"))
    level = (player.get("current_level") or "CPX").upper().replace("COMPLEX", "CPX")

    # Age tier
    diff = features.get("age_vs_level") or 0
    if diff <= -2.0:
        age_tier = "very_young"
    elif diff <= -0.5:
        age_tier = "young"
    elif diff < 0.5:
        age_tier = "neutral"
    elif diff < 2.0:
        age_tier = "old"
    else:
        age_tier = "too_old"

    # Raw power tier from max_ev (the Frias signal)
    max_ev = features.get("max_ev") or 0
    if max_ev >= 110:
        power_tier = "elite"
    elif max_ev >= 100:
        power_tier = "good"
    elif max_ev > 0:
        power_tier = "avg"
    else:
        power_tier = "unknown"   # no EV data

    # Coarsen level for grouping (DSL/ACL/FCL → CPX)
    lvl_coarse = "CPX" if level in ("DSL", "ACL", "FCL", "CPX") else level

    return f"{pos}|{lvl_coarse}|{age_tier}|{power_tier}"


