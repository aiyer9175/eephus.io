"""
grpo_prospect.py — Group Relative Policy Optimization for prospect valuation.

ARCHITECTURE
============

Standard supervised learning asks: "Will this player break out?" — which
requires clean absolute labels and struggles with class imbalance and
cross-position differences.

GRPO asks instead: "Within this group of similar prospects, which one is
most likely to break out?" — a relative ranking that avoids absolute
thresholds and naturally handles rare events.

Core components:

  GROUPS      Players clustered by: position_bucket × level × age_tier × power_tier
              e.g. "C|CPX|neutral|elite" — all CPX catchers in the same age/EV range

  POLICY      f(player_features) → breakout_score ∈ [0,1]
              Lightweight GBM trained with group-relative ranking loss

  REWARD      Verifiable: actual career WAR from graduates.json, or FV delta
              from metric_snapshots when historical depth is available.
              Currently uses career WAR / first-3-season MLB production.

  GRPO LOOP   For each group of K similar players:
                scores    = [policy(pᵢ) for i in 1..k]
                rewards   = [career_war(pᵢ)]            ← verifiable
                baseline  = mean(rewards)               ← group-relative
                advantages = (rewards - baseline) / std ← normalize
                loss       = -Σ log_prob(score) × advantage
                             no critic network needed

FEATURES (per player)
  age_vs_level_diff   how many years younger than level baseline
  level_idx           0=CPX 1=A 2=A+ 3=AA 4=AAA
  position_bucket     0=C 1=SS 2=CF 3=2B/3B 4=corner 5=SP 6=RP
  fv                  consensus FV grade (20-80)
  k_pct_rel           K% minus level average (negative = below avg = good)
  bb_pct_rel          BB% minus level average
  o_swing_pct         chase rate (absolute)
  max_ev              peak exit velocity — the Frias signal
  avg_ev              average exit velocity
  xwoba_est           contact quality index
  barrel_pct          power expression rate
  hard_hit_pct        hard contact percentage
  pedigree            log-scale signing bonus → [0,1]
  war_seasons         MLB seasons of data (0 for pre-debut)

BREAKOUT DETECTION USE CASE — Alexander Frias
  Frias: age 18, CPX, unranked (provisional FV=35), 117mph max_ev
  Group: CPX | age 17-19 | power_tier=elite (max_ev ≥ 110)
  GRPO learns from historical comps in this group:
    → who in this bucket had good MLB outcomes vs. who didn't
    → max_ev at age 18 is among the strongest predictors within the group
  Output: breakout_score → adjusts Frias's FV prior upward from 35
  Trade value impact: provisional $3M → GRPO-informed $10-18M

INTEGRATION WITH TRADE VALUES
  grpo_scores.json (generated by export_grpo_scores) has per-player:
    breakout_score:  [0,1] probability this player outperforms their current FV
    fv_adj:          recommended FV adjustment (positive = upgrade)
    group:           the comparison group key
    group_rank:      rank within group (1 = best in group)
    comps:           top similar historical players
  bayes_trade_value reads this to lift/lower the FV prior before the
  Kalman update, effectively giving unranked / underranked players a
  more informed starting point.

PUBLIC SIDECAR
  grpo_scores.json is model internals and is excluded from the webroot
  (deploy/data_exclude.txt). export_grpo_scores therefore also emits
  data/grpo_public.json - a slim projection (see build_public_sidecar)
  carrying only what the Trade Machine group panel renders. That file
  SHIPS; the full file never does.
"""

