def _feature_vector(feats: dict) -> list[float]:
    """Convert feature dict to numeric vector for the ML policy."""
    return [
        feats.get("age") or 20.0,
        feats.get("age_vs_level") or 0.0,
        feats.get("level_idx") or 0.0,
        float(feats.get("pos_bucket") or 4),
        feats.get("fv") or 35.0,
        feats.get("k_pct") or 24.0,
        feats.get("k_pct_rel") or 0.0,
        feats.get("bb_pct") or 8.0,
        feats.get("bb_pct_rel") or 0.0,
        feats.get("o_swing_pct") or 30.0,
        feats.get("max_ev") or 83.0,
        feats.get("avg_ev") or 83.0,
        feats.get("ev_rel") or 0.0,
        feats.get("xwoba_est") or 0.320,
        feats.get("barrel_pct") or 6.0,
        feats.get("hard_hit_pct") or 38.0,
        feats.get("pedigree") or 0.0,
        math.log10(max(1, feats.get("bonus_usd") or 1)) / 7.0,
    ]


def _training_fingerprint(dataset: list[dict]) -> str:
    """Stable content hash of the GRPO training data.

    train_grpo_policy is deterministic (HistGradientBoostingRegressor with a
    fixed random_state), so an identical training set yields a byte-identical
    fitted model. The fingerprint lets a caller skip a redundant retrain when the
    data has not changed (the monthly run trains GRPO in its own export, then the
    chained run_daily -> rebuild_only retrains again on the exact same graduate
    set) - a provably output-neutral optimization (the scores are unchanged
    because the model is). Hashing the dataset (which fully determines the fitted
    X / y) captures every upstream input, so no training signal can be missed."""
    blob = json.dumps(dataset, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def _fingerprint_path(model_path: Path) -> Path:
    return model_path.with_suffix(".fingerprint")


def _read_fingerprint(fp_path: Path) -> str | None:
    try:
        return fp_path.read_text(encoding="utf-8").strip()
    except OSError:
        return None


def train_grpo_policy(dataset: list[dict],
                       model_path: Path | None = None) -> Any:
    """Train the GRPO policy using group-relative ranking.

    Uses HistGradientBoostingRegressor as the policy backbone.
    The GRPO insight: each player is evaluated relative to their group peers,
    not against an absolute threshold. This handles cross-position and
    cross-level differences naturally.

    Within each group:
      - Players are ranked by outcome
      - The policy learns features that predict within-group rank
      - Loss = group-relative ranking error (not absolute MSE)

    Returns a fitted sklearn model.
    """
    try:
        from sklearn.ensemble import HistGradientBoostingRegressor
        import numpy as np
    except ImportError:
        _log.error("grpo: sklearn not installed; pip install scikit-learn")
        return None

    if not dataset:
        _log.warning("grpo: empty training dataset")
        return None

    # Build training arrays
    X_rows, y_rows = [], []
    for row in dataset:
        X_rows.append(_feature_vector(row["features"]))
        y_rows.append(row["outcome"])

    X = np.array(X_rows, dtype=float)
    y = np.array(y_rows, dtype=float)

    # GRPO: compute group-relative labels
    # Instead of using raw outcome, use the within-group percentile rank.
    # A player who is the best in their group gets y=1.0; worst gets y=0.0.
    # This is the core GRPO idea: no absolute reference, only relative comparison.
    groups = [r["group"] for r in dataset]
    group_indices: dict[str, list[int]] = defaultdict(list)
    for i, g in enumerate(groups):
        group_indices[g].append(i)

    y_grpo = np.zeros(len(y))
    for group, idxs in group_indices.items():
        if len(idxs) == 1:
            y_grpo[idxs[0]] = 0.5   # only member of group → neutral score
            continue
        vals = y[idxs]
        mn, mx = vals.min(), vals.max()
        span = mx - mn
        for i, idx in enumerate(idxs):
            if span < 1e-8:
                y_grpo[idx] = 0.5
            else:
                y_grpo[idx] = (y[idx] - mn) / span   # [0, 1] within group

    # Train the policy to predict within-group rank
    model = HistGradientBoostingRegressor(
        max_iter=400,
        max_depth=5,
        learning_rate=0.05,
        min_samples_leaf=3,
        random_state=42,
    )
    model.fit(X, y_grpo)

    _log.info("grpo: trained on %d players, %d groups",
              len(dataset), len(group_indices))

    if model_path:
        model_path.parent.mkdir(parents=True, exist_ok=True)
        with open(model_path, "wb") as f:
            pickle.dump(model, f, protocol=pickle.HIGHEST_PROTOCOL)
        # Stamp the training fingerprint alongside the model so a later run can
        # detect unchanged training data and skip the redundant retrain.
        try:
            _fingerprint_path(model_path).write_text(
                _training_fingerprint(dataset), encoding="utf-8")
        except OSError:
            pass
        _log.info("grpo: model saved → %s", model_path)

    return model


def load_grpo_model(model_path: Path | None = None) -> Any | None:
    """Load a previously trained GRPO model from disk."""
    path = model_path or (_HERE / "data" / "grpo_model.pkl")
    if not path.exists():
        return None
    try:
        with open(path, "rb") as f:
            return pickle.load(f)
    except Exception as e:
        _log.warning("grpo: could not load model: %s", e)
        return None


