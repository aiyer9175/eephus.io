    ap.add_argument("--top",  type=int, default=20, help="Show top N breakout candidates")
    args = ap.parse_args()

    ts    = json.loads(Path("data/timeseries.json").read_text(encoding="utf-8"))
    gpath = Path("data/graduates.json")
