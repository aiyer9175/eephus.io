def _outcome_label(player: dict, features: dict) -> float | None:
    """Convert a graduated player's career data into a training label.

    Returns a continuous outcome score:
      > 0.7  elite MLB contributor (3+ WAR/yr)
      > 0.5  solid MLB starter (1.5-3 WAR/yr)
      > 0.3  bench/role player (0.5-1.5 WAR/yr)
      > 0.1  cup of coffee (< 0.5 WAR/yr)
        0.0  never reached MLB impact / bust
    """
    war_yr    = features.get("war_per_yr") or 0.0
    war_seasons = features.get("war_seasons") or 0

    if war_seasons == 0:
        return 0.05   # debuted but minimal impact
    if war_yr >= 3.0:
        return 0.85
    if war_yr >= 1.5:
        return 0.65
    if war_yr >= 0.5:
        return 0.40
    if war_yr > 0:
        return 0.20
    return 0.05


def build_training_dataset(graduates: list[dict],
                            level_norms: dict | None = None) -> list[dict]:
    """Build the GRPO training dataset from graduated players.

    Each row: features at graduation time + outcome label.
    The 'group' key enables within-group comparison during training.
    """
    rows = []
    for p in graduates:
        try:
            feats   = extract_features(p, level_norms)
            outcome = _outcome_label(p, feats)
            if outcome is None:
                continue
            group   = assign_group(p, feats)
            rows.append({
                "player_key":   p.get("player_key"),
                "player_name":  p.get("player_name"),
                "group":        group,
                "outcome":      outcome,
                "features":     feats,
            })
        except Exception:
            _log.debug("grpo: feature extraction failed for %s", p.get("player_key"))
    return rows


